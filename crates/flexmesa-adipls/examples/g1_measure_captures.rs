//! Package G1 measurement driver: replay every per-model ADIPLS call that
//! MESA 26.4.1 made in `astero/{example_astero,fast_scan_grid,fast_simplex}`
//! (the A0 glue-tap captures `<case>/a0tap/{calls.tsv,modes.tsv,*.amdl.bin}`
//! under `FLEXMESA_ADIPLS_CAPTURES`) through [`AdiplsSolver::run_call`] and
//! count, per call and per quantity, the records that match MESA at 0 ULP.
//!
//! The replay is the one of `tests/adipls_a2b_modes_parity_test.rs` (same
//! pruned `adipls.c.pruned.in`, same control setup, same AMDL reader that
//! loads only rows 1 to 5 and 10 of `aa`), but it does not stop at the first
//! difference. It prints one JSON object per case on stdout;
//! `scripts/audit/gyre_adipls_measurement.py` aggregates them.
//!
//! When `FLEXMESA_ADIPLS_CAPTURES` is unset or a case directory is missing,
//! the case is reported with `"status": "captures pending"` (the captures are
//! regenerated by `benchmarks/fortran_mesa/adipls_oracles/run_mesa_captures.sh`
//! and are not part of any fetchable bundle).
//!
//! Usage: `cargo run --profile ci -p flexmesa-adipls --example
//! g1_measure_captures [-- <case> ...]` (default: the three cases above).

#![forbid(unsafe_code)]
