const DEFAULT_CASES: [&str; 3] =
    ["example_astero", "fast_scan_grid", "fast_simplex"];

/// Quantity groups: `(name, is_integer_or_raw_bits)`.
const QUANTITIES: [(&str, bool); 8] = [
    ("degree", true),
    ("order", true),
    ("em", true),
    ("cyclic_freq_uHz", false),
    ("inertia", false),
    ("obs_st(1:10)", false),
    ("csummm(1:38)", false),
    ("csummm(39:50)", true),
];

struct CallRow {
    call_id: usize,
    nn: usize,
    amdl_file: String,
    el: f64,
    els1: f64,
    dels: f64,
    sig1: f64,
    sig2: f64,
    dfsig: f64,
    nsel: i32,
    itrsig: i32,
    nsig: i32,
    iscan: i32,
    irotkr: i32,
    nprtkr: i32,
    igm1kr: i32,
    npgmkr: i32,
}

struct ExpectedMode {
    call_id: usize,
    k: usize,
    ints: [i32; 3],
    freq_bits: u64,
    inertia_bits: u64,
    obs_bits: [u64; 10],
    csum_bits: [u64; 50],
}

fn hex_u64(h: &str) -> u64 {
    u64::from_str_radix(h.trim(), 16)
        .unwrap_or_else(|e| panic!("bad hex `{h}`: {e}"))
}

fn hex_f64(h: &str) -> f64 {
    f64::from_bits(hex_u64(h))
}

fn read_calls(path: &Path) -> Vec<CallRow> {
    let text = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let mut out = Vec::new();
    for (i, line) in text.lines().enumerate() {
        if i == 0 || line.trim().is_empty() {
            continue;
        }
        let c: Vec<&str> = line.split('\t').collect();
        assert!(
            c.len() >= 34,
            "{} row {}: {} cols",
            path.display(),
            i + 1,
            c.len()
        );
        let pi = |k: usize| -> i32 { c[k].trim().parse().expect("i32") };
        out.push(CallRow {
            call_id: c[0].trim().parse().expect("call_id"),
            nn: c[4].trim().parse().expect("nn"),
            amdl_file: c[5].trim().to_owned(),
            el: hex_f64(c[10]),
            els1: hex_f64(c[11]),
            dels: hex_f64(c[12]),
            sig1: hex_f64(c[15]),
            sig2: hex_f64(c[16]),
            dfsig: hex_f64(c[17]),
            nsel: pi(22),
            itrsig: pi(25),
            nsig: pi(26),
            iscan: pi(29),
            irotkr: pi(30),
            nprtkr: pi(31),
            igm1kr: pi(32),
            npgmkr: pi(33),
        });
    }
    out
}

fn read_modes(path: &Path) -> Vec<ExpectedMode> {
    let text = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let mut out = Vec::new();
    for (i, line) in text.lines().enumerate() {
        if i == 0 || line.trim().is_empty() {
            continue;
        }
        let p: Vec<&str> = line.split('\t').collect();
        assert_eq!(p.len(), 10, "{} row {}", path.display(), i + 1);
        out.push(ExpectedMode {
            call_id: p[0].trim().parse().unwrap(),
            k: p[1].trim().parse().unwrap(),
            ints: [
                p[3].trim().parse().unwrap(),
                p[4].trim().parse().unwrap(),
                p[5].trim().parse().unwrap(),
            ],
            freq_bits: hex_u64(p[6]),
            inertia_bits: hex_u64(p[7]),
            obs_bits: p[8]
                .split_whitespace()
                .map(hex_u64)
                .collect::<Vec<_>>()
                .try_into()
                .expect("10 obs_st words"),
            csum_bits: p[9]
                .split_whitespace()
                .map(hex_u64)
                .collect::<Vec<_>>()
                .try_into()
                .expect("50 csummm words"),
        });
    }
    out
}

/// Same reader as the A2b test: rows 1 to 5 and 10 of `aa` only (`#479`).
fn read_amdl(path: &Path, nn_expected: usize) -> ([f64; 8], Vec<f64>, AmdlAa) {
    let mut r = BufReader::new(
        File::open(path)
            .unwrap_or_else(|e| panic!("open {}: {e}", path.display())),
    );
    let mut head = [0_u8; 8];
    r.read_exact(&mut head).expect("amdl header");
    let nn =
        usize::try_from(i32::from_le_bytes(head[0..4].try_into().unwrap()))
            .expect("nn");
    let iaa =
        usize::try_from(i32::from_le_bytes(head[4..8].try_into().unwrap()))
            .expect("iaa");
    assert_eq!(nn, nn_expected, "{}: nn", path.display());
    assert_eq!(iaa, 10, "{}: iaa", path.display());
    let mut buf = Vec::new();
    r.read_to_end(&mut buf).expect("amdl payload");
    assert_eq!(
        buf.len(),
        (8 + nn + iaa * nn) * 8,
        "{}: size",
        path.display()
    );
    let f = |i: usize| {
        f64::from_le_bytes(buf[i * 8..i * 8 + 8].try_into().unwrap())
    };
    let mut data = [0.0; 8];
    for (i, d) in data.iter_mut().enumerate() {
        *d = f(i);
    }
    let x: Vec<f64> = (0..nn).map(|i| f(8 + i)).collect();
    let base = 8 + nn;
    let mut aa = AmdlAa::new_unset(nn);
    for row in 0..5 {
        let v: Vec<f64> = (0..nn).map(|z| f(base + z * iaa + row)).collect();
        aa.set_row(row + 1, v).expect("set row");
    }
    let v: Vec<f64> = (0..nn).map(|z| f(base + z * iaa + 9)).collect();
    aa.set_row(10, v).expect("set row 10");
    (data, x, aa)
}

fn ulp_distance(a: u64, b: u64) -> u64 {
    fn ordered(bits: u64) -> i64 {
        let s = bits.cast_signed();
        if s < 0 {
            i64::MIN - s
        } else {
            s
        }
    }
    ordered(a).abs_diff(ordered(b))
}

#[derive(Default)]
struct QStat {
    compared: usize,
    zero_ulp: usize,
    ulps: Vec<u64>,
    first: Option<String>,
}

fn json_str(s: &str) -> String {
    let mut o = String::from("\"");
    for ch in s.chars() {
        match ch {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            c if (c as u32) < 0x20 => {
                let _ = write!(o, "\\u{:04x}", c as u32);
            }
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn pending(case: &str, why: &str) -> String {
    format!(
        "{{\"case\":{},\"code\":\"ADIPLS\",\"status\":\"captures pending\",\
         \"reason\":{}}}",
        json_str(&format!("astero/{case}")),
        json_str(why)
    )
}

fn measure_case(
    root: &Path,
    case: &str,
    solver: &AdiplsSolver,
    base: &AdiplsControlState,
) -> String {
    let dir = root.join(case).join("a0tap");
    if !dir.join("calls.tsv").is_file() || !dir.join("modes.tsv").is_file() {
        return pending(
            case,
            "no <case>/a0tap/{calls,modes}.tsv under FLEXMESA_ADIPLS_CAPTURES",
        );
    }
    let calls = read_calls(&dir.join("calls.tsv"));
    let want = read_modes(&dir.join("modes.tsv"));
    let mut stats: Vec<QStat> =
        QUANTITIES.iter().map(|_| QStat::default()).collect();
    let mut calls_identical = 0usize;
    let mut calls_count_mismatch = 0usize;
    let mut calls_error = 0usize;
    let mut first_call: Option<String> = None;
    let mut n_got = 0usize;
    let mut cached = String::new();
    let mut model: Option<([f64; 8], Vec<f64>, AmdlAa)> = None;

    for row in &calls {
        if row.amdl_file != cached {
            model = Some(read_amdl(&dir.join(&row.amdl_file), row.nn));
            cached.clone_from(&row.amdl_file);
        }
        let (data, x, aa) = model.as_ref().unwrap();
        let el = row.el as i32;
        assert_eq!(f64::from(el).to_bits(), row.el.to_bits());
        let mut controls = *base;
        set_adipls_controls(
            &mut controls,
            el,
            row.nsel,
            row.els1,
            row.dels,
            row.itrsig,
            row.iscan,
            row.sig1,
            row.sig2,
            row.dfsig,
            row.nsig,
            row.irotkr,
            row.nprtkr,
            row.igm1kr,
            row.npgmkr,
        );
        let exp: Vec<&ExpectedMode> =
            want.iter().filter(|m| m.call_id == row.call_id).collect();
        let tag = format!("call {}", row.call_id);
        let res = match solver.run_call(&controls, x, aa, *data) {
            Ok(r) => r,
            Err(e) => {
                calls_error += 1;
                first_call.get_or_insert_with(|| {
                    format!("{tag}: run_call error {e}")
                });
                continue;
            }
        };
        let got = &res.modes.records;
        n_got += got.len();
        let mut identical = got.len() == exp.len();
        if got.len() != exp.len() {
            calls_count_mismatch += 1;
            first_call.get_or_insert_with(|| {
                format!("{tag}: {} modes, MESA {}", got.len(), exp.len())
            });
        }
        for (g, w) in got.iter().zip(&exp) {
            let k = w.k;
            let mut pairs: Vec<(usize, String, u64, u64, bool)> = vec![
                (0, "degree".into(), g.el as u64, w.ints[0] as u64, true),
                (1, "order".into(), g.order as u64, w.ints[1] as u64, true),
                (2, "em".into(), g.em as u64, w.ints[2] as u64, true),
                (
                    3,
                    "cyclic_freq_uHz".into(),
                    g.cyclic_freq_uhz.to_bits(),
                    w.freq_bits,
                    false,
                ),
                (
                    4,
                    "inertia".into(),
                    g.inertia.to_bits(),
                    w.inertia_bits,
                    false,
                ),
            ];
            for (i, (&a, &b)) in
                g.obs_st.as_array().iter().zip(&w.obs_bits).enumerate()
            {
                pairs.push((
                    5,
                    format!("obs_st({})", i + 1),
                    a.to_bits(),
                    b,
                    false,
                ));
            }
            for (i, (&a, &b)) in
                g.csummm.as_bits().iter().zip(&w.csum_bits).enumerate()
            {
                let q = if i < 38 { 6 } else { 7 };
                pairs.push((q, format!("csummm({})", i + 1), a, b, q == 7));
            }
            for (q, name, a, b, raw) in pairs {
                let st = &mut stats[q];
                st.compared += 1;
                if a == b {
                    st.zero_ulp += 1;
                    continue;
                }
                identical = false;
                let d = if q <= 2 {
                    (a as i64).abs_diff(b as i64)
                } else if raw {
                    1
                } else {
                    ulp_distance(a, b)
                };
                st.ulps.push(d);
                let msg = if q <= 2 {
                    format!(
                        "{tag} mode {k}: {name} {} vs MESA {}",
                        a as i32, b as i32
                    )
                } else if raw {
                    format!(
                        "{tag} mode {k}: {name} 0x{a:016x} vs MESA 0x{b:016x}"
                    )
                } else {
                    format!(
                        "{tag} mode {k}: {name} {:e} (0x{a:016x}) vs MESA {:e} \
                         (0x{b:016x}), {d} ULP",
                        f64::from_bits(a),
                        f64::from_bits(b)
                    )
                };
                st.first.get_or_insert_with(|| msg.clone());
                first_call.get_or_insert(msg);
            }
        }
        if identical {
            calls_identical += 1;
        }
    }

    let mut q_json = Vec::new();
    for ((name, is_int), st) in QUANTITIES.iter().zip(&mut stats) {
        st.ulps.sort_unstable();
        let max = st.ulps.last().copied().unwrap_or(0);
        let median = if st.ulps.is_empty() {
            0
        } else {
            st.ulps[st.ulps.len() / 2]
        };
        q_json.push(format!(
            "{{\"name\":{},\"integer\":{is_int},\"compared\":{},\
             \"zero_ulp\":{},\"differ\":{},\"max_ulp\":{max},\
             \"median_ulp_of_differing\":{median},\"first_difference\":{}}}",
            json_str(name),
            st.compared,
            st.zero_ulp,
            st.ulps.len(),
            st.first.as_deref().map_or_else(|| "null".into(), json_str)
        ));
    }
    format!(
        "{{\"case\":{},\"code\":\"ADIPLS\",\"status\":\"measured\",\
         \"calls\":{},\"calls_identical\":{calls_identical},\
         \"calls_mode_count_mismatch\":{calls_count_mismatch},\
         \"calls_error\":{calls_error},\"modes_mesa\":{},\
         \"modes_flexmesa\":{n_got},\"first_differing_call\":{},\
         \"quantities\":[{}]}}",
        json_str(&format!("astero/{case}")),
        calls.len(),
        want.len(),
        first_call
            .as_deref()
            .map_or_else(|| "null".into(), json_str),
        q_json.join(",")
    )
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let cases: Vec<String> = if args.is_empty() {
        DEFAULT_CASES.iter().map(|s| (*s).to_string()).collect()
    } else {
        args
    };
    let root: Option<PathBuf> = std::env::var("FLEXMESA_ADIPLS_CAPTURES")
        .ok()
        .map(|s| s.trim().to_owned())
        .filter(|s| !s.is_empty())
        .map(PathBuf::from);
    let Some(root) = root else {
        for c in &cases {
            println!("{}", pending(c, "FLEXMESA_ADIPLS_CAPTURES unset"));
        }
        return;
    };
    let input = parse_adipls_pruned_in(ADIPLS_PRUNED_IN).expect("pruned in");
    let base = AdiplsControlState::from_input(&input);
    let solver = AdiplsSolver::new(input);
    for c in &cases {
        println!("{}", measure_case(&root, c, &solver, &base));
    }
}
