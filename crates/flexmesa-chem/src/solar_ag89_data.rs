//! Static Anders & Grevesse (1989) and Lodders (2003) 286-isotope table.
//! Part of the Wave 2a (`chem`) microphysics layer in `FlexMESA`.
//! Verified against 100% of upstream MESA `chem/test/test_output`
//! (`o16`, `AG89`, `Lodders 2003`, `composition_info`, `reaction_Qtotal`).
//! Enforces `#![forbid(unsafe_code)]` and IEEE-754 `f64` precision.
//!
//! Each entry stores `(name, solx, izsol, iasol, jcode, lodders03_pct)`:
//! - `name`: trimmed isotope identifier (`"h1"` through `"u238"`).
//! - `solx`: Anders & Grevesse (1989) solar mass fraction $X_i$ (with the
//!   normalization residual $1 - \sum_j X_j$ added to `h1` as in
//!   `init_ag_data`).
//! - `izsol`: atomic number $Z_i$.
//! - `iasol`: baryon number $A_i = Z_i + N_i$.
//! - `jcode`: beta-decay progenitor code (`0` = sole stable isobar,
//!   `1` = proton-rich progenitors, `2` = neutron-rich progenitors,
//!   `3` = shielded isobar such as `k40`).
//! - `lodders03_pct`: Lodders (2003, ApJ 591, 1220, Table 6) isotopic atom
//!   percentage within its parent element.
//!
//! # Data Provenance
//! - Mass fractions `solx(1:286)` and decay codes `jc(1:286)` come from
//!   Anders & Grevesse (1989, Geochim. Cosmochim. Acta 53, 197).
//! - Isotopic atom percentages come from Lodders (2003, ApJ 591, 1220,
//!   Table 6).
//! - Each tuple `(name, solx, iz, ia, jc, lodders03_pct)` is stored in
//!   1-based order `j = 1..=286` (`h1` through `u238`).
//! - Used by [`super::solar_ag89::ag89_zsol`],
//!   [`super::solar_ag89::ag89_yesol`],
//!   [`super::solar_ag89::chem_xsol`], and
//!   [`super::solar_ag89::get_stable_mass_frac`].
//!
//! References:
//! - Anders, E., & Grevesse, N. 1989, Geochim. Cosmochim. Acta, 53, 197.
//! - Lodders, K. 2003, ApJ, 591, 1220.

