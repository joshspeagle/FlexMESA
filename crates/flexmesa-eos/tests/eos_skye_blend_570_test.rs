fn check_vec_bits(
    failures: &mut Vec<String>,
    label: &str,
    group: &str,
    got_vals: &[f64; NUM_EOS_BASIC_RESULTS],
    want_bits: &[u64; NUM_EOS_BASIC_RESULTS],
) {
    for ((j, name), (&got, &want)) in EOS_BASIC_RESULT_NAMES
        .iter()
        .enumerate()
        .zip(got_vals.iter().zip(want_bits.iter()))
    {
        if got.to_bits() != want {
            failures.push(format!(
                "  {label} {group}[{j}:{name}]: got={got:.17e} ({:#018x}) \
                 want={:.17e} ({want:#018x}) ulp={}",
                got.to_bits(),
                f64::from_bits(want),
                ulp_distance(got, want)
            ));
        }
    }
}

fn check_dxa_bits(
    failures: &mut Vec<String>,
    label: &str,
    got_dxa: &[[f64; NUM_EOS_D_DXA_RESULTS]],
    want_dxa: &[[u64; NUM_EOS_D_DXA_RESULTS]],
) {
    assert_eq!(
        got_dxa.len(),
        want_dxa.len(),
        "{label}: unexpected d_dxa species count"
    );
    for (species_idx, (&[d_ln_p, d_ln_e], &[w_p, w_e])) in
        got_dxa.iter().zip(want_dxa.iter()).enumerate()
    {
        if d_ln_p.to_bits() != w_p || d_ln_e.to_bits() != w_e {
            failures.push(format!(
                "  {label} d_dxa[{species_idx}]: got=[{:#018x}, {:#018x}] \
                 want=[{w_p:#018x}, {w_e:#018x}]",
                d_ln_p.to_bits(),
                d_ln_e.to_bits()
            ));
        }
    }
}

fn check_zone_record(
    failures: &mut Vec<String>,
    ht: &HelmTable,
    cfg: &EosConfig,
    view: &ReplayRecordView<'_>,
) {
    let xa: Vec<f64> =
        view.xa_bits.iter().copied().map(f64::from_bits).collect();
    let outs = eos_dt_get_zones_with_logs(
        ht,
        &[f64::from_bits(view.rho_bits)],
        &[f64::from_bits(view.log_rho_bits)],
        &[f64::from_bits(view.t_bits)],
        &[f64::from_bits(view.log_t_bits)],
        view.chem_id,
        &xa,
        cfg,
    )
    .expect("eos_dt_get_zones_with_logs succeeds");
    assert_eq!(outs.len(), 1, "expected one zone result");
    let out = &outs[0];

    check_vec_bits(failures, &view.label, "res", &out.res, view.res_bits);
    check_vec_bits(
        failures,
        &view.label,
        "d_dlnd",
        &out.d_dlnd,
        view.d_dlnd_bits,
    );
    check_vec_bits(
        failures,
        &view.label,
        "d_dlnT",
        &out.d_dln_t,
        view.d_dln_t_bits,
    );
    check_dxa_bits(failures, &view.label, &out.d_dxa, view.d_dxa_bits);
}

fn check_fraction_record(
    failures: &mut Vec<String>,
    ht: &HelmTable,
    cat: &NuclideCatalog,
    out_free: &EosEvalOutput,
    out_skye: &EosEvalOutput,
    view: &ReplayRecordView<'_>,
) {
    let xa: Vec<f64> =
        view.xa_bits.iter().copied().map(f64::from_bits).collect();
    let comp = get_composition_info(cat, view.chem_id, &xa, true)
        .expect("valid composition");
    let (alfa, d_alfa_dlog_t, d_alfa_dlog_rho) = get_skye_alfa(
        ht,
        f64::from_bits(view.log_rho_bits),
        f64::from_bits(view.log_t_bits),
        comp.abar,
        comp.zbar,
    );
    let blended = combine_two_eos_components(
        alfa,
        d_alfa_dlog_t,
        d_alfa_dlog_rho,
        false,
        out_skye,
        out_free,
    );
    let checks = [
        (
            "res[Free]",
            blended.res[I_FRAC_FREE_EOS],
            view.res_bits[I_FRAC_FREE_EOS],
        ),
        (
            "res[Skye]",
            blended.res[I_FRAC_SKYE],
            view.res_bits[I_FRAC_SKYE],
        ),
        (
            "d_dlnd[Free]",
            blended.d_dlnd[I_FRAC_FREE_EOS],
            view.d_dlnd_bits[I_FRAC_FREE_EOS],
        ),
        (
            "d_dlnd[Skye]",
            blended.d_dlnd[I_FRAC_SKYE],
            view.d_dlnd_bits[I_FRAC_SKYE],
        ),
        (
            "d_dlnT[Free]",
            blended.d_dln_t[I_FRAC_FREE_EOS],
            view.d_dln_t_bits[I_FRAC_FREE_EOS],
        ),
        (
            "d_dlnT[Skye]",
            blended.d_dln_t[I_FRAC_SKYE],
            view.d_dln_t_bits[I_FRAC_SKYE],
        ),
    ];
    for (slot_label, got, want) in checks {
        if got.to_bits() != want {
            failures.push(format!(
                "  {} {slot_label}: got={got:.17e} ({:#018x}) \
                 want={:.17e} ({want:#018x}) ulp={}",
                view.label,
                got.to_bits(),
                f64::from_bits(want),
                ulp_distance(got, want)
            ));
        }
    }
}

