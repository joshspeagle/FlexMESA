fn ordered_bits(bits: u64) -> u64 {
    if (bits >> 63) != 0 {
        !bits
    } else {
        bits | (1_u64 << 63)
    }
}

fn ulp_distance(got: f64, want_bits: u64) -> u64 {
    ordered_bits(got.to_bits()).abs_diff(ordered_bits(want_bits))
}

