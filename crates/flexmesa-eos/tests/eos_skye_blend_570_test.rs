//! Regression tests for `#570` (`star/ns_c` model 1 and
//! `star/wd_c_core_ignition` models 1-2 `FreeEOS`/`Skye` blend
//! `d_dlnd(frac)` and derivative/value divergences).
//!
//! Vectors come from the MESA `26.4.1` (`gfortran 15.2.0`, MESA SDK
//! `x86_64-linux-26.6.1`) `#552` cell EOS replay captures of `do_eos_for_cell`:
//! - 15 `star/ns_c` model 1 (`solver_iter` 1-4) calls that previously differed.
//! - 5 `star/wd_c_core_ignition` models 1-2 (`solver_iter = 0`, zones `501`
//!   and `493`) calls covering both differing (`zbar = 0x401B271F226E3E8C`)
//!   and identical (`zbar = 0x401B271F226E3E8A`) zone-493 compositions.
//!
//! Root cause (`eos/private/skye.f90:69`, `eos/private/skye.f90:73-74`,
//! `eos/private/skye.f90:77`, `math/private/math_pown.f90:74-91`):
//! `Get_Skye_alfa` evaluates `1d5 * pow2(zbar)` and `abar * pow3(zbar)`,
//! where Fortran associates `1d5 * (zbar * zbar)` and
//! `abar * ((zbar * zbar) * zbar)` rather than left-to-right
//! `((abar * zbar) * zbar) * zbar`. The 1-ULP shift in `rho_ion` shifts
//! the vertical blend edge (`bounds(3..4)`) directly or flips `d_dlnd` on
//! the horizontal edge (`bounds(2..3)`) between `0.0` and `~1e-30`.

