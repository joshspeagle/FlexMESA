//! Golden parity integration tests for Wave 3a.2 (`HELM` degenerate,
//! relativistic pair-production, crystallized WD, and Hermite basis regimes)
//! against upstream Fortran MESA (`eos_helm_eval.f90` / `helm.f90`).

#![allow(
    clippy::excessive_precision,
    clippy::similar_names,
    clippy::too_many_lines,
    clippy::unreadable_literal
)]

use flexmesa_eos::{
    CubicBasis1D, EOS_BASIC_RESULT_NAMES, HelmConfig, HelmTable,
    QuinticBasis1D, eval_helm_eos, eval_helm_eos_zones, helmeos2,
};

fn helm_exp10(x: f64) -> f64 {
    (x * std::f64::consts::LN_10).exp()
}

fn assert_helm_case(
    label: &str,
    temp: f64,
    den: f64,
    abar: f64,
    zbar: f64,
    expected: &[[f64; 5]; 16],
) {
    let (out, d_dabar, d_dzbar) =
        eval_helm_eos(temp, den, abar, zbar).expect(label);
    for (idx, exp) in expected.iter().enumerate() {
        let name = EOS_BASIC_RESULT_NAMES[idx];
        let got = [
            out.res[idx],
            out.d_dlnd[idx],
            out.d_dln_t[idx],
            d_dabar[idx],
            d_dzbar[idx],
        ];
        for (col, (&g, &e)) in got.iter().zip(exp.iter()).enumerate() {
            let scale = e.abs().max(1.0);
            let rel_err = (g - e).abs() / scale;
            assert!(
                rel_err < 1.0e-14,
                "{label} {name} col {col}: got {g:.16e}, exp {e:.16e} \
                 (rel_err = {rel_err:.3e})"
            );
        }
    }
}

