//! Strict-mode regression snapshot tests for Wave 3a.2 (`HELM` equation of
//! state; `#146`). Real compiled MESA `26.4.1` component oracle comparisons are
//! in `mesa_26_4_1_component_oracles_test.rs` (`T2-15`).

#![allow(
    clippy::excessive_precision,
    clippy::similar_names,
    clippy::too_many_lines,
    clippy::unreadable_literal
)]

use flexmesa_eos::{eval_helm_eos, EOS_BASIC_RESULT_NAMES};

fn assert_helm_case(
    label: &str,
    temp: f64,
    den: f64,
    abar: f64,
    zbar: f64,
    expected: &[[f64; 5]; 16],
) {
    let (out, d_dabar, d_dzbar) =
        eval_helm_eos(temp, den, abar, zbar).expect(label);
    for (idx, exp) in expected.iter().enumerate() {
        let name = EOS_BASIC_RESULT_NAMES[idx];
        let got = [
            out.res[idx],
            out.d_dlnd[idx],
            out.d_dln_t[idx],
            d_dabar[idx],
            d_dzbar[idx],
        ];
        for (col, (&g, &e)) in got.iter().zip(exp.iter()).enumerate() {
            let scale = e.abs().max(1.0);
            let rel_err = (g - e).abs() / scale;
            assert!(
                rel_err < 1.0e-14,
                "{label} {name} col {col}: got {g:.16e}, exp {e:.16e} \
                 (rel_err = {rel_err:.3e})"
            );
        }
    }
}

