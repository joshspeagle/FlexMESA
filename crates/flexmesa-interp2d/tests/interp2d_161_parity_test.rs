fn bits_to_vec(bits: &[u64]) -> Vec<f64> {
    bits.iter().copied().map(f64::from_bits).collect()
}

fn assert_bits_eq(
    label: &str,
    idx: usize,
    comp: usize,
    actual: f64,
    expected_bits: u64,
) {
    assert_eq!(
        actual.to_bits(),
        expected_bits,
        "{label}[{idx}][{comp}] bit mismatch: got {:#018X} ({actual:?}),          expected {expected_bits:#018X}",
        actual.to_bits(),
    );
}

struct BicubCase<'a> {
    label: &'static str,
    z: &'a [f64],
    bcs: [BicubicBc; 4],
    bc_vals: [&'a [f64]; 4],
    expected: &'a [[u64; 4]; 30],
}

#[test]
fn test_photosphere_boundary_slices_logz_m10_and_p05_match_mesa_26_4_1_zero_ulp(
) {
    let x = bits_to_vec(&PHOTO_LOGG_BITS);
    let y = bits_to_vec(&PHOTO_TEFF_BITS);
    let nx = x.len();
    let ny = y.len();

    for (label, z_bits, ix12_bits, iy81_bits) in [
        (
            "photo_logz_m10",
            &PHOTO_ZM10_Z_BITS,
            &PHOTO_ZM10_IX12_BITS,
            &PHOTO_ZM10_IY81_BITS,
        ),
        (
            "photo_logz_p05",
            &PHOTO_ZP05_Z_BITS,
            &PHOTO_ZP05_IX12_BITS,
            &PHOTO_ZP05_IY81_BITS,
        ),
    ] {
        let z = bits_to_vec(z_bits);
        let (coeffs, logg_is_uniform, teff_is_uniform) = interp_mkbicub_db(
            &x,
            &y,
            &z,
            BicubicBc::NotAKnot,
            &[],
            BicubicBc::NotAKnot,
            &[],
            BicubicBc::NotAKnot,
            &[],
            BicubicBc::NotAKnot,
            &[],
        )
        .expect("interp_mkbicub_db on photosphere slice");
        assert!(logg_is_uniform, "{label} logg axis is uniform");
        assert!(!teff_is_uniform, "{label} teff axis is non-uniform");

        for (iy, exp_row) in ix12_bits.iter().enumerate() {
            let actual = coeffs[(nx - 1) * ny + iy];
            for (comp, &exp_bits) in exp_row.iter().enumerate() {
                assert_bits_eq(label, iy, comp, actual[comp], exp_bits);
            }
        }
        for (ix, exp_row) in iy81_bits.iter().enumerate() {
            let actual = coeffs[ix * ny + (ny - 1)];
            for (comp, &exp_bits) in exp_row.iter().enumerate() {
                assert_bits_eq(label, ix, comp, actual[comp], exp_bits);
            }
        }
    }
}

#[test]
fn test_bicub_boundary_conditions_cases_1_to_4_match_mesa_26_4_1_zero_ulp() {
    let x = [0.0_f64, 0.3, 0.85, 1.4, 2.1, 3.0];
    let y = [-1.0_f64, -0.2, 0.4, 1.3, 2.5];
    let nx = x.len();
    let ny = y.len();

    let mut left_bc = Vec::with_capacity(ny);
    let mut right_bc = Vec::with_capacity(ny);
    for &yv in &y {
        left_bc.push(0.6 * x[0] * x[0] - 0.5 * yv * yv + 0.35);
        right_bc.push(1.2 * x[nx - 1] - 0.7 * yv);
    }
    let mut bottom_bc = Vec::with_capacity(nx);
    let mut top_bc = Vec::with_capacity(nx);
    for &xv in &x {
        bottom_bc.push(-xv * y[0] + 0.45);
        top_bc.push(-xv - 0.25 * xv * xv);
    }

    let z_smooth = bits_to_vec(&CASE1_Z_BITS);
    let z_periodic = bits_to_vec(&CASE2_Z_BITS);

    let cases = [
        BicubCase {
            label: "case1_not_a_knot",
            z: &z_smooth,
            bcs: [
                BicubicBc::NotAKnot,
                BicubicBc::NotAKnot,
                BicubicBc::NotAKnot,
                BicubicBc::NotAKnot,
            ],
            bc_vals: [&[], &[], &[], &[]],
            expected: &CASE1_OUT_BITS,
        },
        BicubCase {
            label: "case2_periodic",
            z: &z_periodic,
            bcs: [
                BicubicBc::Periodic,
                BicubicBc::Periodic,
                BicubicBc::Periodic,
                BicubicBc::Periodic,
            ],
            bc_vals: [&[], &[], &[], &[]],
            expected: &CASE2_OUT_BITS,
        },
        BicubCase {
            label: "case3_inhomogeneous",
            z: &z_smooth,
            bcs: [
                BicubicBc::FirstDeriv,
                BicubicBc::SecondDeriv,
                BicubicBc::FirstDeriv,
                BicubicBc::SecondDeriv,
            ],
            bc_vals: [&left_bc, &right_bc, &bottom_bc, &top_bc],
            expected: &CASE3_OUT_BITS,
        },
        BicubCase {
            label: "case4_divided_diff",
            z: &z_smooth,
            bcs: [
                BicubicBc::ZeroSecondDeriv,
                BicubicBc::DividedDiff3,
                BicubicBc::DividedDiff1,
                BicubicBc::DividedDiff2,
            ],
            bc_vals: [&[], &[], &[], &[]],
            expected: &CASE4_OUT_BITS,
        },
    ];

    for case in cases {
        let (coeffs, axis0_uniform, axis1_uniform) = interp_mkbicub_db(
            &x,
            &y,
            case.z,
            case.bcs[0],
            case.bc_vals[0],
            case.bcs[1],
            case.bc_vals[1],
            case.bcs[2],
            case.bc_vals[2],
            case.bcs[3],
            case.bc_vals[3],
        )
        .expect("interp_mkbicub_db case");
        assert!(!axis0_uniform, "{} x grid is non-uniform", case.label);
        assert!(!axis1_uniform, "{} y grid is non-uniform", case.label);
        for (idx, exp_row) in case.expected.iter().enumerate() {
            for (comp, &exp_bits) in exp_row.iter().enumerate() {
                assert_bits_eq(
                    case.label,
                    idx,
                    comp,
                    coeffs[idx][comp],
                    exp_bits,
                );
            }
        }
    }
}

#[test]
fn test_mkspline_db_reproduces_exact_cubic_second_derivatives_across_all_knots()
{
    let x = [0.0_f64, 0.3, 0.85, 1.4, 2.1, 3.0];
    let f: Vec<f64> = x
        .iter()
        .map(|&xv| 0.2 * xv * xv * xv - 0.5 * xv * xv + 1.3 * xv - 0.7)
        .collect();
    let expected_d2f: Vec<f64> = x.iter().map(|&xv| 1.2 * xv - 1.0).collect();

    for (bc_min, wk1, bc_max, wkn) in [
        (BicubicBc::NotAKnot, 0.0, BicubicBc::NotAKnot, 0.0),
        (BicubicBc::FirstDeriv, 1.3, BicubicBc::SecondDeriv, 2.6),
    ] {
        let (d2f, axis_uniform) = mkspline_db(&x, &f, bc_min, wk1, bc_max, wkn)
            .expect("mkspline_db exact cubic");
        assert!(!axis_uniform);
        for (idx, (&actual, &expected)) in
            d2f.iter().zip(expected_d2f.iter()).enumerate()
        {
            assert!(
                (actual - expected).abs() < 1.0e-13,
                "knot {idx}: got {actual}, expected {expected}",
            );
        }
    }
}
