#[test]
fn test_potekhin_clipped_z_extremes_match_condint_lines_189_236() {
    with_numerics_mode(NumericsMode::Strict, || {
        // Interior Z in condtabl (1 < zbar < 60): clipped_log_rho / clipped_log_t
        // inside the else branch zeros dlog_k_dlog_rho / dlog_k_dlog_t, yielding
        // dlnkap_dlnRho = -1.0 and dlnkap_dlnT = 3.0.
        let (k_rho_clip, dlnd_rho_clip, dlnt_rho_clip) =
            do_electron_conduction_potekhin(2.0, -7.0, 6.0).unwrap_or_else(
                |e| panic!("potekhin z=2 rho-clipped failed: {e}"),
            );
        assert!(k_rho_clip > 0.0 && k_rho_clip.is_finite());
        assert_eq!(dlnd_rho_clip.to_bits(), (-1.0_f64).to_bits());
        assert!(dlnt_rho_clip.is_finite());

        let (k_t_clip, dlnd_t_clip, dlnt_t_clip) =
            do_electron_conduction_potekhin(2.0, 0.0, 2.5).unwrap_or_else(
                |e| panic!("potekhin z=2 T-clipped failed: {e}"),
            );
        assert!(k_t_clip > 0.0 && k_t_clip.is_finite());
        assert!(dlnd_t_clip.is_finite());
        assert_eq!(dlnt_t_clip.to_bits(), (3.0_f64).to_bits());

        // Extreme zbar <= 1 and zbar >= 60 take the clamped-Z branches before the
        // else-branch derivative zeroing, staying smooth and finite across clipped grids.
        for &(zbar, log_rho, log_t) in &[
            (0.5, -7.0, 2.5),
            (1.0, -7.0, 6.0),
            (60.0, 11.5, 10.5),
            (70.0, -7.0, 2.5),
            (70.0, 11.5, 10.5),
        ] {
            let (kap, dlnd, dlnt) =
                do_electron_conduction_potekhin(zbar, log_rho, log_t)
                    .unwrap_or_else(|e| {
                        panic!(
                            "potekhin extreme zbar={zbar} ({log_rho}, {log_t}) failed: {e}"
                        )
                    });
            assert!(
                kap > 0.0 && kap.is_finite() && dlnd.is_finite() && dlnt.is_finite(),
                "non-finite potekhin output at zbar={zbar}, logRho={log_rho}, logT={log_t}: \
                 kap={kap}, dlnd={dlnd}, dlnt={dlnt}"
            );
        }
    });
}

