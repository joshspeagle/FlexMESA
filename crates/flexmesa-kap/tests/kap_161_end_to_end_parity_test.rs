#[test]
fn test_get_kap_results_blend_sentinels_kap_eval_lines_161_204() {
    let cfg_no_cond = KapConfig {
        zbase: 0.02,
        kap_option: KapOption::Gs98,
        kap_co_option: KapCoOption::Gs98Co,
        kap_low_t_option: KapLowTOption::LowTFa05Gs98,
        include_electron_conduction: false,
        use_type2_opacities: false,
        ..KapConfig::default()
    };

    with_numerics_mode(NumericsMode::Strict, || {
        // Above logT_Compton_blend_hi, table opacity is skipped (log_kr = log10(1e-30))
        // and total radiative opacity reduces cleanly to Compton opacity.
        let log_rho = -6.0;
        let log_t = 10.5;
        let rho = exp10(log_rho);
        let t = exp10(log_t);
        let lnfree_e = -0.15;
        let dlnfe_d = 0.0;
        let dlnfe_t = 0.0;
        let eta = -8.0;
        let deta_d = 1.0;
        let deta_t = -1.5;

        let (kc, kc_dlnd, kc_dlnt) = compton_opacity(
            rho, t, lnfree_e, dlnfe_d, dlnfe_t, eta, deta_d, deta_t,
        );
        let out = get_kap_results(
            &cfg_no_cond,
            1.15,
            0.70,
            0.02,
            0.003,
            0.001,
            0.01,
            0.002,
            log_rho,
            log_t,
            lnfree_e,
            dlnfe_d,
            dlnfe_t,
            eta,
            deta_d,
            deta_t,
        )
        .unwrap_or_else(|e| panic!("pure-Compton get_kap_results failed: {e}"));

        assert_eq!(out.kap_fracs[I_FRAC_COMPTON].to_bits(), 1.0_f64.to_bits());
        assert_eq!(out.kap_fracs[I_FRAC_LOW_T].to_bits(), 0.0_f64.to_bits());
        assert_eq!(out.kap_fracs[I_FRAC_HIGH_T].to_bits(), 0.0_f64.to_bits());
        assert_eq!(out.kap_fracs[I_FRAC_TYPE2].to_bits(), 0.0_f64.to_bits());
        let expected_log10 = log10(kc);
        assert!(
            (out.log10_kap - expected_log10).abs()
                <= 1.0e-14 * (1.0 + expected_log10.abs()),
            "pure-Compton log10_kap mismatch: {} vs {expected_log10}",
            out.log10_kap
        );
        assert!(
            (out.kap - kc).abs() <= 1.0e-14 * kc,
            "pure-Compton kap mismatch: {} vs {kc}",
            out.kap
        );
        assert!(
            (out.dlnkap_dln_rho - kc_dlnd).abs()
                <= 1.0e-13 * (1.0 + kc_dlnd.abs()),
            "pure-Compton dlnd mismatch: {} vs {kc_dlnd}",
            out.dlnkap_dln_rho
        );
        assert!(
            (out.dlnkap_dln_t - kc_dlnt).abs()
                <= 1.0e-13 * (1.0 + kc_dlnt.abs()),
            "pure-Compton dlnt mismatch: {} vs {kc_dlnt}",
            out.dlnkap_dln_t
        );
    });
}
