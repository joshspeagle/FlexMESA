fn canonical_side_stoich(
    count: usize,
    nums: [u8; 3],
    isos: [u16; 3],
) -> Vec<(u16, u16)> {
    let mut items: Vec<(u16, u16)> = Vec::with_capacity(count.min(3));
    for k in 0..count.min(3) {
        let iso = isos[k];
        let mult = u16::from(nums[k]);
        if iso == 0 || mult == 0 {
            continue;
        }
        if let Some(existing) = items.iter_mut().find(|(id, _)| *id == iso) {
            existing.1 += mult;
        } else {
            items.push((iso, mult));
        }
    }
    items.sort_unstable_by_key(|&(id, _)| id);
    items
}

fn reactions_are_stoichiometric_reverses(
    a: &ReactionInfo,
    b: &ReactionInfo,
) -> bool {
    let a_in = canonical_side_stoich(a.num_in, a.in_num, a.in_iso);
    let a_out = canonical_side_stoich(a.num_out, a.out_num, a.out_iso);
    let b_in = canonical_side_stoich(b.num_in, b.in_num, b.in_iso);
    let b_out = canonical_side_stoich(b.num_out, b.out_num, b.out_iso);
    !a_in.is_empty() && !a_out.is_empty() && a_in == b_out && a_out == b_in
}

fn build_reverse_id_map(
    reactions: &[ReactionInfo],
    extra_pairs: &[(String, String)],
) -> HashMap<usize, usize> {
    let by_name: HashMap<&str, usize> = reactions
        .iter()
        .enumerate()
        .map(|(idx, r)| (r.name.as_str(), idx))
        .collect();
    let mut rev_map = HashMap::new();
    let mut try_insert = |s1: &str, s2: &str| {
        if let (Some(&idx1), Some(&idx2)) = (by_name.get(s1), by_name.get(s2)) {
            let r1 = &reactions[idx1];
            let r2 = &reactions[idx2];
            if reactions_are_stoichiometric_reverses(r1, r2) {
                rev_map.insert(r1.id, r2.id);
                rev_map.insert(r2.id, r1.id);
            }
        }
    };
    for &(s1, s2) in HARDWIRED_REVERSE_PAIRS {
        try_insert(s1, s2);
    }
    for (s1, s2) in extra_pairs {
        try_insert(s1.as_str(), s2.as_str());
    }
    rev_map
}

fn classify_reaclib_kinds(
    reactions: &[ReactionInfo],
    rev_map: &HashMap<usize, usize>,
) -> Result<(Vec<ReaclibKind>, Vec<usize>), NetError> {
    let nuclides = NuclideCatalog::builtin_ref();
    let req_u16 = |name: &str| {
        nuclides
            .get_nuclide_index(name)
            .map(|id| id as u16)
            .ok_or_else(|| NetError::InvalidReactionOrIso(name.to_string()))
    };
    let ineut = req_u16("neut")?;
    let ih1 = req_u16("h1")?;
    let ihe4 = req_u16("he4")?;

    let n = reactions.len();
    let mut kinds = vec![ReaclibKind::Other; n];
    let mut rev_ids = vec![0_usize; n];

    for (i, rxn) in reactions.iter().enumerate() {
        let ir = rxn.id;
        if rxn.weak_isos[0] > 0 || !rxn.name.starts_with("r_") {
            continue;
        }
        let Some(&r_ir) = rev_map.get(&ir) else {
            continue;
        };
        rev_ids[i] = r_ir;
        if rxn.num_in > 2 || rxn.num_out > 2 {
            continue;
        }
        let num_in1 = rxn.in_num[0];
        let iso_in1 = rxn.in_iso[0];
        let num_in2 = rxn.in_num[1];
        let iso_in2 = rxn.in_iso[1];
        let num_out1 = rxn.out_num[0];
        let iso_out1 = rxn.out_iso[0];
        let num_out2 = rxn.out_num[1];
        let iso_out2 = rxn.out_iso[1];

        if iso_in1 == 0 || iso_out1 == 0 || num_in1 > 3 || num_out1 > 3 {
            continue;
        }
        if iso_in2 == 0 {
            if iso_out2 > 0 || (num_in1 == 1 && num_out1 == 1) {
                continue;
            }
            kinds[i] = if r_ir < ir {
                ReaclibKind::Other
            } else {
                ReaclibKind::GeneralOneOne
            };
            continue;
        }
        if iso_out2 == 0 {
            if num_in1 > 1 || num_in2 > 1 || num_out1 > 1 {
                kinds[i] = ReaclibKind::GeneralTwoOne;
                continue;
            }
        } else if num_in1 > 1 || num_in2 > 1 || num_out1 > 1 || num_out2 > 1 {
            kinds[i] = if r_ir == 0 {
                ReaclibKind::Other
            } else {
                ReaclibKind::GeneralTwoTwo
            };
            continue;
        }

        let z_in1 = nuclides.get_by_id(usize::from(iso_in1)).map_or(0, |e| e.z);
        let z_in2 = nuclides.get_by_id(usize::from(iso_in2)).map_or(0, |e| e.z);
        let in_a = if z_in1 <= z_in2 { iso_in1 } else { iso_in2 };

        if iso_out2 == 0 {
            kinds[i] = if in_a == ineut {
                ReaclibKind::Ng
            } else if in_a == ihe4 {
                ReaclibKind::Ag
            } else if in_a == ih1 {
                ReaclibKind::Pg
            } else {
                ReaclibKind::GeneralTwoOne
            };
        } else {
            let z_o1 =
                nuclides.get_by_id(usize::from(iso_out1)).map_or(0, |e| e.z);
            let z_o2 =
                nuclides.get_by_id(usize::from(iso_out2)).map_or(0, |e| e.z);
            let out_c = if z_o1 <= z_o2 { iso_out1 } else { iso_out2 };
            if in_a == ihe4 {
                kinds[i] = if out_c == ih1 {
                    ReaclibKind::Ap
                } else if out_c == ineut {
                    ReaclibKind::An
                } else {
                    ReaclibKind::GeneralTwoTwo
                };
            } else if in_a == ih1 {
                if out_c == ineut {
                    kinds[i] = ReaclibKind::Pn;
                } else if out_c == ihe4 {
                    kinds[i] = ReaclibKind::Other;
                    continue;
                } else {
                    kinds[i] = ReaclibKind::GeneralTwoTwo;
                }
            } else if in_a == ineut {
                if out_c == ih1 || out_c == ihe4 {
                    kinds[i] = ReaclibKind::Other;
                    continue;
                }
                kinds[i] = ReaclibKind::GeneralTwoTwo;
            } else {
                kinds[i] = ReaclibKind::GeneralTwoTwo;
            }
            if kinds[i] == ReaclibKind::GeneralTwoTwo && r_ir > ir {
                kinds[i] = ReaclibKind::Other;
            }
        }
    }
    Ok((kinds, rev_ids))
}

impl NetGeneralInfo {
    /// Compiles and initializes a complete [`NetGeneralInfo`] from an embedded
    /// `.net` file name (e.g., `"basic.net"`, `"approx21.net"`).
    ///
    /// # Errors
    /// Returns [`NetError`] if the file is unknown or fails to initialize.
    pub fn from_name(net_filename: &str) -> Result<Self, NetError> {
        let parsed = ParsedNetDef::parse_from_name(net_filename)?;
        Self::from_parsed(parsed)
    }

    /// Compiles and initializes a [`NetGeneralInfo`] from an embedded `.net`
    /// file name or a case-local file in `search_dir`.
    ///
    /// # Errors
    /// Returns [`NetError`] if the file is unknown or fails to initialize.
    pub fn from_name_or_dir(
        net_filename: &str,
        search_dir: Option<&std::path::Path>,
    ) -> Result<Self, NetError> {
        Self::from_name_or_dir_with_rate_overrides(
            net_filename,
            search_dir,
            &[],
        )
    }

    /// Compiles and initializes a [`NetGeneralInfo`] from an embedded `.net`
    /// file name or a case-local file in `search_dir`, overriding raw rate
    /// tables for the specified `(reaction_name, table)` entries
    /// (`read_rates_from_files` in `star/private/net.f90:735`).
    ///
    /// # Errors
    /// Returns [`NetError`] if the `.net` file cannot be parsed, an override
    /// reaction name is unrecognized, or rate-table spline construction fails.
    pub fn from_name_or_dir_with_rate_overrides(
        net_filename: &str,
        search_dir: Option<&std::path::Path>,
        rate_overrides: &[(String, Arc<RateTable1D>)],
    ) -> Result<Self, NetError> {
        let parsed =
            ParsedNetDef::parse_from_name_or_dir(net_filename, search_dir)?;
        Self::from_parsed_with_rate_overrides(parsed, rate_overrides)
    }

    /// Compiles and initializes a [`NetGeneralInfo`] from a [`ParsedNetDef`].
    pub fn from_parsed(parsed: ParsedNetDef) -> Result<Self, NetError> {
        Self::from_parsed_with_rate_overrides(parsed, &[])
    }

    /// Compiles and initializes a [`NetGeneralInfo`] from a [`ParsedNetDef`]
    /// with optional per-reaction 1D rate table overrides.
    ///
    /// Overridden reactions and their reverse detailed-balance partners bypass
    /// the process-wide `RATTAB_CACHE` so global defaults are never mutated.
    pub fn from_parsed_with_rate_overrides(
        parsed: ParsedNetDef,
        rate_overrides: &[(String, Arc<RateTable1D>)],
    ) -> Result<Self, NetError> {
        let nuclides = NuclideCatalog::builtin_ref();
        let max_chem_id = 7856_usize;
        let mut net_iso = vec![0_usize; max_chem_id + 1];
        let mut chem_id: Vec<usize> = parsed.active_isos.into_iter().collect();
        chem_id.sort_unstable();
        for (idx, &cid) in chem_id.iter().enumerate() {
            net_iso[cid] = idx + 1;
        }
        let num_isos = chem_id.len();

        let mut rxn_map: HashMap<usize, ReactionInfo> = parsed
            .active_reactions
            .into_values()
            .map(|mut r| {
                if let Some(q) = mesa_reaction_qtotal(nuclides, &r) {
                    r.std_q = q;
                }
                (r.id, r)
            })
            .collect();
        let mut reactions: Vec<ReactionInfo> =
            rxn_map.values().cloned().collect();
        reactions.sort_by(|a, b| a.name.cmp(&b.name));

        let num_reactions = reactions.len();
        let rev_map = build_reverse_id_map(&reactions, &parsed.reverse_pairs);
        let (mut reaction_reaclib_kind, mut reverse_id_for_kind_ne_other) =
            classify_reaclib_kinds(&reactions, &rev_map)?;
        let mut reaction_id: Vec<usize> =
            reactions.iter().map(|r| r.id).collect();
        let mut rtab: HashMap<usize, usize> = reaction_id
            .iter()
            .enumerate()
            .map(|(i, &ir)| (ir, i + 1))
            .collect();

        // Group by kind = 1..=9 (`other_kind = 10` goes last)
        let mut i = 0_usize;
        'kind_loop: for kind_code in 1..=9_u8 {
            while i < num_reactions
                && (reaction_reaclib_kind[i] as u8) == kind_code
            {
                i += 1;
                if i >= num_reactions {
                    break 'kind_loop;
                }
            }
            loop {
                let mut found_one = false;
                for j in (i + 1)..num_reactions {
                    if (reaction_reaclib_kind[j] as u8) != kind_code {
                        continue;
                    }
                    reaction_reaclib_kind.swap(i, j);
                    reverse_id_for_kind_ne_other.swap(i, j);
                    reaction_id.swap(i, j);
                    rtab.insert(reaction_id[i], i + 1);
                    rtab.insert(reaction_id[j], j + 1);
                    found_one = true;
                    break;
                }
                if !found_one {
                    break;
                }
                i += 1;
                if i >= num_reactions {
                    break 'kind_loop;
                }
            }
        }

        // Reorder so forward + reverse pairs are adjacent
        let mut idx = 0_usize;
        while idx + 1 < num_reactions {
            if reaction_reaclib_kind[idx] == ReaclibKind::Other {
                idx += 1;
                continue;
            }
            let r_ir = reverse_id_for_kind_ne_other[idx];
            let Some(&r_i_1based) = rtab.get(&r_ir) else {
                idx += 1;
                continue;
            };
            let r_idx = r_i_1based - 1;
            let ir = reaction_id[idx];
            idx += 1;
            for k in (idx..r_idx).rev() {
                reaction_reaclib_kind[k + 1] = reaction_reaclib_kind[k];
                reverse_id_for_kind_ne_other[k + 1] =
                    reverse_id_for_kind_ne_other[k];
                reaction_id[k + 1] = reaction_id[k];
                rtab.insert(reaction_id[k + 1], k + 2);
            }
            reaction_reaclib_kind[idx] = ReaclibKind::Other;
            reverse_id_for_kind_ne_other[idx] = ir;
            reaction_id[idx] = r_ir;
            rtab.insert(r_ir, idx + 1);
            idx += 1;
        }

        let ordered_reactions: Vec<ReactionInfo> = reaction_id
            .iter()
            .map(|id| rxn_map.remove(id).unwrap())
            .collect();

        let ineut = nuclides.get_nuclide_index("neut").unwrap_or(1) as u16;
        let iprot = nuclides.get_nuclide_index("prot").unwrap_or(3) as u16;
        let ih1 = nuclides.get_nuclide_index("h1").unwrap_or(2) as u16;
        let rates_cat = RatesCatalog::builtin();

        let mut reaction_kind = Vec::with_capacity(num_reactions);
        let mut weak_reaction_index = vec![0_usize; num_reactions];
        let mut weak_reaction_num = Vec::new();
        let mut weaklib_ids = Vec::new();
        let mut reaction_max_z = Vec::with_capacity(num_reactions);
        let mut reaction_max_z_plus_n = Vec::with_capacity(num_reactions);

        for (k, rxn) in ordered_reactions.iter().enumerate() {
            let mut max_z = 0_i32;
            let mut max_a = 0_i32;
            for &cid in rxn
                .in_iso
                .iter()
                .take(rxn.num_in)
                .chain(rxn.out_iso.iter().take(rxn.num_out))
            {
                if cid > 0 {
                    if let Some(e) = nuclides.get_by_id(usize::from(cid)) {
                        let ez = e.z as i32;
                        let ea = e.z_plus_n as i32;
                        if ez > max_z || (ez == max_z && ea > max_a) {
                            max_z = ez;
                            max_a = ea;
                        }
                    }
                }
            }
            reaction_max_z.push(max_z);
            reaction_max_z_plus_n.push(max_a);

            if rxn.weak_isos[0] > 0 {
                reaction_kind.push(ReactionKind::Weak);
                weak_reaction_num.push(k + 1);
                weak_reaction_index[k] = weak_reaction_num.len();
                let lhs = nuclides
                    .get_by_id(usize::from(rxn.weak_isos[0]))
                    .map_or("", |e| e.name.as_str());
                let rhs = nuclides
                    .get_by_id(usize::from(rxn.weak_isos[1]))
                    .map_or("", |e| e.name.as_str());
                let w_id = rates_cat.weak_by_pair(lhs, rhs).map_or(0, |w| w.id);
                weaklib_ids.push(w_id);
            } else {
                let mut has_neut = false;
                let mut has_prot = false;
                for &cid in rxn
                    .in_iso
                    .iter()
                    .take(rxn.num_in)
                    .chain(rxn.out_iso.iter().take(rxn.num_out))
                {
                    if cid == ineut {
                        has_neut = true;
                    }
                    if cid == iprot || cid == ih1 {
                        has_prot = true;
                    }
                }
                if has_neut && !has_prot {
                    reaction_kind.push(ReactionKind::Neut);
                } else if has_prot {
                    reaction_kind.push(ReactionKind::Prot);
                } else {
                    reaction_kind.push(ReactionKind::OtherStrong);
                }
            }
        }

        let mut z158 = Vec::with_capacity(num_isos);
        let mut z52 = Vec::with_capacity(num_isos);
        let mut mion = Vec::with_capacity(num_isos);
        for &cid in &chem_id {
            let e = nuclides.get_by_id(cid).unwrap();
            let zf = e.z as f64;
            z158.push(flexmesa_math::pow(zf, 1.58));
            z52.push(flexmesa_math::pow(zf, 2.50));
            mion.push(
                nuclides.get_mass_excess(cid).map_err(|e| {
                    NetError::InvalidReactionOrIso(e.to_string())
                })? * MEV2GR,
            );
        }

        let net_reaction_by_name = ordered_reactions
            .iter()
            .enumerate()
            .map(|(i, r)| (r.name.clone(), i + 1))
            .collect();
        let net_reaction_by_id = ordered_reactions
            .iter()
            .enumerate()
            .map(|(i, r)| (r.id, i + 1))
            .collect();

        let rattab_splines = build_rate_tables_with_overrides(
            &ordered_reactions,
            &rev_map,
            rate_overrides,
        )?;
        let identity_id = compute_net_identity_id(
            &parsed.net_filename,
            &chem_id,
            &ordered_reactions,
            parsed.doing_approx21,
            parsed.add_co56_to_approx21,
            parsed.approx21_ye_iso,
            parsed.fe56ec_n_neut,
            rate_overrides,
        );

        let mut info = Self {
            net_filename: parsed.net_filename,
            identity_id,
            num_isos,
            num_reactions,
            num_wk_reactions: weak_reaction_num.len(),
            chem_id,
            net_iso,
            reactions: ordered_reactions,
            net_reaction_by_name,
            net_reaction_by_id,
            reaction_reaclib_kind,
            reaction_kind,
            reverse_id_for_kind_ne_other,
            weak_reaction_index,
            weak_reaction_num,
            weaklib_ids,
            reaction_max_z,
            reaction_max_z_plus_n,
            z158,
            z52,
            mion,
            screen_params: vec![ScreenPairParams::default(); num_reactions],
            rattab_splines,
            log_tcut_lo: RATTAB_TLO,
            log_tcut_lim: RATTAB_TLO + 0.1,
            doing_approx21: parsed.doing_approx21,
            add_co56_to_approx21: parsed.add_co56_to_approx21,
            approx21_ye_iso: parsed.approx21_ye_iso,
            fe56ec_n_neut: parsed.fe56ec_n_neut,
            fe56ec_fake_factor: 1.0e-4,
            min_t_for_fe56ec_fake_factor: 3.0e9,
            reaction_neuqs_factor: 1.0,
            use_3a_fl87: false,
            use_suzuki_weak_rates: false,
        };
        init_screening_tables(&mut info);
        Ok(info)
    }

    /// Evaluates raw unscreened reaction rates `(rate_raw, rate_raw_dt, rate_raw_drho)`
    /// across `self.reactions` using the precomputed `interp_m3q` rate tables
    /// (`do_get_raw_rates` in `rates/private/rates_support.f90`).
    pub fn eval_raw_rates_from_tables(
        &self,
        ye: f64,
        log_t_in: f64,
        btemp: f64,
        bden: f64,
        rate_factors: &[f64],
        rate_raw: &mut [f64],
        rate_raw_dt: &mut [f64],
        rate_raw_drho: &mut [f64],
    ) -> Result<(), NetError> {
        let logtemp = log_t_in.min(MAX_SAFE_LOGT_FOR_RATES);
        if logtemp > RATTAB_THI {
            return Err(NetError::IntegrationError(format!(
                "logT={logtemp} exceeds RATTAB_THI={RATTAB_THI}"
            )));
        }
        let logttab = global_logttab();
        let iat0 = ((logtemp - RATTAB_TLO) / RATTAB_TSTP) as isize + 1;
        let iat = iat0 - 1;
        let mut k = iat.clamp(1, (NRATTAB as isize) - 3) as usize;
        while k > 0 && logtemp < logttab[k] {
            k -= 1;
        }
        while k + 1 < NRATTAB && logtemp > logttab[k + 1] {
            k += 1;
        }
        let dt = logtemp - logttab[k];
        let bt_ln10 = btemp * LN10;

        for (i, rxn) in self.reactions.iter().enumerate() {
            let mut dtab = match rxn.ye_exp {
                1 => ye,
                2 => ye * ye,
                _ => 1.0,
            };
            let irho = rxn.rho_exp;
            match irho {
                1 => dtab *= bden,
                2 => dtab = (dtab * bden) * bden,
                3 => dtab = ((dtab * bden) * bden) * bden,
                4 => dtab = (((dtab * bden) * bden) * bden) * bden,
                _ => {}
            }
            let ddtab = f64::from(irho) * dtab / bden;
            let c = &self.rattab_splines[i][k];
            let fac = rate_factors.get(i).copied().unwrap_or(1.0);
            let poly = c[0] + dt * (c[1] + dt * (c[2] + dt * c[3]));
            let dpoly = c[1] + 2.0 * dt * (c[2] + 1.5 * dt * c[3]);
            let r = poly * dtab;
            rate_raw[i] = r * fac;
            rate_raw_drho[i] = (r * ddtab / dtab) * fac;
            rate_raw_dt[i] = if logtemp >= MAX_SAFE_LOGT_FOR_RATES {
                0.0
            } else {
                (dpoly * dtab / bt_ln10) * fac
            };
        }
        Ok(())
    }
}

fn fnv1a_update(hash: &mut u64, bytes: &[u8]) {
    for &b in bytes {
        *hash ^= u64::from(b);
        *hash = hash.wrapping_mul(0x100000001b3);
    }
}

fn compute_net_identity_id(
    net_filename: &str,
    chem_id: &[usize],
    reactions: &[ReactionInfo],
    doing_approx21: bool,
    add_co56_to_approx21: bool,
    approx21_ye_iso: usize,
    fe56ec_n_neut: i32,
    rate_overrides: &[(String, Arc<RateTable1D>)],
) -> u64 {
    let mut h = 0xcbf2_9ce4_8422_2325_u64;
    fnv1a_update(&mut h, &(net_filename.len() as u64).to_le_bytes());
    fnv1a_update(&mut h, net_filename.as_bytes());
    fnv1a_update(&mut h, &(chem_id.len() as u64).to_le_bytes());
    for &cid in chem_id {
        fnv1a_update(&mut h, &(cid as u64).to_le_bytes());
    }
    fnv1a_update(&mut h, &(reactions.len() as u64).to_le_bytes());
    for r in reactions {
        fnv1a_update(&mut h, &(r.id as u64).to_le_bytes());
        fnv1a_update(&mut h, &(r.name.len() as u64).to_le_bytes());
        fnv1a_update(&mut h, r.name.as_bytes());
    }
    let flags =
        u8::from(doing_approx21) | (u8::from(add_co56_to_approx21) << 1);
    fnv1a_update(&mut h, &[flags]);
    fnv1a_update(&mut h, &(approx21_ye_iso as u64).to_le_bytes());
    fnv1a_update(&mut h, &fe56ec_n_neut.to_le_bytes());
    if !rate_overrides.is_empty() {
        let mut sorted: Vec<(&str, u64)> = rate_overrides
            .iter()
            .map(|(n, t)| (n.as_str(), t.content_fingerprint()))
            .collect();
        sorted.sort_unstable_by(|a, b| a.0.cmp(b.0));
        fnv1a_update(&mut h, &(sorted.len() as u64).to_le_bytes());
        for (name, fp) in sorted {
            fnv1a_update(&mut h, &(name.len() as u64).to_le_bytes());
            fnv1a_update(&mut h, name.as_bytes());
            fnv1a_update(&mut h, &fp.to_le_bytes());
        }
    }
    h
}

/// Builds the `NRATTAB` cubic spline for one reaction's raw rate table.
///
/// Maps `weaklib_only` (`op_code == 2`) sentinel returns (`< 0.0`, returned by
/// raw REACLIB evaluation before `eval_weak` lookup) to `exp(-99.0)`, matching
/// MESA REACLIB initialization (`coefficients(1) = -99.0`).
fn spline_reaction_rate_table<E, F>(
    rxn: &ReactionInfo,
    logttab: &[f64],
    ttab: &[f64],
    label: &str,
    eval_fn: F,
) -> Result<Arc<Vec<CubicCoeffs>>, NetError>
where
    E: std::fmt::Display,
    F: Fn(f64, &TFactors) -> Result<f64, E>,
{
    let mut y = Vec::with_capacity(NRATTAB);
    for idx in 0..NRATTAB {
        let tf = TFactors::from_log_t(logttab[idx], ttab[idx]);
        let raw = eval_fn(ttab[idx], &tf).map_err(|e| {
            NetError::IntegrationError(format!(
                "failed to evaluate {label} '{}': {e}",
                rxn.name
            ))
        })?;
        // Weaklib-only reactions hold `-99.0` in REACLIB slot 1 so raw table
        // evaluation yields `exp(-99.0)` instead of the `-1.0` sentinel.
        let rate = if rxn.op_code == 2 && raw < 0.0 {
            exp(-99.0_f64)
        } else {
            raw
        };
        y.push(rate);
    }
    let coeffs = interp_m3q(logttab, &y).map_err(|e| {
        NetError::IntegrationError(format!(
            "failed to spline {label} '{}': {e}",
            rxn.name
        ))
    })?;
    Ok(Arc::new(coeffs))
}

fn build_rate_tables_with_overrides(
    reactions: &[ReactionInfo],
    rev_map: &HashMap<usize, usize>,
    rate_overrides: &[(String, Arc<RateTable1D>)],
) -> Result<Vec<Arc<Vec<CubicCoeffs>>>, NetError> {
    let cat = RatesCatalog::builtin();
    let mut override_map: HashMap<String, Arc<RateTable1D>> =
        HashMap::with_capacity(rate_overrides.len());
    for (name, tbl) in rate_overrides {
        let trimmed = name.trim();
        if trimmed.is_empty() {
            continue;
        }
        let known_in_net = reactions.iter().any(|r| r.name == trimmed);
        if !known_in_net && cat.reaction_id_by_name(trimmed).is_none() {
            return Err(NetError::InvalidReactionOrIso(format!(
                "unknown reaction '{trimmed}' in filename_of_special_rate"
            )));
        }
        override_map.insert(trimmed.to_string(), Arc::clone(tbl));
    }

    let id_to_name: HashMap<usize, &str> = reactions
        .iter()
        .map(|r| (r.id, r.name.as_str()))
        .collect();
    let override_infos: Vec<(&str, &ReactionInfo)> = override_map
        .keys()
        .filter_map(|name| {
            reactions
                .iter()
                .find(|r| r.name == *name)
                .or_else(|| {
                    cat.reaction_id_by_name(name)
                        .and_then(|id| cat.reaction_by_id(id).ok())
                })
                .map(|info| (name.as_str(), info))
        })
        .collect();

    let find_reverse_name = |rxn: &ReactionInfo| -> Option<String> {
        if let Some(&r_id) = rev_map.get(&rxn.id) {
            if let Some(&r_name) = id_to_name.get(&r_id) {
                return Some(r_name.to_string());
            }
        }
        if !override_map.is_empty() {
            for &(ov_name, ov_info) in &override_infos {
                if reactions_are_stoichiometric_reverses(rxn, ov_info) {
                    return Some(ov_name.to_string());
                }
            }
        }
        None
    };

    let mut custom_indices: Vec<(usize, Option<String>)> = Vec::new();
    let mut default_rxns: Vec<&ReactionInfo> = Vec::new();
    for (idx, rxn) in reactions.iter().enumerate() {
        let rev_name = find_reverse_name(rxn);
        let needs_custom = !override_map.is_empty()
            && (override_map.contains_key(&rxn.name)
                || rev_name
                    .as_deref()
                    .is_some_and(|rn| override_map.contains_key(rn)));
        if needs_custom {
            custom_indices.push((idx, rev_name));
        } else {
            default_rxns.push(rxn);
        }
    }

    let cache_mutex = RATTAB_CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let mut uncached = Vec::new();
    {
        let guard = cache_mutex.lock().map_err(|e| {
            NetError::IntegrationError(format!(
                "rate table cache mutex poisoned: {e}"
            ))
        })?;
        for rxn in &default_rxns {
            if !guard.contains_key(&rxn.name) {
                uncached.push((*rxn).clone());
            }
        }
    }
    if !uncached.is_empty() {
        let logttab = global_logttab();
        let ttab = global_ttab();
        let built: Vec<(String, Arc<Vec<CubicCoeffs>>)> = uncached
            .par_iter()
            .map(|rxn| {
                let arc_coeffs = spline_reaction_rate_table(
                    rxn,
                    logttab,
                    ttab,
                    "reaction",
                    |t, tf| eval_reaction_raw(cat, rxn, t, tf),
                )?;
                Ok((rxn.name.clone(), arc_coeffs))
            })
            .collect::<Result<Vec<_>, NetError>>()?;
        let mut guard = cache_mutex.lock().map_err(|e| {
            NetError::IntegrationError(format!(
                "rate table cache mutex poisoned: {e}"
            ))
        })?;
        for (name, arc_c) in built {
            guard.insert(name, arc_c);
        }
    }

    let custom_built: HashMap<usize, Arc<Vec<CubicCoeffs>>> =
        if custom_indices.is_empty() {
            HashMap::new()
        } else {
            let logttab = global_logttab();
            let ttab = global_ttab();
            custom_indices
                .par_iter()
                .map(|(rxn_idx, rev_name)| {
                    let rxn = &reactions[*rxn_idx];
                    let arc_coeffs = spline_reaction_rate_table(
                        rxn,
                        logttab,
                        ttab,
                        "overridden reaction",
                        |t, tf| {
                            eval_reaction_raw_with_overrides(
                                cat,
                                rxn,
                                t,
                                tf,
                                &override_map,
                                rev_name.as_deref(),
                            )
                        },
                    )?;
                    Ok((*rxn_idx, arc_coeffs))
                })
                .collect::<Result<HashMap<_, _>, NetError>>()?
        };

    let guard = cache_mutex.lock().map_err(|e| {
        NetError::IntegrationError(format!(
            "rate table cache mutex poisoned: {e}"
        ))
    })?;
    reactions
        .iter()
        .enumerate()
        .map(|(idx, rxn)| {
            if let Some(arc_c) = custom_built.get(&idx) {
                Ok(Arc::clone(arc_c))
            } else {
                guard
                    .get(&rxn.name)
                    .map(Arc::clone)
                    .ok_or_else(|| NetError::MissingReaction(rxn.name.clone()))
            }
        })
        .collect()
}

