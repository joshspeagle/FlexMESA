const AIC_STATES_DATA: &str = include_str!("../data/aic.states");
const AIC_TRANS_DATA: &str = include_str!("../data/aic.transitions");

fn check_wd_aic_row(
    fails: &mut Vec<String>,
    max_ulp: &mut u64,
    cat: &RatesCatalog,
    parsed_ec: &EcaptureTables,
    row: &WdAicOracle,
) {
    let &(cmode, lhs, rhs, pt, ref inp, ref exp) = row;
    let (_, _, _, zl, zr, qt) = cat
        .special_ecapture_data(lhs, rhs)
        .expect("special_ecapture_data");
    let (_, _, _, pzl, pzr, pqt) =
        parsed_ec.pair_data(lhs, rhs).expect("parsed pair_data");
    assert_eq!(zl, pzl);
    assert_eq!(zr, pzr);
    assert_eq!(qt.to_bits(), pqt.to_bits());
    let (wmui, wvs) = if cmode == 0 {
        (CoulombMuiOption::None, CoulombVsOption::None)
    } else {
        (CoulombMuiOption::Pcr2009, CoulombVsOption::Itoh2002)
    };
    let ev = eval_ecapture_pair_with_derivs(
        lhs,
        rhs,
        f64h(inp[0]),
        f64h(inp[1]),
        f64h(inp[2]),
        f64h(inp[3]),
        f64h(inp[4]),
        wmui,
        wvs,
        f64h(inp[5]),
        f64h(inp[6]),
    )
    .expect("eval_ecapture_pair_with_derivs");
    let ev_tbl = eval_ecapture_pair_with_tables(
        parsed_ec,
        lhs,
        rhs,
        f64h(inp[0]),
        f64h(inp[1]),
        f64h(inp[2]),
        f64h(inp[3]),
        f64h(inp[4]),
        wmui,
        wvs,
        f64h(inp[5]),
        f64h(inp[6]),
    )
    .expect("eval_ecapture_pair_with_tables");
    assert_eq!(
        ev, ev_tbl,
        "builtin vs from_str_pair mismatch for {lhs}->{rhs} pt={pt}"
    );
    let ev_zero = eval_ecapture_pair(
        lhs,
        rhs,
        f64h(inp[0]),
        f64h(inp[1]),
        f64h(inp[2]),
        wmui,
        wvs,
        f64h(inp[5]),
        f64h(inp[6]),
    )
    .expect("eval_ecapture_pair");
    assert_eq!(ev_zero.lambda.to_bits(), ev.lambda.to_bits());
    assert_eq!(ev_zero.q.to_bits(), ev.q.to_bits());
    assert_eq!(ev_zero.qneu.to_bits(), ev.qneu.to_bits());
    let ctx = format!("cmode={cmode} {lhs}->{rhs} pt={pt}");
    let got = [
        ev.lambda,
        ev.dlambda_dln_t,
        ev.dlambda_dln_rho,
        ev.q,
        ev.dq_dln_t,
        ev.dq_dln_rho,
        ev.qneu,
        ev.dqneu_dln_t,
        ev.dqneu_dln_rho,
    ];
    let names = ["lam", "dlT", "dlR", "q", "dqT", "dqR", "qn", "dqnT", "dqnR"];
    for idx in 0..9 {
        check_field(fails, max_ulp, &ctx, names[idx], got[idx], exp[idx], 0);
    }
}

#[test]
fn test_wd_aic_ecapture_all_64_oracles_and_derivs() {
    math_init();
    with_numerics_mode(NumericsMode::Strict, || {
        let builtin_ec = EcaptureTables::builtin();
        let parsed_ec =
            EcaptureTables::from_str_pair(AIC_STATES_DATA, AIC_TRANS_DATA)
                .expect("parse embedded aic tables");
        let cat = RatesCatalog::builtin();
        assert_eq!(builtin_ec.states().len(), 6);
        assert_eq!(builtin_ec.transitions().len(), 8);
        let mut fails = Vec::new();
        let mut max_ulp = 0_u64;
        for row in WD_AIC_ORACLES {
            check_wd_aic_row(&mut fails, &mut max_ulp, cat, &parsed_ec, row);
        }
        assert!(
            fails.is_empty(),
            "wd_aic ecapture parity failures (max_ulp={max_ulp}, n={}):\n{}",
            fails.len(),
            fails
                .iter()
                .take(20)
                .cloned()
                .collect::<Vec<_>>()
                .join("\n")
        );
    });
}

