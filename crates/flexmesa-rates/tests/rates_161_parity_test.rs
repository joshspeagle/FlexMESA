#[test]
fn test_suzuki_all_69_tables_and_eval_parity() {
    math_init();
    with_numerics_mode(NumericsMode::Strict, || {
        let cat = RatesCatalog::builtin();
        let mut fails = Vec::new();
        let mut max_ulp = 0_u64;
        for &(lhs, rhs, nt, ny, hd, hc, d0, d1, ref exp) in SUZUKI_ORACLES {
            let tab = cat.suzuki_by_pair(lhs, rhs).unwrap_or_else(|| {
                panic!("missing suzuki table for ({lhs}, {rhs})")
            });
            assert_eq!(tab.logts.len(), nt, "logts len for ({lhs}, {rhs})");
            assert_eq!(tab.lyerhos.len(), ny, "lyerhos len for ({lhs}, {rhs})");
            assert_eq!(tab.has_decay, hd, "has_decay for ({lhs}, {rhs})");
            assert_eq!(tab.has_capture, hc, "has_capture for ({lhs}, {rhs})");
            if hd {
                assert_eq!(
                    tab.decay_rate[0].to_bits(),
                    d0,
                    "decay[0] for ({lhs}, {rhs})"
                );
            }
            if hc {
                assert_eq!(
                    tab.capture_rate[nt * ny - 1].to_bits(),
                    d1,
                    "capture[end] for ({lhs}, {rhs})"
                );
            }
            let ev =
                eval_weak_reaction_pair(lhs, rhs, 2.5, 5.0e7, true).unwrap();
            let ctx = format!("{lhs}->{rhs}");
            check_field(
                &mut fails,
                &mut max_ulp,
                &ctx,
                "lambda",
                ev.lambda,
                exp[0],
                0,
            );
            check_field(
                &mut fails,
                &mut max_ulp,
                &ctx,
                "dlT",
                ev.dlambda_dln_t,
                exp[1],
                0,
            );
            check_field(
                &mut fails,
                &mut max_ulp,
                &ctx,
                "dlR",
                ev.dlambda_dln_rho,
                exp[2],
                0,
            );
            check_field(&mut fails, &mut max_ulp, &ctx, "q", ev.q, exp[3], 0);
            check_field(
                &mut fails,
                &mut max_ulp,
                &ctx,
                "qneu",
                ev.qneu,
                exp[4],
                0,
            );
            check_field(
                &mut fails,
                &mut max_ulp,
                &ctx,
                "dqnT",
                ev.dqneu_dln_t,
                exp[5],
                0,
            );
            check_field(
                &mut fails,
                &mut max_ulp,
                &ctx,
                "dqnR",
                ev.dqneu_dln_rho,
                exp[6],
                0,
            );
        }
        assert!(
            fails.is_empty(),
            "Suzuki 69 parity failures (max_ulp={max_ulp}, n={}):\n{}",
            fails.len(),
            fails
                .iter()
                .take(20)
                .cloned()
                .collect::<Vec<_>>()
                .join("\n")
        );
    });
}

