#[test]
fn test_all_316_raw_rates_four_temperatures_parity() {
    math_init();
    with_numerics_mode(NumericsMode::Strict, || {
        let log_ts = [5.5_f64, 7.3_f64, 8.5_f64, 9.8_f64];
        let tfs: Vec<TFactors> = log_ts
            .iter()
            .map(|&lt| TFactors::from_log_t(lt, flexmesa_math::exp10(lt)))
            .collect();
        let mut fails = Vec::new();
        let mut max_ulp = 0_u64;
        for &(ir, op_code, ref exp) in RAW_ORACLES {
            for k in 0..4 {
                let got = set_raw_rate(ir, tfs[k].temp, &tfs[k])
                    .unwrap_or_else(|e| {
                        panic!("set_raw_rate ir={ir} k={k}: {e}")
                    });
                let ctx = format!("RAW ir={ir} op={op_code} k={k}");
                check_field(
                    &mut fails,
                    &mut max_ulp,
                    &ctx,
                    "rate",
                    got,
                    exp[k],
                    0,
                );
            }
        }
        assert!(
            fails.is_empty(),
            "RAW 316x4 parity failures (max_ulp={max_ulp}, n={}):\n{}",
            fails.len(),
            fails
                .iter()
                .take(30)
                .cloned()
                .collect::<Vec<_>>()
                .join("\n")
        );
    });
}

#[test]
fn test_ecapture_custom_tables_aliases_and_bounds() {
    math_init();
    with_numerics_mode(NumericsMode::Strict, || {
        let states_src = concat!(
            "! custom states with Fortran D exponents and al26 isomer alias\n",
            "al-6 2\n",
            "0.0d0 5.0d0\n",
            "0.228D0 0.0D0\n",
            "mg26 1\n",
            "0.0 0.0\n",
        );
        let trans_src = "al-6 mg26 1\n2 1 5.0d0\n";
        let custom =
            EcaptureTables::from_str_pair(states_src, trans_src).unwrap();
        let (_, _, tr, zl, zr, _) = custom.pair_data("al26-1", "mg26").unwrap();
        assert_eq!(tr.len(), 1);
        assert_eq!(zl, 13.0);
        assert_eq!(zr, 12.0);
        let ev = eval_ecapture_pair_with_tables(
            &custom,
            "al26-1",
            "mg26",
            1.2,
            7.2e9,
            28.0,
            -27.5,
            9.4,
            CoulombMuiOption::Pcr2009,
            CoulombVsOption::Itoh2002,
            12.0,
            24.0,
        )
        .unwrap();
        assert!(ev.lambda.is_finite() && ev.lambda >= 0.0);
        let bad_trans = "al-6 mg26 1\n9 1 5.0\n";
        assert!(EcaptureTables::from_str_pair(states_src, bad_trans).is_err());
    });
}
