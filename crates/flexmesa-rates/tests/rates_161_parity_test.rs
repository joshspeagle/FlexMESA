const fn f64h(bits: u64) -> f64 {
    f64::from_bits(bits)
}

fn ulp_diff(a: f64, b: f64) -> u64 {
    if a.is_nan() && b.is_nan() {
        return 0;
    }
    if a.to_bits() == b.to_bits() || (a + 0.0).to_bits() == (b + 0.0).to_bits()
    {
        return 0;
    }
    let ua = a.to_bits().cast_signed();
    let ub = b.to_bits().cast_signed();
    let ma = if ua < 0 { i64::MIN - ua } else { ua };
    let mb = if ub < 0 { i64::MIN - ub } else { ub };
    ma.abs_diff(mb)
}

fn check_field(
    fails: &mut Vec<String>,
    max_ulp: &mut u64,
    ctx: &str,
    field: &str,
    got: f64,
    exp_bits: u64,
    tol_ulp: u64,
) {
    let exp = f64h(exp_bits);
    let u = ulp_diff(got, exp);
    if u > *max_ulp {
        *max_ulp = u;
    }
    if u > tol_ulp {
        fails.push(format!(
            "{ctx} {field}: got=0x{:016X} ({got:.16e}) exp=0x{:016X} ({exp:.16e}) ulp={u} > {tol_ulp}",
            got.to_bits(), exp_bits
        ));
    }
}

