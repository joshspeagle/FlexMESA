/// Pre-hashed lookup sets for single-star namelist validation.
#[derive(Debug)]
pub struct StarControlInventory {
    /// Supported `&star_job` keys wired into runtime initialization/evolution.
    pub star_job_supported: HashSet<&'static str>,
    /// Parsed-but-unused `&star_job` fields flagged by default (`#147`).
    pub star_job_unused: HashSet<&'static str>,
    /// Headless `&star_job` GUI flags treated as no-ops (`DECISIONS #25`).
    pub star_job_headless_gui_flags: HashSet<&'static str>,
    /// Supported `&eos` keys.
    pub eos_supported: HashSet<&'static str>,
    /// Supported `&kap` keys.
    pub kap_supported: HashSet<&'static str>,
    /// Supported `&controls` keys wired into physics/solver/output execution.
    pub controls_supported: HashSet<&'static str>,
    /// Parsed-but-unused `&controls` fields flagged by default (`#147`).
    pub controls_unused: HashSet<&'static str>,
    /// `&star_job` keys that only write to the terminal (`DECISIONS #26`).
    pub star_job_terminal_output: HashSet<&'static str>,
    /// `&controls` keys that only write to the terminal (`DECISIONS #26`).
    pub controls_terminal_output: HashSet<&'static str>,
}

static INVENTORY: OnceLock<StarControlInventory> = OnceLock::new();

/// Returns the cached [`StarControlInventory`] for single-star sections.
#[must_use]
pub fn supported_star_control_inventory() -> &'static StarControlInventory {
    INVENTORY.get_or_init(|| StarControlInventory {
        star_job_supported: STAR_JOB_SUPPORTED.iter().copied().collect(),
        star_job_unused: STAR_JOB_UNUSED.iter().copied().collect(),
        star_job_headless_gui_flags: STAR_JOB_HEADLESS_GUI
            .iter()
            .copied()
            .collect(),
        eos_supported: EOS_SUPPORTED.iter().copied().collect(),
        kap_supported: KAP_SUPPORTED.iter().copied().collect(),
        controls_supported: CONTROLS_SUPPORTED.iter().copied().collect(),
        controls_unused: CONTROLS_UNUSED.iter().copied().collect(),
        star_job_terminal_output: STAR_JOB_TERMINAL_OUTPUT
            .iter()
            .copied()
            .collect(),
        controls_terminal_output: CONTROLS_TERMINAL_OUTPUT
            .iter()
            .copied()
            .collect(),
    })
}

