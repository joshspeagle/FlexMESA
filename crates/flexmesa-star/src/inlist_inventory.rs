/// Copies a single-star case directory `src_case` to `dst_case` and strips
/// unsupported or unused namelist sections/keys so strict `#147` loading
/// passes cleanly without setting `allow_unsupported_controls = true`.
///
/// # Errors
/// Returns [`StarError::IoError`] if copying or rewriting files fails.
pub fn copy_cleaned_star_case(
    src_case: &Path,
    dst_case: &Path,
) -> Result<(), StarError> {
    let inv = supported_star_control_inventory();
    copy_cleaned_case_dir(
        src_case,
        dst_case,
        &|sec| {
            matches!(
                sec,
                "star_job" | "eos" | "kap" | "colors" | "controls" | "pgstar"
            )
        },
        &|sec, key| match sec {
            "star_job" => {
                is_include_key(sec, key)
                    || inv.star_job_supported.contains(key)
                    || inv.star_job_headless_gui_flags.contains(key)
                    || inv.star_job_terminal_output.contains(key)
            }
            "eos" => {
                is_include_key(sec, key)
                    || inv.eos_supported.contains(key)
                    || inv.eos_terminal_output.contains(key)
            }
            "kap" => {
                is_include_key(sec, key)
                    || inv.kap_supported.contains(key)
                    || inv.kap_terminal_output.contains(key)
            }
            "colors" => {
                is_include_key(sec, key)
                    || inv.colors_supported.contains(key)
                    || inv.colors_terminal_output.contains(key)
            }
            "controls" => {
                is_include_key(sec, key)
                    || inv.controls_supported.contains(key)
                    || inv.controls_terminal_output.contains(key)
            }
            "pgstar" => {
                is_include_key(sec, key)
                    || upstream_section_keys("pgstar")
                        .is_some_and(|set| set.contains(key))
            }
            _ => false,
        },
    )
    .map_err(|e| StarError::IoError(e.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_star_control_inventory_sets_are_disjoint_and_lowercase() {
        let inv = supported_star_control_inventory();
        for key in inv
            .star_job_supported
            .iter()
            .chain(inv.star_job_unused.iter())
            .chain(inv.star_job_headless_gui_flags.iter())
            .chain(inv.eos_supported.iter())
            .chain(inv.kap_supported.iter())
            .chain(inv.colors_supported.iter())
            .chain(inv.colors_unused.iter())
            .chain(inv.controls_supported.iter())
            .chain(inv.controls_unused.iter())
        {
            assert_eq!(*key, key.to_ascii_lowercase());
        }
        assert!(inv.colors_supported.is_disjoint(&inv.colors_unused));
        assert!(inv
            .colors_supported
            .is_disjoint(&inv.colors_terminal_output));
        for key in &inv.colors_supported {
            assert!(
                upstream_section_keys("colors")
                    .is_some_and(|set| set.contains(key)),
                "{key} is not an upstream &colors key"
            );
        }
        assert!(inv.star_job_supported.is_disjoint(&inv.star_job_unused));
        assert!(inv
            .star_job_supported
            .is_disjoint(&inv.star_job_headless_gui_flags));
        assert!(inv
            .star_job_unused
            .is_disjoint(&inv.star_job_headless_gui_flags));
        assert!(inv.controls_supported.is_disjoint(&inv.controls_unused));
        assert!(inv.eos_supported.is_disjoint(&inv.eos_terminal_output));
        assert!(inv.kap_supported.is_disjoint(&inv.kap_terminal_output));
        for key in &inv.eos_terminal_output {
            assert_eq!(*key, key.to_ascii_lowercase());
            assert!(
                upstream_section_keys("eos")
                    .is_some_and(|set| set.contains(key)),
                "{key} is not an upstream &eos key"
            );
        }
        for key in &inv.kap_terminal_output {
            assert_eq!(*key, key.to_ascii_lowercase());
            assert!(
                upstream_section_keys("kap")
                    .is_some_and(|set| set.contains(key)),
                "{key} is not an upstream &kap key"
            );
        }
        for (terminal, others) in [
            (
                &inv.star_job_terminal_output,
                [&inv.star_job_supported, &inv.star_job_unused],
            ),
            (
                &inv.controls_terminal_output,
                [&inv.controls_supported, &inv.controls_unused],
            ),
        ] {
            for key in terminal {
                assert_eq!(*key, key.to_ascii_lowercase());
            }
            for other in others {
                assert!(terminal.is_disjoint(other));
            }
        }
        for key in &inv.star_job_terminal_output {
            assert!(
                upstream_section_keys("star_job")
                    .is_some_and(|set| set.contains(key)),
                "{key} is not an upstream &star_job key"
            );
        }
        for key in &inv.controls_terminal_output {
            assert!(
                upstream_section_keys("controls")
                    .is_some_and(|set| set.contains(key)),
                "{key} is not an upstream &controls key"
            );
        }
    }
}
