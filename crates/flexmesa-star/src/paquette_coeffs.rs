//! Atomic diffusion collision integrals and Burgers resistance coefficients
//! following Paquette, Pelletier, Fontaine & Michaud (1986, ApJS 61, 177),
//! ported from MESA `26.4.1` `star/private/paquette_coeffs.f90`.

use flexmesa_const::{AMU, BOLTZM, PI4, QE};

/// Evaluates screened Coulomb collision integrals and Burgers resistance
/// coefficients `(Ddiff, Kdiff, Zdiff, Zdiff1, Zdiff2, Ath)` for `nn` species
/// (ions `0..nn - 1` plus electrons at index `nn - 1`) in exact MESA `26.4.1`
/// order (`star/private/paquette_coeffs.f90:58-255`).
///
/// Output matrices are stored in row-major `(nn, nn)` order where element
/// `(nref, i)` is at `nref * nn + i`, matching Fortran `(NREF, I)`.
#[allow(
    clippy::too_many_arguments,
    clippy::similar_names,
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss
)]
pub fn paquette_coefficients(
    _rho: f64,
    t: f64,
    nn: usize,
    can1: &[f64],
    kzn1: &[f64],
    na1: &[f64],
    ddiff: &mut [f64],
    kdiff: &mut [f64],
    zdiff: &mut [f64],
    zdiff1: &mut [f64],
    zdiff2: &mut [f64],
    ath: &mut [f64],
) {
    debug_assert!(nn >= 1);
    let elec = nn - 1;
    let ne = na1[elec];
    let mut ni = 0.0_f64;
    let mut nzz = 0.0_f64;
    for i in 0..elec {
        ni += na1[i];
        nzz += kzn1[i] * kzn1[i] * na1[i];
    }

    let kt = BOLTZM * t;
    let lambda_i2 = flexmesa_math::pow(3.0 / (PI4 * ni), 2.0 / 3.0);
    let lambda_d2 = kt / (PI4 * QE * QE * (ne + nzz));
    let lambda2 = lambda_d2.max(lambda_i2);

    let mut omega2 = vec![0.0_f64; nn];
    let mut f22 = 1.0_f64;

    // Self-collision integrals Omega^{(2,2)}_{ss} (paquette_coeffs.f90:105-147).
    for i in 0..nn {
        let nref = i;
        let gamma2 =
            flexmesa_math::pow2(4.0 * kt / (QE * QE * kzn1[nref])) * lambda2;
        let gamma_st2 = gamma2 / flexmesa_math::pow2(kzn1[i]);
        let a = can1[i] * can1[nref] / (can1[i] + can1[nref]);
        let eps_st =
            PI4 * lambda2 / gamma_st2 * (2.0 * kt / (PI4 * AMU * a)).sqrt();
        let e_psi_st = flexmesa_math::log(1.0 + gamma_st2);
        let mut psi_st = flexmesa_math::log(e_psi_st);

        let is_attractive =
            (i == elec || nref == elec) && nref != i;
        if psi_st <= 3.0 {
            psi_st = (-7.0_f64).max(psi_st);
            let n_idx = 1_usize
                + 49_usize.min(((psi_st + 7.0) / 0.2).floor().max(0.0) as usize);
            let n_f = n_idx as f64;
            let dpsi_n1 = (-7.2 + 0.2 * (n_f + 1.0)) - psi_st;
            let dpsi_n = psi_st - (-7.2 + 0.2 * n_f);
            let base = (n_idx - 1) * 4;
            let tbl = if is_attractive { &DDAT } else { &DD };
            f22 = flexmesa_math::exp(
                tbl[base] * dpsi_n1 * dpsi_n1 * dpsi_n1
                    + tbl[base + 1] * dpsi_n * dpsi_n * dpsi_n
                    + tbl[base + 2] * dpsi_n1
                    + tbl[base + 3] * dpsi_n,
            );
        } else if psi_st > 3.0 && psi_st < 4.0 {
            if is_attractive {
                f22 = 2.08699 * e_psi_st - 5.81444;
            } else {
                f22 = 1.99016 * e_psi_st - 4.56958;
            }
        } else if psi_st >= 4.0 {
            f22 = 1.99016 * e_psi_st - 4.56958;
        }
        omega2[i] = eps_st * f22;
    }

    // Pairwise collision integrals and Burgers resistance coefficients
    // (paquette_coeffs.f90:149-252).
    let mut f1 = [0.0_f64; 3];
    for k in 0..nn {
        let nref = k;
        let gamma2 =
            flexmesa_math::pow2(4.0 * kt / (QE * QE * kzn1[nref])) * lambda2;
        for i in 0..nn {
            let gamma_st2 = gamma2 / flexmesa_math::pow2(kzn1[i]);
            let a = can1[i] * can1[nref] / (can1[i] + can1[nref]);
            let eps_st =
                PI4 * lambda2 / gamma_st2 * (2.0 * kt / (PI4 * AMU * a)).sqrt();
            let e_psi_st = flexmesa_math::log(1.0 + gamma_st2);
            let mut psi_st = flexmesa_math::log(e_psi_st);

            let is_attractive =
                (i == elec || nref == elec) && nref != i;
            if psi_st <= 3.0 {
                psi_st = (-7.0_f64).max(psi_st);
                let n_idx = 1_usize
                    + 49_usize
                        .min(((psi_st + 7.0) / 0.2).floor().max(0.0) as usize);
                let n_f = n_idx as f64;
                let dpsi_n1 = (-7.2 + 0.2 * (n_f + 1.0)) - psi_st;
                let dpsi_n = psi_st - (-7.2 + 0.2 * n_f);
                let dd_base = (n_idx - 1) * 4;
                if is_attractive {
                    for j in 0..3 {
                        let dc_base = (j * 50 + (n_idx - 1)) * 4;
                        f1[j] = flexmesa_math::exp(
                            DCAT[dc_base] * dpsi_n1 * dpsi_n1 * dpsi_n1
                                + DCAT[dc_base + 1] * dpsi_n * dpsi_n * dpsi_n
                                + DCAT[dc_base + 2] * dpsi_n1
                                + DCAT[dc_base + 3] * dpsi_n,
                        );
                    }
                    f22 = flexmesa_math::exp(
                        DDAT[dd_base] * dpsi_n1 * dpsi_n1 * dpsi_n1
                            + DDAT[dd_base + 1] * dpsi_n * dpsi_n * dpsi_n
                            + DDAT[dd_base + 2] * dpsi_n1
                            + DDAT[dd_base + 3] * dpsi_n,
                    );
                } else {
                    for j in 0..3 {
                        let dc_base = (j * 50 + (n_idx - 1)) * 4;
                        f1[j] = flexmesa_math::exp(
                            DC[dc_base] * dpsi_n1 * dpsi_n1 * dpsi_n1
                                + DC[dc_base + 1] * dpsi_n * dpsi_n * dpsi_n
                                + DC[dc_base + 2] * dpsi_n1
                                + DC[dc_base + 3] * dpsi_n,
                        );
                    }
                    f22 = flexmesa_math::exp(
                        DD[dd_base] * dpsi_n1 * dpsi_n1 * dpsi_n1
                            + DD[dd_base + 1] * dpsi_n * dpsi_n * dpsi_n
                            + DD[dd_base + 2] * dpsi_n1
                            + DD[dd_base + 3] * dpsi_n,
                    );
                }
            } else if psi_st > 3.0 && psi_st < 4.0 {
                if is_attractive {
                    f1[0] = 1.01101 * e_psi_st - 3.19815;
                    f1[1] = 1.04230 * e_psi_st - 1.89637;
                    f1[2] = 2.15672 * e_psi_st - 2.81038;
                    f22 = 2.08699 * e_psi_st - 5.81444;
                } else {
                    f1[0] = 1.00141 * e_psi_st - 3.18209;
                    f1[1] = 0.99559 * e_psi_st - 1.29553;
                    f1[2] = 1.99814 * e_psi_st - 0.64413;
                    f22 = 1.99016 * e_psi_st - 4.56958;
                }
            } else if psi_st >= 4.0 {
                f1[0] = 1.00141 * e_psi_st - 3.18209;
                f1[1] = 0.99559 * e_psi_st - 1.29553;
                f1[2] = 1.99814 * e_psi_st - 0.64413;
                f22 = 1.99016 * e_psi_st - 4.56958;
            }

            let omega1_0 = eps_st * f1[0];
            let omega1_1 = eps_st * f1[1];
            let omega1_2 = eps_st * f1[2];
            let omega22 = eps_st * f22;

            let idx = nref * nn + i;
            let d_first = 3.0 * kt
                / (16.0 * (na1[nref] + na1[i]) * (a * AMU) * omega1_0);

            let aa = omega22 / (5.0 * omega1_0);
            let bb = (5.0 * omega1_1 - omega1_2) / (5.0 * omega1_0);
            let cc = 2.0 * omega1_1 / (5.0 * omega1_0) - 1.0;
            let xs = na1[nref] / (na1[i] + na1[nref]);
            let xt = na1[i] / (na1[i] + na1[nref]);
            let ms = can1[nref] / (can1[nref] + can1[i]);
            let mt = can1[i] / (can1[nref] + can1[i]);
            let pst = 3.0 * (ms - mt) * (ms - mt) + 4.0 * ms * mt * aa;
            let ee = kt / (8.0 * ms * mt * omega1_0);
            let ps = 8.0 * ms * ee * omega2[nref] / (5.0 * kt);
            let pt = 8.0 * mt * ee * omega2[i] / (5.0 * kt);
            let ss = ms * ps - mt * (3.0 * (mt - ms) + 4.0 * ms * aa);
            let st = mt * pt - ms * (3.0 * (ms - mt) + 4.0 * mt * aa);
            let qs = ps
                * (6.0 * mt * mt + 5.0 * ms * ms - 4.0 * ms * ms * bb
                    + 8.0 * ms * mt * aa);
            let qt = pt
                * (6.0 * ms * ms + 5.0 * mt * mt - 4.0 * mt * mt * bb
                    + 8.0 * mt * ms * aa);
            let qst = 3.0 * (ms - mt) * (ms - mt) * (5.0 - 4.0 * bb)
                + 4.0 * ms * mt * aa * (11.0 - 4.0 * bb)
                + 2.0 * ps * pt;
            let delta = 5.0
                * cc
                * cc
                * (ms * ms * ps * xs * xs
                    + mt * mt * pt * xt * xt
                    + pst * xs * xt)
                / (xs * xs * qs + xt * xt * qt + xs * xt * qst);

            ddiff[idx] = d_first / (1.0 - delta);
            ath[idx] = 5.0 * cc * (xs * ss - xt * st)
                / (xs * xs * qs + xt * xt * qt + xs * xt * qst);
            kdiff[idx] =
                16.0 / 3.0 * na1[nref] * na1[i] * (a * AMU) * omega1_0;
            zdiff[idx] = -cc;
            zdiff1[idx] = -2.0 * bb + 2.5;
            zdiff2[idx] = 5.0 * aa;
        }
    }
}

