//! MESA `26.4.1` IEEE-754 hex parity tests for element diffusion (`#407`, `#156`).
//!
//! Exercises [`do_element_diffusion_step`] in `NumericsMode::Strict` across
//! coarsened 24-zone MESA `26.4.1` profiles covering all four diffusion test-suite
//! regimes (`1.5M_with_diffusion`, `wd_cool_0.6M`, `wd_diffusion`, and
//! `diffusion_smoothness`), plus exact face-gradient IEEE-754 hex vectors from the
//! full models verifying the `PI4 * (r_k * r_k)` operator precedence fix matching
//! `star/private/element_diffusion.f90:562` (`area = pi4*s% r(k)**2`).

