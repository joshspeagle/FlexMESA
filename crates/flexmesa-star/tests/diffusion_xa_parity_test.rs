fn signed_magnitude(bits: u64) -> i128 {
    if (bits >> 63) != 0 {
        -i128::from(bits ^ (1_u64 << 63))
    } else {
        i128::from(bits)
    }
}

fn ulp_distance(actual: f64, expected: f64) -> u64 {
    if actual.is_nan() || expected.is_nan() {
        return if actual.is_nan() && expected.is_nan() {
            0
        } else {
            u64::MAX
        };
    }
    let a = signed_magnitude(actual.to_bits());
    let b = signed_magnitude(expected.to_bits());
    u64::try_from((a - b).unsigned_abs()).unwrap_or(u64::MAX)
}

#[derive(Clone, Copy)]
struct CaseFixture {
    name: &'static str,
    nz: usize,
    species: usize,
    dt_bits: u64,
    mstar_bits: u64,
    m_center_bits: u64,
    r_center_bits: u64,
    expected_steps: usize,
    expected_iters: usize,
    isos: &'static [&'static str],
    // Per zone: [eta, phase, grav, gam, q, dq, m, m_grav, peos, chi_t, chi_rho,
    //            gradt, t, ln_t, rho, lnd, r, rmid, dm, dm_bar, abar, ye,
    //            lnfree_e, lum, d_mix, cgrav, mixing_type_f64]
    zones_bits: &'static [[u64; 27]],
    xa_pre_bits: &'static [u64],
    xa_post_bits: &'static [u64],
}

fn build_controls(case_name: &str) -> StarControls {
    let mut c = StarControls {
        do_element_diffusion: true,
        ..StarControls::default()
    };
    c.diffusion.diffusion_use_cgs_solver = true;
    c.diffusion.diffusion_dt_limit = 3.15e7;
    c.diffusion.diffusion_t_full_on = 1.0e3;
    c.diffusion.diffusion_t_full_off = 1.0e3;
    c.diffusion.d_mix_ignore_diffusion = 1.0e5;
    c.diffusion.diffusion_v_max = 1.0e-3;
    c.diffusion.diffusion_nsmooth_typical_charge = 10;
    match case_name {
        "1.5M_with_diffusion" => {
            c.diffusion.d_mix_ignore_diffusion = 1.0e2;
            c.diffusion.diffusion_calculates_ionization = true;
            c.diffusion.diffusion_use_full_net = false;
            c.diffusion.diffusion_num_classes = 8;
            c.diffusion.diffusion_class_representative = vec![
                "h1".into(),
                "he3".into(),
                "he4".into(),
                "c12".into(),
                "n14".into(),
                "o16".into(),
                "ne20".into(),
                "mg24".into(),
            ];
            c.diffusion.diffusion_class_a_max =
                vec![2.0, 3.0, 4.0, 12.0, 14.0, 16.0, 20.0, 10000.0];
            c.diffusion.diffusion_use_isolve = true;
            c.diffusion.diffusion_rtol_for_isolve = 1.0e-4;
            c.diffusion.diffusion_atol_for_isolve = 1.0e-5;
            c.diffusion.diffusion_maxsteps_for_isolve = 1000;
            c.diffusion.diffusion_isolve_solver = "ros2_solver".into();
        }
        "wd_cool_0.6M" => {
            c.do_phase_separation = true;
            c.diffusion.diffusion_use_full_net = true;
            c.diffusion.diffusion_calculates_ionization = true;
        }
        "wd_diffusion" => {
            c.diffusion.diffusion_use_full_net = true;
            c.diffusion.diffusion_calculates_ionization = true;
            c.ts_stop.diffusion_steps_hard_limit = 50;
            c.ts_stop.diffusion_iters_hard_limit = 100;
        }
        "diffusion_smoothness" => {
            c.diffusion.diffusion_calculates_ionization = true;
            c.diffusion.diffusion_use_full_net = false;
            c.diffusion.diffusion_num_classes = 4;
            c.diffusion.diffusion_class_representative =
                vec!["h1".into(), "he4".into(), "o16".into(), "fe56".into()];
            c.diffusion.diffusion_class_a_max = vec![2.0, 4.0, 16.0, 10000.0];
            c.diffusion.diffusion_use_isolve = true;
            c.diffusion.diffusion_rtol_for_isolve = 1.0e-4;
            c.diffusion.diffusion_atol_for_isolve = 1.0e-5;
            c.diffusion.diffusion_maxsteps_for_isolve = 1000;
            c.diffusion.diffusion_isolve_solver = "ros2_solver".into();
        }
        other => panic!("unknown fixture {other}"),
    }
    c
}

fn verify_case_zero_ulp(fx: &CaseFixture) {
    with_numerics_mode(NumericsMode::Strict, || {
        let catalog = NuclideCatalog::builtin_ref();
        let chem_id: Vec<usize> = fx
            .isos
            .iter()
            .map(|name| {
                catalog
                    .get_by_name(name)
                    .unwrap_or_else(|| panic!("unknown iso {name}"))
                    .chem_id
            })
            .collect();
        let controls = build_controls(fx.name);
        let mut model = StarModel::new(
            fx.nz,
            chem_id,
            StarJobControls::default(),
            controls,
        );
        let dt = f64::from_bits(fx.dt_bits);
        model.dt = dt;
        model.mstar = f64::from_bits(fx.mstar_bits);
        model.m_center = f64::from_bits(fx.m_center_bits);
        model.r_center = f64::from_bits(fx.r_center_bits);
        for k in 0..fx.nz {
            let z = &fx.zones_bits[k];
            model.eta[k] = f64::from_bits(z[0]);
            model.eos_res[k][I_PHASE] = f64::from_bits(z[1]);
            model.grav[k] = f64::from_bits(z[2]);
            model.gam[k] = f64::from_bits(z[3]);
            model.q[k] = f64::from_bits(z[4]);
            model.dq[k] = f64::from_bits(z[5]);
            model.m[k] = f64::from_bits(z[6]);
            model.m_grav[k] = f64::from_bits(z[7]);
            model.peos[k] = f64::from_bits(z[8]);
            model.chi_t[k] = f64::from_bits(z[9]);
            model.chi_rho[k] = f64::from_bits(z[10]);
            model.gradt[k] = f64::from_bits(z[11]);
            model.t[k] = f64::from_bits(z[12]);
            model.ln_t[k] = f64::from_bits(z[13]);
            model.rho[k] = f64::from_bits(z[14]);
            model.lnd[k] = f64::from_bits(z[15]);
            model.r[k] = f64::from_bits(z[16]);
            model.rmid[k] = f64::from_bits(z[17]);
            model.dm[k] = f64::from_bits(z[18]);
            model.dm_bar[k] = f64::from_bits(z[19]);
            model.abar[k] = f64::from_bits(z[20]);
            model.ye[k] = f64::from_bits(z[21]);
            model.lnfree_e[k] = f64::from_bits(z[22]);
            model.lum[k] = f64::from_bits(z[23]);
            model.d_mix[k] = f64::from_bits(z[24]);
            model.cgrav[k] = f64::from_bits(z[25]);
            let mcode = f64::from_bits(z[26]) as i32;
            model.mixing_type[k] =
                MixingType::from_code(mcode).unwrap_or(MixingType::NoMixing);
        }
        for i in 0..fx.xa_pre_bits.len() {
            model.xa[i] = f64::from_bits(fx.xa_pre_bits[i]);
        }

        do_element_diffusion_step(&mut model, dt).unwrap_or_else(|e| {
            panic!("do_element_diffusion_step failed for {}: {e}", fx.name)
        });

        assert_eq!(
            model.aux.step_hist.num_diffusion_solver_steps, fx.expected_steps,
            "{}: substep count mismatch",
            fx.name
        );
        assert_eq!(
            model.aux.step_hist.num_diffusion_solver_iters, fx.expected_iters,
            "{}: iter count mismatch",
            fx.name
        );

        let sp = fx.species;
        let mut n_diff = 0usize;
        let mut max_ulp = 0u64;
        let mut worst = String::new();
        for k in 0..fx.nz {
            for j in 0..sp {
                let idx = k * sp + j;
                let got = model.xa[idx];
                let want = f64::from_bits(fx.xa_post_bits[idx]);
                let u = ulp_distance(got, want);
                if u > 0 {
                    n_diff += 1;
                    if u > max_ulp {
                        max_ulp = u;
                        worst = format!(
                            "k={} iso={} got={:016X} want={:016X} u={u}",
                            k + 1,
                            fx.isos[j],
                            got.to_bits(),
                            want.to_bits()
                        );
                    }
                }
            }
        }
        assert_eq!(
            n_diff, 0,
            "{}: expected 0 ULP across all {} entries, got {n_diff} diffs (max_ulp={max_ulp}: {worst})",
            fx.name,
            fx.nz * sp
        );
    });
}
