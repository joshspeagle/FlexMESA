fn signed_magnitude(bits: u64) -> i128 {
    if (bits >> 63) != 0 {
        -((bits ^ (1_u64 << 63)) as i128)
    } else {
        bits as i128
    }
}

fn ulp_distance(a: f64, b: f64) -> u64 {
    if a.is_nan() || b.is_nan() {
        return if a.is_nan() && b.is_nan() {
            0
        } else {
            u64::MAX
        };
    }
    if a == 0.0 && b == 0.0 {
        return 0;
    }
    let da = signed_magnitude(a.to_bits());
    let db = signed_magnitude(b.to_bits());
    u64::try_from((da - db).unsigned_abs()).unwrap_or(u64::MAX)
}

fn assert_zero_ulp(label: &str, got: f64, expected_bits: u64) {
    let expected = f64::from_bits(expected_bits);
    let ulp = ulp_distance(got, expected);
    assert_eq!(
        ulp,
        0,
        "{label}: got={:#018x} ({got:.17e}), expected={expected_bits:#018x} ({expected:.17e}), ulp={ulp}",
        got.to_bits(),
    );
}

fn assert_eos_zero_ulp(
    label: &str,
    out: &EosEvalOutput,
    expected_basic: &[[u64; 3]; NUM_EOS_BASIC_RESULTS],
    expected_ddxa: &[[u64; 2]],
) {
    for (j, exp) in expected_basic.iter().enumerate() {
        let name = EOS_BASIC_RESULT_NAMES[j];
        assert_zero_ulp(
            &format!("{label}.res[{j}:{name}]"),
            out.res[j],
            exp[0],
        );
        assert_zero_ulp(
            &format!("{label}.d_dlnd[{j}:{name}]"),
            out.d_dlnd[j],
            exp[1],
        );
        assert_zero_ulp(
            &format!("{label}.d_dln_t[{j}:{name}]"),
            out.d_dln_t[j],
            exp[2],
        );
    }
    if expected_ddxa.is_empty() {
        assert!(out.d_dxa.is_empty(), "{label} expected empty d_dxa");
    } else {
        assert_eq!(out.d_dxa.len(), expected_ddxa.len(), "{label} species len");
        for (s, (got_row, exp_row)) in
            out.d_dxa.iter().zip(expected_ddxa).enumerate()
        {
            assert_zero_ulp(
                &format!("{label}.d_dxa[{s}][0]"),
                got_row[0],
                exp_row[0],
            );
            assert_zero_ulp(
                &format!("{label}.d_dxa[{s}][1]"),
                got_row[1],
                exp_row[1],
            );
        }
    }
}

fn make_cids(names: &[&str]) -> Vec<usize> {
    let cat = NuclideCatalog::builtin_ref();
    names
        .iter()
        .map(|n| cat.get_nuclide_index(n).expect(n))
        .collect()
}

fn f_vec(bits: &[u64]) -> Vec<f64> {
    bits.iter().copied().map(f64::from_bits).collect()
}

