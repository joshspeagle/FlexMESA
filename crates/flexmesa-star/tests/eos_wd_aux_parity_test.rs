//! Hermetic MESA `26.4.1` IEEE-754 binary64 bit-exact parity tests (`0 ULP`)
//! for `Skye`, `HELM`, `FreeEOS`-`Skye` / `HELM`-`Skye` quintic blends, and
//! white-dwarf EOS `AUX` outputs on `star/wd_cool_0.6M` (`Ogata`) and
//! `star/wd_diffusion` (`PC`) (Refs `#421`, `#156`, `#161`, `#140`).

#![forbid(unsafe_code)]
#![allow(
    clippy::cast_precision_loss,
    clippy::too_many_lines,
    clippy::unreadable_literal
)]

use flexmesa_chem::NuclideCatalog;
use flexmesa_eos::{
    eos_dt_get, EosConfig, HelmTable, SkyeSolidMixingRule,
    NUM_EOS_BASIC_RESULTS,
};
use flexmesa_math::{exp10, with_numerics_mode, NumericsMode};
use flexmesa_star::micro::{do_eos, set_basic_vars};
use flexmesa_star::{StarControls, StarJobControls, StarModel};

const WD_SPECIES: [&str; 11] = [
    "h1", "he3", "he4", "c12", "n14", "o16", "o18", "ne20", "ne22", "mg24",
    "si28",
];

const ORACLE_SPECIES: [&str; 7] =
    ["h1", "he4", "c12", "n14", "o16", "ne20", "mg24"];

struct WdZoneCase {
    zone: usize,
    lnd: u64,
    ln_t: u64,
    xa: [u64; 11],
    peos: u64,
    grada: u64,
    chi_rho: u64,
    chi_t: u64,
    cp: u64,
}

struct EosOracleCase {
    label: &'static str,
    use_skye: bool,
    solid_rule: SkyeSolidMixingRule,
    rho: f64,
    temp: f64,
    xa: [f64; 7],
    res: [u64; NUM_EOS_BASIC_RESULTS],
    dlnd: [u64; NUM_EOS_BASIC_RESULTS],
    dlnt: [u64; NUM_EOS_BASIC_RESULTS],
}

fn assert_bits(label: &str, channel: usize, got: f64, expected_bits: u64) {
    let got_bits = got.to_bits();
    assert_eq!(
        got_bits,
        expected_bits,
        "{label} ch={channel}: got=0x{got_bits:016X} ({got:.17e}) expected=0x{expected_bits:016X} ({:.17e})",
        f64::from_bits(expected_bits)
    );
}

fn check_wd_zones(ogata: bool, zones: &[WdZoneCase]) {
    let cat = NuclideCatalog::builtin_ref();
    let chem_id: Vec<usize> = WD_SPECIES
        .iter()
        .map(|name| cat.get_by_name(name).expect("known nuclide").chem_id)
        .collect();
    let sp = chem_id.len();
    let nz = zones.len();

    let mut model = StarModel::new(
        nz,
        chem_id,
        StarJobControls::default(),
        StarControls::default(),
    );
    model.eos_config = EosConfig::default();
    if ogata {
        model.eos_config.skye.skye_solid_mixing_rule =
            SkyeSolidMixingRule::Ogata;
    }
    model.dq.fill(1.0 / (nz as f64));
    model.set_qs();

    for (idx, z) in zones.iter().enumerate() {
        model.lnd[idx] = f64::from_bits(z.lnd);
        model.ln_t[idx] = f64::from_bits(z.ln_t);
        for (j, &bits) in z.xa.iter().enumerate() {
            model.xa[idx * sp + j] = f64::from_bits(bits);
        }
    }

    with_numerics_mode(NumericsMode::Strict, || {
        set_basic_vars(&mut model).expect("set_basic_vars");
        do_eos(&mut model).expect("do_eos");
    });

    let tag = if ogata {
        "wd_cool_0.6M"
    } else {
        "wd_diffusion"
    };
    for (idx, z) in zones.iter().enumerate() {
        let lbl = format!("{tag} k={}", z.zone);
        assert_bits(&lbl, 0, model.peos[idx], z.peos);
        assert_bits(&lbl, 4, model.grada[idx], z.grada);
        assert_bits(&lbl, 7, model.chi_rho[idx], z.chi_rho);
        assert_bits(&lbl, 8, model.chi_t[idx], z.chi_t);
        assert_bits(&lbl, 9, model.cp[idx], z.cp);
    }
}

