fn verify_row_zero_ulp(row: &OracleRow) {
    let cfg = cfg_for_case(row.cfg);
    let log_rho = f64::from_bits(row.lnd) / LN10;
    let log_t = f64::from_bits(row.lnt) / LN10;
    let x = f64::from_bits(row.x);
    let z = f64::from_bits(row.z);
    let xc = f64::from_bits(row.xc);
    let xn = f64::from_bits(row.xn);
    let xo = f64::from_bits(row.xo);
    let xne = f64::from_bits(row.xne);
    let zbar = f64::from_bits(row.zbar);

    let (fl, fh, ft2, rad_kap, rad_dr, rad_dt) =
        get_kap_results_blend_t(&cfg, x, z, xc, xn, xo, xne, log_rho, log_t)
            .unwrap_or_else(|e| {
                panic!("{}: get_kap_results_blend_t: {e}", row.tag)
            });
    assert_eq!(rad_kap.to_bits(), row.kap_rad, "{}: kap_rad", row.tag);
    assert_eq!(rad_dr.to_bits(), row.rad_dlnd, "{}: rad_dlnd", row.tag);
    assert_eq!(rad_dt.to_bits(), row.rad_dlnt, "{}: rad_dlnt", row.tag);
    assert_eq!(ft2.to_bits(), row.frac_type2, "{}: frac_type2", row.tag);

    let out = get_kap_results(
        &cfg,
        zbar,
        x,
        z,
        xc,
        xn,
        xo,
        xne,
        log_rho,
        log_t,
        f64::from_bits(row.lnfree_e),
        f64::from_bits(row.dlnfe_d),
        f64::from_bits(row.dlnfe_t),
        f64::from_bits(row.eta),
        f64::from_bits(row.deta_d),
        f64::from_bits(row.deta_t),
    )
    .unwrap_or_else(|e| panic!("{}: get_kap_results: {e}", row.tag));
    assert_eq!(
        out.kap_fracs[I_FRAC_LOW_T].to_bits(),
        row.frac_low_t,
        "{}: frac_low_t",
        row.tag
    );
    assert_eq!(
        out.kap_fracs[I_FRAC_HIGH_T].to_bits(),
        row.frac_high_t,
        "{}: frac_high_t",
        row.tag
    );
    assert_eq!(
        out.kap_fracs[I_FRAC_TYPE2].to_bits(),
        row.frac_type2,
        "{}: out frac_type2",
        row.tag
    );
    assert_eq!(
        out.kap_fracs[I_FRAC_COMPTON].to_bits(),
        row.frac_compton,
        "{}: frac_compton",
        row.tag
    );
    assert_eq!(
        ((1.0 - out.kap_fracs[I_FRAC_COMPTON]) * fl).to_bits(),
        row.frac_low_t,
        "{}: weighted frac_low_t",
        row.tag
    );
    assert_eq!(
        ((1.0 - out.kap_fracs[I_FRAC_COMPTON]) * fh).to_bits(),
        row.frac_high_t,
        "{}: weighted frac_high_t",
        row.tag
    );

    // Isolate `eval.rs` Compton blending + harmonic conduction combination from
    // `compton.rs`/`conduction.rs` by feeding MESA `26.4.1` `kap_comp`/`kap_cond`.
    let log_rho_ad = AutoDiffReal2VarOrder1 {
        val: log_rho,
        d1: [1.0, 0.0],
    };
    let log_t_ad = AutoDiffReal2VarOrder1 {
        val: log_t,
        d1: [0.0, 1.0],
    };
    let log_r_ad = log_rho_ad - log_t_ad * 3.0 + 18.0;
    let (lt_hi, lr_lo) = kap_tables()
        .expect("kap tables")
        .compton_blend_bounds(&cfg)
        .expect("compton_blend_bounds");
    let lt_lo = lt_hi - 0.5;
    let lr_hi = lr_lo + 0.5;
    let qstep = |u: AutoDiffReal2VarOrder1| -> AutoDiffReal2VarOrder1 {
        let u2 = u * u;
        let u3 = u2 * u;
        -(u3 * ((u * (u * (-6.0) + 15.0)) - 10.0))
    };
    let b_lt = if log_t_ad.val >= lt_hi {
        AutoDiffReal2VarOrder1::from(1.0)
    } else if log_t_ad.val > lt_lo {
        qstep((log_t_ad - lt_lo) / (lt_hi - lt_lo))
    } else {
        AutoDiffReal2VarOrder1::from(0.0)
    };
    let b_lr = if log_r_ad.val <= lr_lo {
        AutoDiffReal2VarOrder1::from(1.0)
    } else if log_r_ad.val <= lr_hi {
        qstep((lr_hi - log_r_ad) / (lr_hi - lr_lo))
    } else {
        AutoDiffReal2VarOrder1::from(0.0)
    };
    let one = AutoDiffReal2VarOrder1::from(1.0);
    let blend = one - (one - b_lt) * (one - b_lr);
    let lkc = if blend.val > 0.0 {
        AutoDiffReal2VarOrder1 {
            val: safe_log10(f64::from_bits(row.kap_comp)),
            d1: [f64::from_bits(row.comp_dlnd), f64::from_bits(row.comp_dlnt)],
        }
    } else {
        AutoDiffReal2VarOrder1::from(0.0)
    };
    let lkr = if blend.val < 1.0 {
        AutoDiffReal2VarOrder1 {
            val: safe_log10(rad_kap),
            d1: [rad_dr, rad_dt],
        }
    } else {
        AutoDiffReal2VarOrder1::from(0.0)
    };
    let lk = blend * lkc + (one - blend) * lkr;
    let kr_iso = exp10(lk.val);
    let kc = f64::from_bits(row.kap_cond);
    let kc_dr = f64::from_bits(row.cond_dlnd);
    let kc_dt = f64::from_bits(row.cond_dlnt);
    let kap_iso = 1.0 / (1.0 / kr_iso + 1.0 / kc);
    let dr_iso = (kap_iso / kr_iso) * lk.d1[0] + (kap_iso / kc) * kc_dr;
    let dt_iso = (kap_iso / kr_iso) * lk.d1[1] + (kap_iso / kc) * kc_dt;

    assert_eq!(kap_iso.to_bits(), row.kap_tot, "{}: eval_iso_kap", row.tag);
    assert_eq!(dr_iso.to_bits(), row.tot_dlnd, "{}: eval_iso_dlnd", row.tag);
    assert_eq!(dt_iso.to_bits(), row.tot_dlnt, "{}: eval_iso_dlnt", row.tag);
}

#[test]
fn test_make_brown_dwarf_z388_and_full_model0_regimes_zero_ulp() {
    with_numerics_mode(NumericsMode::Strict, || {
        for row in ORACLE_ROWS.iter().filter(|r| r.tag.starts_with("bd_")) {
            verify_row_zero_ulp(row);
        }

        // Direct `kap_get` composition-moment + radiative/total check for
        // `star/make_brown_dwarf` Model 0 surface (`k=0`) and `k=388` (`#738`).
        let cfg = cfg_for_case("inl_bd.txt");
        let cat = NuclideCatalog::builtin_ref();
        let names = ["h1", "he3", "he4", "c12", "n14", "o16", "ne20", "mg24"];
        let chem_id: Vec<usize> = names
            .iter()
            .map(|n| cat.get_nuclide_index(n).expect("builtin nuclide"))
            .collect();

        let xa_k0 = [
            f64::from_bits(0x3FE84F765FD8ADAB),
            f64::from_bits(0x3EFACDC71D680D69),
            f64::from_bits(0x3FCEBE093606FA88),
            f64::from_bits(0x3EF212541AC81F31),
            f64::from_bits(0x3ED5303C7D57B101),
            f64::from_bits(0x3F08972A60D212D3),
            f64::from_bits(0x3EE5DCF1DFB835A4),
            f64::from_bits(0x3EF5605AC0D2B418),
        ];
        let k0 = &ORACLE_ROWS[0];
        assert_eq!(k0.tag, "bd_m0_k0000");
        let out_k0 = kap_get(
            &cfg,
            &chem_id,
            &xa_k0,
            f64::from_bits(k0.lnd) / LN10,
            f64::from_bits(k0.lnt) / LN10,
            f64::from_bits(k0.lnfree_e),
            f64::from_bits(k0.dlnfe_d),
            f64::from_bits(k0.dlnfe_t),
            f64::from_bits(k0.eta),
            f64::from_bits(k0.deta_d),
            f64::from_bits(k0.deta_t),
        )
        .expect("kap_get bd_m0_k0000");
        assert_eq!(out_k0.kap.to_bits(), k0.kap_tot, "bd_m0_k0000 kap_tot");
        assert_eq!(
            out_k0.dlnkap_dln_rho.to_bits(),
            k0.tot_dlnd,
            "bd_m0_k0000 dlnd"
        );
        assert_eq!(
            out_k0.dlnkap_dln_t.to_bits(),
            k0.tot_dlnt,
            "bd_m0_k0000 dlnt"
        );

        let xa_z388 = [
            f64::from_bits(0x3FE84F765FD8ADAD),
            f64::from_bits(0x3EFACDC71D680D6B),
            f64::from_bits(0x3FCEBE093606FA8A),
            f64::from_bits(0x3EF212541AC81F32),
            f64::from_bits(0x3ED5303C7D57B102),
            f64::from_bits(0x3F08972A60D212D5),
            f64::from_bits(0x3EE5DCF1DFB835A5),
            f64::from_bits(0x3EF5605AC0D2B419),
        ];
        let z388 = ORACLE_ROWS
            .iter()
            .find(|r| r.tag == "bd_z388")
            .expect("bd_z388 row");
        let out_z388 = kap_get(
            &cfg,
            &chem_id,
            &xa_z388,
            f64::from_bits(z388.lnd) / LN10,
            f64::from_bits(z388.lnt) / LN10,
            f64::from_bits(z388.lnfree_e),
            f64::from_bits(z388.dlnfe_d),
            f64::from_bits(z388.dlnfe_t),
            f64::from_bits(z388.eta),
            f64::from_bits(z388.deta_d),
            f64::from_bits(z388.deta_t),
        )
        .expect("kap_get bd_z388");
        assert_eq!(
            out_z388.kap_fracs[I_FRAC_HIGH_T].to_bits(),
            0x3FF0_0000_0000_0000,
            "bd_z388 frac_high_t"
        );
        assert!(out_z388.kap.is_finite() && out_z388.kap > 0.0);
    });
}

