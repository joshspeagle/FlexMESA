"""Generate the per-case wall-time budgets of strict harness campaigns (#640).

Two committed tables, one data flow:

* ``benchmarks/history_harness/case_timings.toml`` holds the measurements:
  for every manifest case, the wall time and step count of FlexMESA on a
  hosted runner (the shard reports of one full strict campaign) and of
  MESA 26.4.1 itself (``case_result.json`` of each stored run in the
  ``mesa-histories`` bundle). ``--collect`` writes it and needs both
  sources, so it is rerun only after a new campaign.
* ``benchmarks/history_harness/case_budgets.toml`` holds the derived
  ``budget_sec`` of each case. The default mode writes it from the timings
  alone and ``--check`` confirms the committed file is what the timings
  give, so CI needs no data download.

Projection of the time a case needs on a hosted runner:

* A case that ran to its own termination in the campaign (status ``ok``,
  termination matched) needs what it measured: ``measured``.
* Any other case (cut off by the old budget, or stopped by an error) has no
  representative cost per step, because its steps are those of a run that
  has diverged from MESA (one case took 230 s per step while stuck in
  retries). It is projected from MESA's own wall time on the case times the
  median hosted-to-MESA wall ratio ``R`` of the measured cases:
  ``mesa_wall_ratio``. The per-step projection (FlexMESA seconds per step
  times MESA steps) is stored beside it as a cross-check, and a case where
  the two differ by more than a factor of 3 is listed as ``disputed``.

``budget_sec = min(cap, max(floor, ceil60(factor * projected)))`` with the
floor, the factors and the cap stated in the file header.

Usage:
    python scripts/audit/case_budgets.py --check
    python scripts/audit/case_budgets.py            # rewrite budgets
    python scripts/audit/case_budgets.py --collect SHARD_DIR MESA_RUNS_DIR \
        --campaign-run RUN_ID
    python scripts/audit/case_budgets.py --get star/ns_h
    python scripts/audit/case_budgets.py --shards 16   # packing report
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import math
import pathlib
import statistics
import sys
import tomllib
from typing import Any

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]


def _load_case_budgets() -> Any:
    """Load ``flexmesa.testing.case_budgets`` without importing the package.

    The module has no package dependencies, so the generator and its CI check
    need no compiled extension.
    """
    path = REPO_ROOT / "src" / "flexmesa" / "testing" / "case_budgets.py"
    spec = importlib.util.spec_from_file_location("_case_budgets", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["_case_budgets"] = module
    spec.loader.exec_module(module)
    return module


case_budgets = _load_case_budgets()

HARNESS_DIR = REPO_ROOT / "benchmarks" / "history_harness"
TIMINGS_PATH = HARNESS_DIR / "case_timings.toml"
BUDGETS_PATH = HARNESS_DIR / "case_budgets.toml"

#: Smallest budget (s). The cheapest cases finish in 4 to 25 s; two cases
#: share a runner and each pays start-up, so 300 s is over ten times the
#: largest of those while still ending a stuck tiny case quickly.
FLOOR_SEC = 300
#: Safety factor on a measured time: runner speed differs between jobs and
#: ports add cost, so 2 matches the long-standing ``--budget-factor``.
FACTOR_MEASURED = 2.0
#: Safety factor on a projection from MESA's wall time. The hosted-to-MESA
#: ratio of the measured cases has p10 0.8 and p90 2.5 around a median of
#: 1.4, so a projection can be 1.8 times too low before the run diverges.
FACTOR_PROJECTED = 3.0
#: Ratio between the two projections beyond which a case is called disputed.
DISPUTE_RATIO = 3.0
#: Cases with a MESA wall time below this do not enter the median ratio.
MIN_MESA_WALL_SEC = 60.0
SHARDS = 16
JOBS_PER_SHARD = 2


_TIMINGS_HEADER = """\
# SPDX-License-Identifier: GPL-3.0-or-later
# Generated by `scripts/audit/case_budgets.py --collect`; do not edit.
# Measured wall times behind `case_budgets.toml` (#640).
#
# flex_*: FlexMESA, strict mode, on a hosted runner with two cases at once,
#   from campaign run {campaign_run} (shard reports). flex_steps is the sum
#   of the per-stage step counts.
# mesa_*: MESA 26.4.1 on the reference machine, from `case_result.json` of
#   each stored run (`wall_seconds`; `total_steps_all_stages`).
"""

_BUDGETS_HEADER = """\
# SPDX-License-Identifier: GPL-3.0-or-later
# Generated by `scripts/audit/case_budgets.py`; do not edit.
# Per-case wall-time budgets of strict harness campaigns (#640).
#
# budget_sec = min(cap, max(floor, ceil60(factor * projected_sec)))
#   floor  = {floor} s: the cheapest cases need 4 to 25 s and two cases
#            share a runner, so the floor is over ten times that.
#   factor = {f_meas:g} on a measured time (a case that ran to its own
#            termination in the campaign), the long-standing
#            --budget-factor; runner speed and ported physics move it.
#   factor = {f_proj:g} on a projection from MESA's wall time (a case that
#            was cut off or errored). Over the {n} measured cases with a
#            MESA wall time of at least {min_wall:g} s the hosted-to-MESA
#            wall ratio is {qmin:.2f} (min), {p10:.2f} (p10),
#            {med:.2f} (median), {p90:.2f} (p90), {qmax:.2f} (max), so a
#            projection from the median is low by {low90:.1f} at p90 and
#            {lowmax:.1f} at the maximum.
#   cap    = {cap} s: a {limit}-minute hosted job less {headroom} minutes
#            of build download, data fetch and uploads (the headroom of
#            case-run.yml).
# projected_sec, by basis:
#   measured              campaign wall time of a case that completed
#   mesa_wall_ratio       {ratio:g} x MESA's wall time (the median ratio);
#                         per_step_sec, FlexMESA s/step x MESA steps, is the
#                         cross-check
#   mesa_wall_lower_bound the same with MESA itself cut off
#   timeout_lower_bound   the campaign run ended on its old budget after
#                         longer than the projection, so that wall time
#   floor                 no usable measurement
# Inputs: case_timings.toml. Recipe: see the script docstring.
"""


def _round_up(value: float, quantum: int = 60) -> int:
    return int(math.ceil(value / quantum) * quantum)


def _key(row: dict[str, Any]) -> str:
    return f"{row['suite']}/{row['case']}"


# --------------------------------------------------------------------------
# Collecting measurements


def _flex_total_steps(row: dict[str, Any]) -> int:
    stages = row.get("stage_steps")
    if stages:
        return int(sum(stages))
    return int(row.get("steps") or 0)


def collect(
    shard_dir: pathlib.Path, runs_dir: pathlib.Path, campaign_run: str
) -> str:
    """Return the text of ``case_timings.toml`` from the two sources."""
    flex: dict[str, dict[str, Any]] = {}
    for path in sorted(shard_dir.glob("**/shard_*.json")):
        for row in json.loads(path.read_text(encoding="utf-8"))["cases"]:
            if row.get("executed"):
                flex[_key(row)] = row
    lines = [
        _TIMINGS_HEADER.format(campaign_run=campaign_run).rstrip("\n"),
        "",
    ]
    for key in sorted(flex):
        suite, case = key.split("/", 1)
        f = flex[key]
        res = json.loads(
            (runs_dir / suite / case / "case_result.json").read_text(
                encoding="utf-8"
            )
        )
        completed = bool(
            f["run_status"] == "ok" and f.get("termination_matches")
        )
        lines += [
            "[[cases]]",
            f'suite = "{suite}"',
            f'case = "{case}"',
            f'flex_status = "{f["run_status"]}"',
            f"flex_completed = {str(completed).lower()}",
            f"flex_wall_sec = {float(f['wall_time_sec']):.1f}",
            f"flex_steps = {_flex_total_steps(f)}",
            f'mesa_status = "{res["status"]}"',
            f"mesa_wall_sec = {float(res.get('wall_seconds') or 0.0):.1f}",
            f"mesa_steps = {int(res.get('total_steps_all_stages') or 0)}",
            "",
        ]
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Deriving budgets


def project(row: dict[str, Any], ratio: float) -> dict[str, Any]:
    """Project the hosted time one case needs and its budget.

    Args:
        row: A ``[[cases]]`` row of the timings table.
        ratio: Median hosted-to-MESA wall ratio ``R``.

    Returns:
        ``projected_sec``, ``basis``, ``factor``, ``per_step_sec`` (or
        ``None``) and ``uncapped_sec``, the budget before the cap.
    """
    mesa_ok = row["mesa_status"] == "ok" and row["mesa_wall_sec"] > 0
    mesa_wall = float(row["mesa_wall_sec"])
    per_step = None
    if row["flex_steps"] > 0 and row["mesa_steps"] > 0:
        per_step = row["flex_wall_sec"] / row["flex_steps"] * row["mesa_steps"]
    if row["flex_completed"]:
        projected, basis, factor = row["flex_wall_sec"], "measured", 2.0
    elif mesa_wall > 0 and row["mesa_status"] in ("ok", "timeout"):
        projected = ratio * mesa_wall
        basis = "mesa_wall_ratio" if mesa_ok else "mesa_wall_lower_bound"
        factor = FACTOR_PROJECTED
        if row["flex_status"] == "timeout" and row["flex_wall_sec"] > projected:
            # The old budget ended the run, so it needs at least that long.
            projected, basis = row["flex_wall_sec"], "timeout_lower_bound"
    else:
        projected, basis, factor = 0.0, "floor", FACTOR_MEASURED
    uncapped = max(FLOOR_SEC, _round_up(factor * projected))
    return {
        "projected_sec": round(projected),
        "basis": basis,
        "factor": factor,
        "per_step_sec": None if per_step is None else round(per_step),
        "uncapped_sec": uncapped,
    }


def ratio_quantiles(rows: list[dict[str, Any]]) -> dict[str, float]:
    """Return min, p10, median, p90 and max of the hosted/MESA wall ratio.

    Only cases that completed in the campaign and whose MESA run completed
    with at least ``MIN_MESA_WALL_SEC`` of wall time enter.
    """
    ratios = sorted(
        r["flex_wall_sec"] / r["mesa_wall_sec"]
        for r in rows
        if r["flex_completed"]
        and r["mesa_status"] == "ok"
        and r["mesa_wall_sec"] >= MIN_MESA_WALL_SEC
    )
    n = len(ratios)
    return {
        "n": n,
        "min": ratios[0],
        "p10": ratios[n // 10],
        "median": statistics.median(ratios),
        "p90": ratios[(9 * n) // 10],
        "max": ratios[-1],
    }


def derive(timings_text: str) -> tuple[str, dict[str, Any]]:
    """Return the text of ``case_budgets.toml`` and a summary dict."""
    data = tomllib.loads(timings_text)
    rows = data["cases"]
    q = ratio_quantiles(rows)
    ratio = round(q["median"], 3)
    cap = case_budgets.USABLE_JOB_SEC
    out: list[dict[str, Any]] = []
    for row in rows:
        p = project(row, ratio)
        p["suite"], p["case"] = row["suite"], row["case"]
        p["budget_sec"] = min(cap, p["uncapped_sec"])
        ps = p["per_step_sec"]
        p["disputed"] = bool(
            ps
            and p["projected_sec"]
            and not row["flex_completed"]
            and (
                ps > DISPUTE_RATIO * p["projected_sec"]
                or ps * DISPUTE_RATIO < p["projected_sec"]
            )
        )
        out.append(p)
    over = [_key(p) for p in out if p["projected_sec"] > cap]
    capped = [
        _key(p) for p in out if p["uncapped_sec"] > cap and _key(p) not in over
    ]
    disputed = [_key(p) for p in out if p["disputed"]]
    lines = [
        _BUDGETS_HEADER.format(
            floor=FLOOR_SEC,
            f_meas=FACTOR_MEASURED,
            f_proj=FACTOR_PROJECTED,
            n=q["n"],
            min_wall=MIN_MESA_WALL_SEC,
            qmin=q["min"],
            p10=q["p10"],
            med=q["median"],
            p90=q["p90"],
            qmax=q["max"],
            low90=q["p90"] / q["median"],
            lowmax=q["max"] / q["median"],
            ratio=ratio,
            cap=cap,
            limit=case_budgets.JOB_LIMIT_MIN,
            headroom=case_budgets.HEADROOM_MIN,
        ),
        "# Cases whose projected time exceeds one hosted job.",
        f"over_limit = {json.dumps(over)}",
        "# Cases whose budget would exceed the cap and was cut to it.",
        f"capped = {json.dumps(capped)}",
        "# Cases whose two projections differ by more than a factor of 3.",
        f"disputed = {json.dumps(disputed)}",
        "",
    ]
    for p in sorted(out, key=_key):
        lines += [
            "[[cases]]",
            f'suite = "{p["suite"]}"',
            f'case = "{p["case"]}"',
            f"budget_sec = {p['budget_sec']}",
            f"projected_sec = {p['projected_sec']}",
        ]
        if p["per_step_sec"] is not None:
            lines.append(f"per_step_sec = {p['per_step_sec']}")
        lines += [f'basis = "{p["basis"]}"', ""]
    summary = {
        "ratio": ratio,
        "over": over,
        "capped": capped,
        "disputed": disputed,
        "rows": out,
    }
    return "\n".join(lines), summary


# --------------------------------------------------------------------------
# Reporting


def pack_report(summary: dict[str, Any], shards: int) -> str:
    """Return the shard loads of the heaviest-first packing by budget."""
    weights = {_key(p): p["budget_sec"] for p in summary["rows"]}
    load = [0.0] * shards
    for key in sorted(weights, key=lambda k: (-weights[k], k)):
        slot = min(range(shards), key=lambda i: (load[i], i))
        load[slot] += weights[key]
    worst = max(load)
    return (
        f"{shards} shards: budget sum per shard min {min(load) / 3600:.2f} h,"
        f" max {worst / 3600:.2f} h; at {JOBS_PER_SHARD} cases at once a"
        f" shard needs at most {worst / JOBS_PER_SHARD / 60:.0f} min of"
        f" cases if every case used its whole budget"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument(
        "--collect",
        nargs=2,
        metavar=("SHARD_DIR", "MESA_RUNS_DIR"),
        help="rewrite case_timings.toml from shard reports and MESA runs",
    )
    ap.add_argument("--campaign-run", default="unknown")
    ap.add_argument("--get", metavar="SUITE/CASE")
    ap.add_argument("--shards", type=int, default=None)
    ns = ap.parse_args(argv)

    if ns.collect:
        text = collect(
            pathlib.Path(ns.collect[0]),
            pathlib.Path(ns.collect[1]),
            ns.campaign_run,
        )
        TIMINGS_PATH.write_text(text, encoding="utf-8")
        print(f"wrote {TIMINGS_PATH.relative_to(REPO_ROOT)}")
    text, summary = derive(TIMINGS_PATH.read_text(encoding="utf-8"))
    if ns.get:
        table = case_budgets.load_case_budgets(BUDGETS_PATH)
        suite, _, case = ns.get.partition("/")
        if (suite, case) not in table:
            print(f"no budget for {ns.get}", file=sys.stderr)
            return 1
        print(int(table[(suite, case)]))
        return 0
    if ns.check:
        committed = BUDGETS_PATH.read_text(encoding="utf-8")
        if committed != text:
            print(
                f"{BUDGETS_PATH.relative_to(REPO_ROOT)} is out of date;"
                " run scripts/audit/case_budgets.py",
                file=sys.stderr,
            )
            return 1
        print("case budgets are up to date")
        return 0
    BUDGETS_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {BUDGETS_PATH.relative_to(REPO_ROOT)}")
    print(f"median hosted/MESA wall ratio {summary['ratio']}")
    print(f"over one job ({case_budgets.USABLE_JOB_SEC} s): {summary['over']}")
    print(f"capped: {summary['capped']}")
    print(f"disputed: {summary['disputed']}")
    print(pack_report(summary, ns.shards or SHARDS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
