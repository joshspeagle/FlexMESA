"""Compare manifest terminations with MESA 26.4.1's own output (`#604`).

`required_termination` in `case_manifest.toml` is entered by hand. This script
compares every value with what the stored real-MESA run of the case printed.

The MESA side is a small committed ledger,
`benchmarks/history_harness/mesa_terminations.toml`, generated from the
`out.txt` of every stored run in the `mesa-histories-v1` data bundle. It
records, per case, the per-stage step counts and the `termination code:` line
of each stage, plus the SHA-256 of the `out.txt` it was read from. CI therefore
needs no data download.

Rule: the manifest value (any `|` alternative) must equal the termination code
MESA printed for the final stage. Otherwise the case must appear in
`benchmarks/history_harness/mesa_termination_exceptions.toml`, whose entry
names the upstream source line that ends the run and the message MESA printed
(which the generator verifies is present in `out.txt`). A case in the
`unresolved` table of that file is reported but does not fail the check.

Usage:
    python scripts/audit/mesa_terminations.py --check
    python scripts/audit/mesa_terminations.py --write
    python scripts/audit/mesa_terminations.py --report-stage-steps

`--check` always compares the manifest with the ledger and the exceptions.
When the stored runs are present (`FLEXMESA_HISTORIES_DIR` or the default data
cache) it also confirms the ledger is reproducible from them. `--write`
regenerates the ledger and needs the stored runs; pass `--mesa-source-dir`
(or set `MESA_SOURCE_DIR`) to verify the upstream source lines at the same
time.
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import re
import sys
import tomllib
from typing import Any

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "src"))

from flexmesa.data import fetch  # noqa: E402
from flexmesa.testing import case_manifest  # noqa: E402

LEDGER_REL = "benchmarks/history_harness/mesa_terminations.toml"
EXCEPTIONS_REL = "benchmarks/history_harness/mesa_termination_exceptions.toml"
BASELINE_REL = "benchmarks/history_harness/baseline_run_26_4_1.json"
BUNDLE_NAME = "mesa_histories"

EXCEPTION_KINDS = frozenset(
    {
        "hook_without_code",
        "binary_message",
        "multi_stage_final_hook",
        "no_mesa_run",
        "result_reason",
        "after_evolve_code",
        "hook_error_exit",
    }
)
# Kinds whose upstream message must be visible in the stored out.txt.
_NEEDS_MESSAGE = EXCEPTION_KINDS - {"no_mesa_run"}

_CODE_RE = re.compile(r"^termination code: (.*)$")
_RUNTIME_RE = re.compile(
    r"runtime \(minutes\), retries, steps\s+\S+\s+\d+\s+(\d+)\s*$"
)
_SOURCE_RE = re.compile(r"^(?P<path>[^:\s]+):(?P<line>\d+)$")

_HEADER = """\
# GENERATED by scripts/audit/mesa_terminations.py from the out.txt of every
# stored MESA 26.4.1 run in the mesa-histories-v1 data bundle. Do not edit by
# hand; regenerate with `--write` and verify with `--check`.
#
# stage_steps: the `runtime (minutes), retries, steps` step count of each
#              stage, in order.
# stage_codes: the `termination code:` MESA printed in each stage ("" when it
#              printed none, as when an extras hook returns terminate without
#              setting a code).
# out_sha256:  SHA-256 of the out.txt read, as listed in the bundle's
#              SHA256SUMS.tsv.
# evidence:    messages from the exceptions table found in that out.txt.
# source_checked: the upstream source line named in the exceptions table was
#              read at tag 26.4.1 and contains the quoted text.
"""


def split_stages(text: str) -> tuple[list[int], list[str], list[str]]:
    """Split a stored MESA terminal log into stages.

    A stage ends at its `runtime (minutes), retries, steps` line. MESA prints
    a star's `termination code:` before that line, so a code belongs to the
    stage whose runtime line follows it. Binary runs print it after the
    runtime line, so codes after the final runtime line belong to the final
    stage.

    Args:
        text: Contents of a stored `out.txt`.

    Returns:
        `(stage_steps, stage_codes, result_reasons)`. The first two have one
        entry per stage (codes are `""` when none was printed). The last lists
        every `terminated evolution:` reason printed.
    """
    steps: list[int] = []
    codes: list[str] = []
    reasons: list[str] = []
    current = ""
    for raw in text.splitlines():
        line = raw.rstrip()
        match = _CODE_RE.match(line)
        if match:
            current = match.group(1).strip()
            continue
        if line.startswith("terminated evolution: "):
            reasons.append(line.split(": ", 1)[1].strip())
            continue
        run = _RUNTIME_RE.search(line)
        if run:
            steps.append(int(run.group(1)))
            codes.append(current)
            current = ""
    if current:
        if codes:
            codes[-1] = current
        else:
            codes.append(current)
    return steps, codes, reasons


def _quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _histories_runs_dir() -> pathlib.Path | None:
    root = fetch.resolve_mesa_histories_dir()
    runs = root / "runs"
    return runs if runs.is_dir() else None


def _load_toml(path: pathlib.Path) -> dict[str, Any]:
    with path.open("rb") as fh:
        return tomllib.load(fh)


def _bundle_sha(repo_root: pathlib.Path) -> str:
    bundles = _load_toml(repo_root / "src/flexmesa/data/bundles.toml")
    for entry in bundles["bundles"]:
        if entry["name"] == BUNDLE_NAME:
            return str(entry["archive_sha256"])
    raise ValueError(f"bundle {BUNDLE_NAME!r} not in bundles.toml")


def _out_sha_table(runs_dir: pathlib.Path) -> dict[str, str]:
    sums = runs_dir.parent / "SHA256SUMS.tsv"
    table: dict[str, str] = {}
    if not sums.is_file():
        return table
    for line in sums.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) == 3 and parts[2].endswith("/out.txt"):
            table[parts[2]] = parts[0]
    return table


def check_source_line(
    mesa_source: pathlib.Path, source: str, text: str
) -> str | None:
    """Verify an upstream `path:line` contains the quoted text.

    Args:
        mesa_source: Root of the MESA 26.4.1 source tree.
        source: `path/relative/to/root:line`.
        text: Text that must occur on that line.

    Returns:
        An error message, or `None` when the line holds the text.
    """
    match = _SOURCE_RE.match(source)
    if not match:
        return f"malformed source {source!r}"
    path = mesa_source / match.group("path")
    if not path.is_file():
        return f"source file {match.group('path')} not found"
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    number = int(match.group("line"))
    if number > len(lines) or text not in lines[number - 1]:
        return f"{source} does not contain {text!r}"
    return None


def render_ledger(
    repo_root: pathlib.Path,
    runs_dir: pathlib.Path,
    mesa_source: pathlib.Path | None,
    previous: dict[tuple[str, str], bool],
) -> tuple[str, list[str]]:
    """Render the ledger from the stored runs.

    Args:
        repo_root: Repository root.
        runs_dir: The bundle's `runs/` directory.
        mesa_source: Optional MESA source root to verify exception sources.
        previous: `source_checked` values of the committed ledger, kept when
            `mesa_source` is not given.

    Returns:
        `(toml_text, errors)` where `errors` lists exceptions whose message or
        source line could not be verified.
    """
    manifest = case_manifest.load_case_manifest()
    exceptions = _load_exceptions(repo_root)
    sha_table = _out_sha_table(runs_dir)
    errors: list[str] = []
    lines = [
        _HEADER,
        "[bundle]",
        'name = "mesa-histories-v1"',
        f'archive_sha256 = "{_bundle_sha(repo_root)}"',
        'mesa_release = "26.4.1"',
        "",
    ]
    for entry in manifest.cases:
        key = (entry.suite, entry.case)
        rel = f"runs/{entry.suite}/{entry.case}"
        out = runs_dir / entry.suite / entry.case / "out.txt"
        result_path = out.parent / "case_result.json"
        status = "ok"
        if result_path.is_file():
            status = str(json.loads(result_path.read_text()).get("status", ""))
        text = out.read_text(errors="replace") if out.is_file() else ""
        steps, codes, _ = split_stages(text)
        lines += [
            "[[runs]]",
            f'suite = "{entry.suite}"',
            f'case = "{entry.case}"',
            f"run_status = {_quote(status)}",
            f"stage_steps = {json.dumps(steps)}",
            f"stage_codes = {json.dumps(codes, ensure_ascii=False)}",
            f'out_sha256 = "{sha_table.get(rel + "/out.txt", "")}"',
        ]
        exc = exceptions.get(key)
        if exc is not None:
            msg = str(exc.get("message", ""))
            found = [msg] if msg and msg in text else []
            if msg and not found:
                errors.append(f"{key}: message {msg!r} not in out.txt")
            lines.append(f"evidence = {json.dumps(found, ensure_ascii=False)}")
            checked = previous.get(key, False)
            if mesa_source is not None:
                problem = check_source_line(
                    mesa_source, str(exc["source"]), str(exc["source_text"])
                )
                checked = problem is None
                if problem:
                    errors.append(f"{key}: {problem}")
            lines.append(f"source_checked = {str(checked).lower()}")
        lines.append("")
    return "\n".join(lines), errors


def _load_exceptions(repo_root: pathlib.Path) -> dict[tuple[str, str], Any]:
    data = _load_toml(repo_root / EXCEPTIONS_REL)
    out: dict[tuple[str, str], Any] = {}
    for raw in data.get("exceptions", []):
        out[(raw["suite"], raw["case"])] = raw
    return out


def _load_unresolved(repo_root: pathlib.Path) -> dict[tuple[str, str], Any]:
    data = _load_toml(repo_root / EXCEPTIONS_REL)
    return {(r["suite"], r["case"]): r for r in data.get("unresolved", [])}


def _ledger_runs(repo_root: pathlib.Path) -> dict[tuple[str, str], Any]:
    data = _load_toml(repo_root / LEDGER_REL)
    return {(r["suite"], r["case"]): r for r in data["runs"]}


def compare(repo_root: pathlib.Path) -> tuple[list[str], list[str]]:
    """Compare every manifest case with the ledger and exceptions table.

    Args:
        repo_root: Repository root.

    Returns:
        `(failures, unresolved_notes)`.
    """
    manifest = case_manifest.load_case_manifest()
    runs = _ledger_runs(repo_root)
    exceptions = _load_exceptions(repo_root)
    unresolved = _load_unresolved(repo_root)
    failures: list[str] = []
    notes: list[str] = []
    seen: set[tuple[str, str]] = set()
    for entry in manifest.cases:
        key = (entry.suite, entry.case)
        name = f"{entry.suite}/{entry.case}"
        required = entry.required_termination
        run = runs.get(key)
        if run is None:
            failures.append(f"{name}: no ledger row (regenerate with --write)")
            continue
        codes = run["stage_codes"]
        final = codes[-1] if codes else ""
        exc = exceptions.get(key)
        if key in unresolved:
            row = unresolved[key]
            seen.add(key)
            notes.append(
                f"{name}: manifest {required!r}, MESA final code {final!r}; "
                f"{row['note']}"
            )
            if exc is not None:
                failures.append(f"{name}: both exception and unresolved")
            continue
        if exc is None:
            if run["run_status"] != "ok":
                failures.append(
                    f"{name}: no completed MESA run ({run['run_status']}) and "
                    "no no_mesa_run exception"
                )
            elif not final or not case_manifest.termination_matches(
                required, final
            ):
                failures.append(
                    f"{name}: manifest {required!r} but MESA's final stage "
                    f"printed {final!r}; fix the manifest or add an exception"
                )
            continue
        seen.add(key)
        failures += _check_exception(name, required, run, exc, final)
    for stray in set(exceptions) | set(unresolved):
        if stray not in seen:
            failures.append(f"{stray[0]}/{stray[1]}: table entry names no case")
    return failures, notes


def _check_exception(
    name: str,
    required: str,
    run: dict[str, Any],
    exc: dict[str, Any],
    final: str,
) -> list[str]:
    out: list[str] = []
    kind = str(exc.get("kind", ""))
    if kind not in EXCEPTION_KINDS:
        return [f"{name}: unknown exception kind {kind!r}"]
    if str(exc.get("manifest", "")) != required:
        out.append(
            f"{name}: exception was written for manifest "
            f"{exc.get('manifest')!r}, manifest is now {required!r}"
        )
    if not _SOURCE_RE.match(str(exc.get("source", ""))):
        out.append(f"{name}: exception source is not <file>:<line>")
    if not str(exc.get("source_text", "")).strip():
        out.append(f"{name}: exception lacks source_text")
    if kind in _NEEDS_MESSAGE:
        msg = str(exc.get("message", ""))
        if not msg or msg not in run.get("evidence", []):
            out.append(f"{name}: message {msg!r} not found in MESA output")
        if (
            kind != "binary_message"
            and final
            and kind
            in (
                "hook_without_code",
                "multi_stage_final_hook",
                "hook_error_exit",
            )
        ):
            out.append(
                f"{name}: kind {kind} but MESA printed final code {final!r}"
            )
        if kind == "binary_message" and required not in msg:
            out.append(f"{name}: manifest value is not named by the message")
    else:
        if run["run_status"] == "ok":
            out.append(f"{name}: no_mesa_run but MESA run is ok")
    if not run.get("source_checked", False):
        out.append(f"{name}: upstream source line not verified")
    return out


def reproducible(repo_root: pathlib.Path) -> tuple[bool | None, list[str]]:
    """Check that the committed ledger regenerates from the stored runs.

    Args:
        repo_root: Repository root.

    Returns:
        `(status, errors)` with `status` `None` when no stored runs exist.
    """
    runs_dir = _histories_runs_dir()
    if runs_dir is None:
        return None, []
    prev = {
        k: bool(v.get("source_checked", False))
        for k, v in _ledger_runs(repo_root).items()
    }
    text, errors = render_ledger(repo_root, runs_dir, None, prev)
    current = (repo_root / LEDGER_REL).read_text(encoding="utf-8")
    return text == current, errors


def stage_step_report(repo_root: pathlib.Path) -> list[str]:
    """List disagreements between baseline and MESA stage step counts.

    Args:
        repo_root: Repository root.

    Returns:
        One line per case whose baseline `mesa_stage_steps` is recorded and
        differs from the ledger, plus one summary line for absent values.
    """
    runs = _ledger_runs(repo_root)
    base = json.loads((repo_root / BASELINE_REL).read_text())["cases"]
    out: list[str] = []
    absent = 0
    for row in base:
        key = (row["suite"], row["case"])
        mesa = runs[key]["stage_steps"]
        rec = row.get("mesa_stage_steps")
        if rec is None:
            absent += 1
        elif list(rec) != list(mesa):
            out.append(f"{key[0]}/{key[1]}: baseline {rec} vs out.txt {mesa}")
    out.append(f"{absent} cases have no baseline mesa_stage_steps")
    return out


def main(argv: list[str] | None = None) -> int:
    """Run the check, regenerate the ledger, or report stage counts.

    Args:
        argv: Command-line arguments (default `sys.argv[1:]`).

    Returns:
        `0` on success, `1` when the check fails.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", default=str(REPO_ROOT))
    parser.add_argument("--mesa-source-dir", default=None)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--write", action="store_true")
    group.add_argument("--report-stage-steps", action="store_true")
    ns = parser.parse_args(argv)
    root = pathlib.Path(ns.repo_root)
    if ns.report_stage_steps:
        print("\n".join(stage_step_report(root)))
        return 0
    if ns.write:
        runs_dir = _histories_runs_dir()
        if runs_dir is None:
            print("stored MESA runs not found; fetch mesa-histories-v1")
            return 1
        src = ns.mesa_source_dir or os.environ.get("MESA_SOURCE_DIR")
        ledger = root / LEDGER_REL
        prev = (
            {
                k: bool(v.get("source_checked", False))
                for k, v in _ledger_runs(root).items()
            }
            if ledger.is_file()
            else {}
        )
        text, errors = render_ledger(
            root, runs_dir, pathlib.Path(src) if src else None, prev
        )
        ledger.write_text(text, encoding="utf-8")
        for err in errors:
            print(f"UNVERIFIED {err}")
        return 1 if errors else 0
    failures, notes = compare(root)
    status, errors = reproducible(root)
    failures += errors
    if status is False:
        failures.append(
            "ledger differs from the stored MESA outputs; run --write"
        )
    for note in notes:
        print(f"UNRESOLVED (reported, not failing) {note}")
    for fail in failures:
        print(f"FAIL {fail}")
    if status is None:
        print("note: stored MESA runs absent; ledger reproducibility skipped")
    if failures:
        return 1
    print("manifest terminations agree with MESA output and exceptions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
