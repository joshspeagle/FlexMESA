"""Generate the per-case status of upstream extras logic (`#148`, `#231`).

Each upstream case ships `src/run_star_extras.f90` (and, for binaries,
`src/run_binary_extras.f90`). The history harness attaches a test-side handler
from `tests.case_extras` when one exists and otherwise runs with default no-op
hooks. This script records, for every manifest case, whether its extras are
`ported` (a handler is attached), `stock` (the sources equal a reviewed
template without case logic) or `unported` (the case has extras logic that is
not executed). The harness reads the result and never counts an `unported`
case as passing.

Usage:
    python scripts/audit/render_extras_status.py            # rewrite
    python scripts/audit/render_extras_status.py --check    # verify
"""

from __future__ import annotations

import argparse
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "src"))

from tests import case_extras  # noqa: E402

from flexmesa.testing import case_manifest, harness_runner  # noqa: E402

LEDGER_REL = "benchmarks/history_harness/extras_status.toml"
UNPORTED_ISSUE = "#231"

_HEADER = """\
# GENERATED by scripts/audit/render_extras_status.py from the MESA 26.4.1
# test inputs and tests/case_extras. Do not edit by hand.
#
# status = "ported":   tests.case_extras attaches a handler for this case.
# status = "stock":    the extras sources equal a reviewed template that
#                      contains no case logic.
# status = "unported": the case has upstream extras logic that FlexMESA does
#                      not execute. The harness never reports such a case as
#                      passing; `issue` is the open issue that owns the port.
"""


def render_ledger(mesa_dir: pathlib.Path | None = None) -> str:
    """Render the extras-status ledger for every manifest case.

    Args:
        mesa_dir: Optional MESA test-input root; defaults to the configured
            bundle location.

    Returns:
        TOML text of the ledger.
    """
    manifest = case_manifest.load_case_manifest()
    lines = [_HEADER]
    for entry in manifest.cases:
        case_dir = harness_runner.resolve_case_dir(
            entry.suite, entry.case, mesa_dir=mesa_dir
        )
        status = case_extras.classify_case_extras(entry.suite, case_dir)
        lines.append("[[cases]]")
        lines.append(f'suite = "{entry.suite}"')
        lines.append(f'case = "{entry.case}"')
        lines.append(f'status = "{status}"')
        lines.append(f'digest = "{case_extras.extras_source_digest(case_dir)}"')
        if status == "unported":
            lines.append(f'issue = "{UNPORTED_ISSUE}"')
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Rewrite or check the committed extras-status ledger.

    Args:
        argv: Command-line arguments (default `sys.argv[1:]`).

    Returns:
        `0` on success, `1` when `--check` finds a stale ledger.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", default=str(REPO_ROOT))
    parser.add_argument("--mesa-dir", default=None)
    parser.add_argument("--check", action="store_true")
    ns = parser.parse_args(argv)
    ledger_path = pathlib.Path(ns.repo_root) / LEDGER_REL
    mesa_dir = pathlib.Path(ns.mesa_dir) if ns.mesa_dir else None
    text = render_ledger(mesa_dir)
    if ns.check:
        current = (
            ledger_path.read_text(encoding="utf-8")
            if ledger_path.is_file()
            else ""
        )
        if current != text:
            print(
                f"STALE: {LEDGER_REL} does not match the upstream extras "
                "sources and tests/case_extras; rerun "
                "scripts/audit/render_extras_status.py",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {LEDGER_REL} matches the upstream extras sources.")
        return 0
    ledger_path.write_text(text, encoding="utf-8")
    print(f"Wrote {LEDGER_REL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
