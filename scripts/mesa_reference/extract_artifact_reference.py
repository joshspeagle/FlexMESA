"""Regenerate the committed artifact references of zero-step cases (`#606`).

`star/rsp_check_2nd_crossing` takes no evolution step in MESA `26.4.1`; its
hook writes `7B_2nd_crossing.data` and prints one block per scanned model.
The harness compares a run's file with the copy committed under
`benchmarks/history_harness/reference_artifacts/<suite>/<case>/`. This script
rebuilds that directory from the stored MESA run of the `mesa-histories-v1`
data bundle:

* the MESA-written file, byte for byte;
* `models_stdout.txt`, the per-model blocks (`call star_do1_rsp_build ...`,
  the `P(days) growth` header and the period line) taken from `out.txt`;
* `PROVENANCE.toml`, with the MESA version string, compiler and SDK from the
  bundle's `PROVENANCE.json` and the SHA-256 of each source file as listed in
  the repository's copy of the bundle checksum list.

Usage:
    python scripts/mesa_reference/extract_artifact_reference.py --write
    python scripts/mesa_reference/extract_artifact_reference.py --check

`--check` always verifies that the committed files match the checksums in
`PROVENANCE.toml` and the bundle checksum list. When the stored runs are
present (`FLEXMESA_HISTORIES_DIR` or the default data cache) it also
confirms that regenerating gives identical files. `--write` needs the runs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import sys
import tomllib

from flexmesa.data import fetch

SUITE = "star"
CASE = "rsp_check_2nd_crossing"
ARTIFACT = "7B_2nd_crossing.data"
BUNDLE = "mesa-histories-v1"
_SCRIPT = "scripts/mesa_reference/extract_artifact_reference.py"
_BLOCK_RE = re.compile(r"call star_do1_rsp_build model Teff L\s+\d+\s")


def _repo_root() -> pathlib.Path:
    return pathlib.Path(__file__).resolve().parents[2]


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def extract_model_blocks(out_text: str) -> str:
    """Return the three-line per-model blocks of a terminal log."""
    lines = out_text.splitlines()
    keep: list[str] = []
    for i, line in enumerate(lines):
        if _BLOCK_RE.search(line):
            if i + 2 >= len(lines) or "P(days)" not in lines[i + 1]:
                raise ValueError(f"incomplete model block at line {i + 1}")
            keep.extend(ln.rstrip() for ln in lines[i : i + 3])
    if not keep:
        raise ValueError("no per-model blocks found in out.txt")
    return "\n".join(keep) + "\n"


def _checksum_list(repo: pathlib.Path) -> dict[str, str]:
    path = repo / "src/flexmesa/data/bundle_hashes/mesa_histories.sha256.tsv"
    table: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) == 3:
            table[parts[2]] = parts[0]
    return table


def _bundle_archive_sha(repo: pathlib.Path) -> str:
    with (repo / "src/flexmesa/data/bundles.toml").open("rb") as fh:
        for entry in tomllib.load(fh)["bundles"]:
            if entry["name"] == "mesa_histories":
                return str(entry["archive_sha256"])
    raise ValueError("bundle mesa_histories not in bundles.toml")


def build(repo: pathlib.Path, root: pathlib.Path) -> dict[str, bytes]:
    """Build the reference files from the stored run under ``root``."""
    run = root / "runs" / SUITE / CASE
    data = (run / ARTIFACT).read_bytes()
    out_text = (run / "out.txt").read_text(encoding="utf-8")
    prov = json.loads((root / "PROVENANCE.json").read_text(encoding="utf-8"))
    sums = _checksum_list(repo)
    rel = f"runs/{SUITE}/{CASE}"
    for name, content in ((ARTIFACT, data), ("out.txt", out_text.encode())):
        listed = sums.get(f"{rel}/{name}")
        if listed != _sha(content):
            raise ValueError(
                f"{rel}/{name}: sha256 differs from the checksum list"
            )
    blocks = extract_model_blocks(out_text).encode()
    version_line = next(
        ln.strip() for ln in out_text.splitlines() if "version_number" in ln
    )
    mesa, sdk = prov["mesa"], prov["sdk_and_compiler"]
    sidecar = "\n".join(
        [
            "# GENERATED by " + _SCRIPT,
            f"# from the stored MESA run of the {BUNDLE} data bundle (`#606`).",
            "# Do not edit by hand; regenerate with `--write`, verify with "
            "`--check`.",
            "",
            "[source]",
            f'bundle = "{BUNDLE}"',
            f'bundle_archive_sha256 = "{_bundle_archive_sha(repo)}"',
            f'run = "{rel}"',
            f'mesa_release = "{mesa["release"]}"',
            f'mesa_git_commit = "{mesa["git_commit_short"]}"',
            f'version_string = "{version_line}"',
            f'compiler = "{sdk["compiler"]}"',
            f'sdk = "{sdk["mesasdk_version"]}"',
            "",
            "[files]",
            f'"{ARTIFACT}" = "{_sha(data)}"',
            f'"models_stdout.txt" = "{_sha(blocks)}"',
            '"out.txt (source of models_stdout.txt)" = '
            f'"{_sha(out_text.encode())}"',
            "",
        ]
    ).encode()
    return {
        ARTIFACT: data,
        "models_stdout.txt": blocks,
        "PROVENANCE.toml": sidecar,
    }


def main() -> int:
    """Run the script."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ns = ap.parse_args()
    repo = _repo_root()
    dest = (
        repo / "benchmarks/history_harness/reference_artifacts" / SUITE / CASE
    )
    root = fetch.resolve_mesa_histories_dir()
    have_runs = (root / "runs" / SUITE / CASE / ARTIFACT).is_file()
    if ns.write:
        if not have_runs:
            print("stored MESA runs not found; cannot --write", file=sys.stderr)
            return 2
        dest.mkdir(parents=True, exist_ok=True)
        for name, content in build(repo, root).items():
            (dest / name).write_bytes(content)
        print(f"wrote {dest.relative_to(repo)}")
        return 0
    errors: list[str] = []
    sums = _checksum_list(repo)
    with (dest / "PROVENANCE.toml").open("rb") as fh:
        files = tomllib.load(fh)["files"]
    for name in (ARTIFACT, "models_stdout.txt"):
        if _sha((dest / name).read_bytes()) != files.get(name):
            errors.append(f"{name}: differs from PROVENANCE.toml checksum")
    if files.get(ARTIFACT) != sums.get(f"runs/{SUITE}/{CASE}/{ARTIFACT}"):
        errors.append(f"{ARTIFACT}: differs from the bundle checksum list")
    if have_runs:
        for name, content in build(repo, root).items():
            if (dest / name).read_bytes() != content:
                errors.append(f"{name}: differs from regeneration")
    for err in errors:
        print(f"FAIL {err}", file=sys.stderr)
    print("ok" if not errors else f"{len(errors)} problems")
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
