"""Validation helpers for ``port_manifest.verify_port_manifest`` (`#174`)."""

from __future__ import annotations

import collections.abc
import hashlib
import json
import pathlib
import subprocess
from typing import Any

from flexmesa.testing import _port_parsers, port_manifest


def _artifact_has_provenance(path: pathlib.Path) -> bool:
    """Confirm a committed evidence artifact carries MESA 26.4.1 provenance."""
    head = path.read_bytes()[:8192].decode("utf-8", errors="replace")
    markers = ("r26.4.1", "26.4.1", "mesa_26_4_1", "GENERATED BY")
    return any(tok in head for tok in markers)


def _is_safe_relpath(rel: str) -> bool:
    """Return ``True`` when ``rel`` is a normalized relative POSIX path."""
    if not rel or rel.startswith("/") or "\\" in rel or ":" in rel:
        return False
    parts = rel.split("/")
    return all(part not in {"", ".", ".."} for part in parts)


def _git_tracked_files(repo_root: pathlib.Path) -> frozenset[str] | None:
    """Return Git-tracked relative paths when ``repo_root`` is a Git repo."""
    if not (repo_root / ".git").exists():
        return None
    proc = subprocess.run(
        ["git", "-C", str(repo_root), "ls-files", "-z"],
        check=False,
        capture_output=True,
    )
    if proc.returncode != 0:
        return None
    return frozenset(
        tok.decode("utf-8", errors="replace")
        for tok in proc.stdout.split(b"\x00")
        if tok
    )


def _make_disk_include_resolver(
    up_file: pathlib.Path, mesa_dir: pathlib.Path
) -> collections.abc.Callable[[str], tuple[str, str] | None]:
    """Resolve ``include`` directives against ``mesa_dir``."""

    def _resolve(inc_name: str) -> tuple[str, str] | None:
        if not _is_safe_relpath(inc_name):
            return None
        candidates = [
            up_file.parent / inc_name,
            up_file.parent.parent / "private" / inc_name,
            up_file.parent.parent / "public" / inc_name,
        ]
        for mod in _port_parsers.CORE_UPSTREAM_MODULES:
            candidates.append(mesa_dir / mod / "public" / inc_name)
            candidates.append(mesa_dir / mod / "private" / inc_name)
        for cand in candidates:
            if cand.is_file():
                return (
                    cand.read_text(encoding="utf-8", errors="replace"),
                    cand.suffix,
                )
        return None

    return _resolve


def _verify_entry_flexmesa_files(
    entry: port_manifest.PortManifestEntry,
    repo_root: pathlib.Path,
    tracked: frozenset[str] | None,
    errors: list[str],
) -> None:
    up = entry.upstream_path
    if entry.status == port_manifest.PortStatus.ABSENT:
        if entry.flexmesa_files:
            errors.append(f"{up}: absent entry must not list flexmesa_files")
        if entry.routine_map_partial:
            errors.append(
                f"{up}: absent entry must not list routine_map_partial"
            )
        return
    if not entry.flexmesa_files:
        errors.append(
            f"{up}: status={entry.status.value} requires flexmesa_files"
        )
    for rel_fm in entry.flexmesa_files:
        if not _is_safe_relpath(rel_fm) or not rel_fm.startswith(
            ("crates/", "src/flexmesa/")
        ):
            errors.append(
                f"{up}: flexmesa_file {rel_fm!r} must be a safe path "
                "in crates/ or src/flexmesa/"
            )
            continue
        if not (repo_root / rel_fm).is_file():
            errors.append(f"{up}: missing flexmesa_file {rel_fm!r}")
        elif tracked is not None and rel_fm not in tracked:
            errors.append(
                f"{up}: flexmesa_file {rel_fm!r} is not tracked in git"
            )


def _verify_entry_upstream_and_routines(
    entry: port_manifest.PortManifestEntry,
    repo_root: pathlib.Path,
    mesa_dir: pathlib.Path | None,
    sym_cache: dict[str, set[str]],
    errors: list[str],
) -> None:
    up = entry.upstream_path
    if mesa_dir is not None:
        up_file = mesa_dir / up
        if up_file.is_file():
            raw_bytes = up_file.read_bytes()
            actual_lines = len(raw_bytes.splitlines())
            actual_sha = hashlib.sha256(raw_bytes).hexdigest()
            if actual_lines != entry.upstream_lines:
                errors.append(
                    f"{up}: upstream_lines={entry.upstream_lines} != "
                    f"actual {actual_lines}"
                )
            if actual_sha != entry.upstream_sha256:
                errors.append(
                    f"{up}: upstream_sha256 mismatch vs {mesa_dir.name}"
                )
            if entry.status.is_ported:
                pubs = _port_parsers.extract_fortran_public_routines(
                    raw_bytes.decode("utf-8", errors="replace"),
                    suffix=up_file.suffix,
                    include_resolver=_make_disk_include_resolver(
                        up_file, mesa_dir
                    ),
                )
                rmap = entry.routine_dict()
                for proc in pubs:
                    if proc not in rmap:
                        errors.append(
                            f"{up}: status={entry.status.value} missing "
                            f"public routine {proc!r} in routine_map"
                        )
        elif (
            entry.module not in port_manifest.BUNDLED_MODULES
            and not up.endswith((".c", ".h"))
        ):
            errors.append(
                f"{up}: missing upstream source file in {mesa_dir.name}"
            )

    keys = {k for k, _ in entry.routine_map}
    for name in entry.routine_map_partial:
        if name not in keys:
            errors.append(
                f"{up}: routine_map_partial[{name!r}] is not a routine_map key"
            )
    if not entry.status.is_ported:
        return
    allowed_files = frozenset(entry.flexmesa_files)
    for proc, target in entry.routine_map:
        if "::" not in target:
            errors.append(
                f"{up}: routine_map[{proc!r}]={target!r} must use "
                "'<flexmesa_file>::<symbol>'"
            )
            continue
        rel_fm, syms_raw = target.split("::", 1)
        if rel_fm not in allowed_files:
            errors.append(
                f"{up}: routine_map[{proc!r}] file {rel_fm!r} not in "
                "flexmesa_files"
            )
            continue
        fm_path = repo_root / rel_fm
        if fm_path.is_file():
            if rel_fm not in sym_cache:
                sym_cache[rel_fm] = _port_parsers.extract_flexmesa_symbols(
                    fm_path
                )
            avail = sym_cache[rel_fm]
            for sym in syms_raw.split("+"):
                clean_sym = sym.strip()
                if not clean_sym or clean_sym not in avail:
                    errors.append(
                        f"{up}: symbol {clean_sym!r} not found in {rel_fm}"
                    )


def _verify_entry_evidence(
    entry: port_manifest.PortManifestEntry,
    repo_root: pathlib.Path,
    tracked: frozenset[str] | None,
    passing_cases: set[str],
    errors: list[str],
) -> None:
    up = entry.upstream_path
    st = port_manifest.PortStatus
    if not entry.status.is_verified:
        if (
            entry.evidence_artifacts
            or entry.evidence_tests
            or entry.harness_cases
        ):
            errors.append(
                f"{up}: unverified status={entry.status.value} must not "
                "populate evidence_artifacts, evidence_tests, or harness_cases"
            )
        return

    if not entry.evidence_artifacts:
        errors.append(
            f"{up}: verified status={entry.status.value} requires "
            "non-empty evidence_artifacts"
        )
    for art_rel in entry.evidence_artifacts:
        if not _is_safe_relpath(art_rel) or not (
            art_rel.startswith(("benchmarks/", "tests/fixtures/"))
            or art_rel == "notes/audit/case_table.md"
        ):
            errors.append(
                f"{up}: evidence_artifact {art_rel!r} must be a safe path in "
                "benchmarks/, tests/fixtures/, or notes/audit/case_table.md"
            )
            continue
        art_path = repo_root / art_rel
        if not art_path.is_file():
            errors.append(f"{up}: missing evidence_artifact {art_rel!r}")
        elif tracked is not None and art_rel not in tracked:
            errors.append(
                f"{up}: evidence_artifact {art_rel!r} is not tracked in git"
            )
        elif not _artifact_has_provenance(art_path):
            errors.append(
                f"{up}: evidence_artifact {art_rel!r} lacks MESA "
                "26.4.1 / GENERATED provenance header"
            )

    if entry.status == st.KERNEL_REFERENCE_VECTORS:
        if not entry.evidence_tests:
            errors.append(
                f"{up}: kernel_reference_vectors requires non-empty "
                "evidence_tests"
            )
        if entry.harness_cases:
            errors.append(
                f"{up}: kernel_reference_vectors must not set harness_cases"
            )

    for test_rel in entry.evidence_tests:
        if not _is_safe_relpath(test_rel) or not test_rel.startswith(
            ("crates/", "tests/")
        ):
            errors.append(
                f"{up}: evidence_test {test_rel!r} must be a safe path in "
                "crates/ or tests/"
            )
            continue
        if not (repo_root / test_rel).is_file():
            errors.append(f"{up}: missing evidence_test {test_rel!r}")
        elif tracked is not None and test_rel not in tracked:
            errors.append(
                f"{up}: evidence_test {test_rel!r} is not tracked in git"
            )

    if entry.status == st.CASE_LEVEL_EVIDENCE:
        if not entry.harness_cases:
            errors.append(f"{up}: case_level_evidence requires harness_cases")
        for cid in entry.harness_cases:
            if cid not in passing_cases:
                errors.append(
                    f"{up}: harness_case {cid!r} is not passing against "
                    "mesa_26_4_1 in baseline_run_26_4_1.json"
                )


def _verify_base_diff_and_immutability(
    manifest: port_manifest.PortManifest,
    base_manifest: port_manifest.PortManifest,
    seen_paths: set[str],
    changed_paths: frozenset[str] | None,
    errors: list[str],
) -> None:
    st = port_manifest.PortStatus
    base_by_path = base_manifest.by_upstream_path()
    same_commit = manifest.upstream_commit == base_manifest.upstream_commit
    if same_commit and set(base_by_path) != seen_paths:
        errors.append(
            "upstream_path inventory differs from base_manifest while "
            "upstream_commit is unchanged"
        )
    for entry in manifest.entries:
        prev = base_by_path.get(entry.upstream_path)
        if prev is None:
            continue
        if same_commit and (
            entry.module != prev.module
            or entry.upstream_lines != prev.upstream_lines
            or entry.upstream_sha256 != prev.upstream_sha256
        ):
            errors.append(
                f"{entry.upstream_path}: upstream metadata "
                "(module/upstream_lines/upstream_sha256) modified relative to "
                "base_manifest"
            )
        if changed_paths is None or entry.status.rank <= prev.status.rank:
            continue
        if entry.status == st.KERNEL_REFERENCE_VECTORS:
            evidence_gate = set(entry.evidence_artifacts) | set(
                entry.evidence_tests
            )
            if not (changed_paths & evidence_gate):
                errors.append(
                    f"{entry.upstream_path}: status raised from "
                    f"{prev.status.value} to {entry.status.value} without "
                    "adding or updating evidence artifacts/tests in PR"
                )
        elif entry.status == st.CASE_LEVEL_EVIDENCE:
            case_gate = (
                set(entry.evidence_artifacts)
                | set(entry.evidence_tests)
                | {"benchmarks/history_harness/baseline_run_26_4_1.json"}
            )
            if not (changed_paths & case_gate):
                errors.append(
                    f"{entry.upstream_path}: status raised from "
                    f"{prev.status.value} to {entry.status.value} without "
                    "adding or updating case evidence in PR"
                )
        else:
            if not (changed_paths & set(entry.flexmesa_files)):
                errors.append(
                    f"{entry.upstream_path}: status raised from "
                    f"{prev.status.value} to {entry.status.value} without "
                    "modifying implementing flexmesa_files in PR"
                )


def verify_port_manifest_impl(
    manifest: port_manifest.PortManifest,
    repo_root: pathlib.Path,
    mesa_dir: pathlib.Path | None = None,
    baseline_harness_json: pathlib.Path | None = None,
    base_manifest: port_manifest.PortManifest | None = None,
    changed_paths: frozenset[str] | None = None,
) -> list[str]:
    """Run all schema, routine, evidence, and diff invariants."""
    errors: list[str] = []
    if manifest.upstream_version != port_manifest.EXPECTED_UPSTREAM_VERSION:
        errors.append(
            f"upstream_version={manifest.upstream_version!r} != "
            f"{port_manifest.EXPECTED_UPSTREAM_VERSION!r}"
        )
    if manifest.upstream_commit != port_manifest.EXPECTED_UPSTREAM_COMMIT:
        errors.append(
            f"upstream_commit={manifest.upstream_commit!r} != "
            f"{port_manifest.EXPECTED_UPSTREAM_COMMIT!r}"
        )
    if manifest.archive_md5 != port_manifest.EXPECTED_ARCHIVE_MD5:
        errors.append(
            f"archive_md5={manifest.archive_md5!r} != "
            f"{port_manifest.EXPECTED_ARCHIVE_MD5!r}"
        )

    valid_modules = frozenset(port_manifest.MODULE_ORDER)
    seen_paths: set[str] = set()
    sym_cache: dict[str, set[str]] = {}
    tracked = _git_tracked_files(repo_root)

    passing_cases: set[str] = set()
    if baseline_harness_json is not None and baseline_harness_json.is_file():
        payload: dict[str, Any] = json.loads(
            baseline_harness_json.read_text(encoding="utf-8")
        )
        for rec in payload.get("cases", payload.get("results", [])):
            if (
                rec.get("verdict") == "pass"
                and rec.get("reference_status") == "mesa_26_4_1"
            ):
                passing_cases.add(f"{rec.get('suite')}/{rec.get('case')}")

    entry_paths = [e.upstream_path for e in manifest.entries]
    if entry_paths != sorted(entry_paths):
        errors.append("[[files]] entries must be sorted by upstream_path")

    for entry in manifest.entries:
        up = entry.upstream_path
        if not _is_safe_relpath(up):
            errors.append(f"{up!r}: unsafe or non-normalized upstream_path")
        if up in seen_paths:
            errors.append(f"{up}: duplicate upstream_path")
        seen_paths.add(up)

        if entry.module not in valid_modules:
            errors.append(f"{up}: unknown module {entry.module!r}")
        expected_mod = _port_parsers.classify_upstream_relpath(up)
        if expected_mod is not None and entry.module != expected_mod:
            errors.append(
                f"{up}: module={entry.module!r} != classified {expected_mod!r}"
            )
        if entry.upstream_lines < 0:
            errors.append(f"{up}: negative upstream_lines")

        _verify_entry_flexmesa_files(entry, repo_root, tracked, errors)
        _verify_entry_upstream_and_routines(
            entry, repo_root, mesa_dir, sym_cache, errors
        )
        _verify_entry_evidence(entry, repo_root, tracked, passing_cases, errors)

    if mesa_dir is not None and mesa_dir.is_dir():
        for disk_path in sorted(mesa_dir.rglob("*")):
            if not disk_path.is_file():
                continue
            rel = disk_path.relative_to(mesa_dir).as_posix()
            if (
                _port_parsers.classify_upstream_relpath(rel) is not None
                and rel not in seen_paths
            ):
                errors.append(
                    f"{rel}: upstream MESA 26.4.1 file missing from "
                    "port_manifest.toml"
                )

    if base_manifest is not None:
        _verify_base_diff_and_immutability(
            manifest, base_manifest, seen_paths, changed_paths, errors
        )
    return errors
