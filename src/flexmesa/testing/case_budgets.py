"""Committed per-case wall-time budgets for strict harness campaigns.

``benchmarks/history_harness/case_budgets.toml`` is generated by
``scripts/audit/case_budgets.py`` from measured wall times (see the header
of that file for the recipe, the floor and the safety factors). A campaign
or a single-case run reads it with ``flexmesa harness run --case-budgets``
so that a case that needs seconds does not hold a budget sized for the
slowest case, and a case that needs hours is not cut off by a budget sized
for the typical one. A case that stops on its budget is inconclusive, as with
any time budget (``DECISIONS #59``).
"""

from __future__ import annotations

import pathlib
import tomllib

__all__ = [
    "HEADROOM_MIN",
    "JOB_LIMIT_MIN",
    "USABLE_JOB_SEC",
    "default_path",
    "load_case_budgets",
]

#: Wall-clock limit assumed for one hosted job, in minutes (``min``).
JOB_LIMIT_MIN = 330
#: Minutes of a job spent outside the case (build download, data fetch,
#: uploads); the same headroom ``case-run.yml`` adds to a case budget.
HEADROOM_MIN = 45
#: Longest case budget that fits one hosted job, in seconds (``s``).
USABLE_JOB_SEC = (JOB_LIMIT_MIN - HEADROOM_MIN) * 60


def default_path() -> pathlib.Path:
    """Return the committed budget table of a source checkout."""
    return (
        pathlib.Path(__file__).resolve().parents[3]
        / "benchmarks"
        / "history_harness"
        / "case_budgets.toml"
    )


def load_case_budgets(
    path: pathlib.Path | str,
) -> dict[tuple[str, str], float]:
    """Read the wall-time budget of each case from a budget table.

    Args:
        path: A ``case_budgets.toml`` file with ``[[cases]]`` rows carrying
            ``suite``, ``case`` and ``budget_sec``.

    Returns:
        ``{(suite, case): budget_sec}`` with every budget positive, in
        seconds (``s``).

    Raises:
        ValueError: If the file has no ``cases`` list, a row is malformed,
            a budget is not positive, or a case appears twice.
    """
    with pathlib.Path(path).open("rb") as fh:
        data = tomllib.load(fh)
    rows = data.get("cases")
    if not isinstance(rows, list) or not rows:
        raise ValueError(f"{path}: no 'cases' list")
    out: dict[tuple[str, str], float] = {}
    for row in rows:
        try:
            key = (str(row["suite"]), str(row["case"]))
            budget = float(row["budget_sec"])
        except (KeyError, TypeError, ValueError) as exc:
            raise ValueError(f"{path}: malformed row {row!r}") from exc
        if not budget > 0.0:
            raise ValueError(f"{path}: budget of {key} is not positive")
        if key in out:
            raise ValueError(f"{path}: {key[0]}/{key[1]} appears twice")
        out[key] = budget
    return out
