"""Routine inventory of upstream MESA 26.4.1 Fortran sources (`#611`).

The committed inventory ``benchmarks/dashboard/routine_inventory.json`` lists,
for every Fortran file in ``port_manifest.toml``, each routine with its line
span and the number of lines outside any routine. It is generated by
``scripts/dashboard/build_routine_inventory.py`` from the upstream source and
checked here without the source by internal-consistency rules.

Covered suffixes are those that hold Fortran text: ``.f90``, ``.F90``,
``.f``, ``.inc``, ``.incl``, ``.dek``, ``.fpp``, and ``.fypp`` (GYRE
templates, scanned unexpanded). Skipped suffixes are ``.c`` and ``.h`` (C
sources) and ``.trf`` (STELLA sources in a transformed Fortran dialect with
``;`` terminators and ``--`` comments that the routine scanner cannot read).
"""

from __future__ import annotations

import hashlib
import json
import pathlib
from typing import Any

from flexmesa.testing import _fortran_routines, port_manifest

INVENTORY_RELPATH = "benchmarks/dashboard/routine_inventory.json"
GENERATOR = "scripts/dashboard/build_routine_inventory.py"
SCHEMA_VERSION = 1
COVERED_SUFFIXES = (
    ".f90",
    ".F90",
    ".f",
    ".inc",
    ".incl",
    ".dek",
    ".fpp",
    ".fypp",
)
SKIPPED_SUFFIX_REASONS = {
    ".c": "C source",
    ".h": "C header",
    ".trf": "transformed-Fortran dialect, not parseable as Fortran",
}


def is_covered(upstream_path: str) -> bool:
    """Return ``True`` when the inventory scans ``upstream_path``."""
    return upstream_path.endswith(COVERED_SUFFIXES)


def build_inventory(
    manifest: port_manifest.PortManifest, mesa_dir: pathlib.Path
) -> dict[str, Any]:
    """Parse every covered upstream file and build the inventory payload.

    Args:
        manifest: Loaded port manifest (provides paths and SHA-256 digests).
        mesa_dir: Root of the MESA 26.4.1 source tree.

    Returns:
        JSON-serializable inventory with a provenance header and per-file
        routine lists.

    Raises:
        ValueError: If a source digest or line count disagrees with the
            manifest, or the parser reports a diagnostic for a file.
    """
    files: dict[str, Any] = {}
    skipped: dict[str, int] = {}
    problems: list[str] = []
    for entry in manifest.entries:
        up = entry.upstream_path
        if not is_covered(up):
            suffix = "." + up.rsplit(".", 1)[-1]
            skipped[suffix] = skipped.get(suffix, 0) + 1
            continue
        raw = (mesa_dir / up).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        if digest != entry.upstream_sha256:
            problems.append(f"{up}: sha256 differs from port_manifest.toml")
            continue
        lines = [
            ln.decode("utf-8", errors="replace") for ln in raw.splitlines()
        ]
        result = _fortran_routines.parse_fortran(
            lines, pathlib.PurePath(up).suffix
        )
        if result.total_lines != entry.upstream_lines:
            problems.append(
                f"{up}: {result.total_lines} lines != manifest "
                f"{entry.upstream_lines}"
            )
        problems.extend(f"{up}: {w}" for w in result.warnings)
        files[up] = {
            "sha256": digest,
            "lines": result.total_lines,
            "outside": result.outside_lines,
            "routines": [
                [r.name, r.kind, r.parent, r.first, r.last]
                for r in result.routines
            ],
        }
    if problems:
        raise ValueError("\n".join(problems))
    return {
        "header": {
            "generator": GENERATOR,
            "schema_version": SCHEMA_VERSION,
            "mesa_version": manifest.upstream_version,
            "upstream_commit": manifest.upstream_commit,
            "covered_suffixes": list(COVERED_SUFFIXES),
            "skipped_files_by_suffix": dict(sorted(skipped.items())),
            "files": len(files),
            "routines": sum(len(f["routines"]) for f in files.values()),
        },
        "files": files,
    }


def render_inventory(payload: dict[str, Any]) -> str:
    """Render the inventory deterministically, one routine per line."""
    out = [
        "{",
        '"header": ' + json.dumps(payload["header"]) + ",",
        '"files": {',
    ]
    items = list(payload["files"].items())
    for i, (path, rec) in enumerate(items):
        scalars = {k: rec[k] for k in ("sha256", "lines", "outside")}
        out.append(
            f'{json.dumps(path)}: {json.dumps(scalars)[:-1]}, "routines": ['
        )
        routines = [json.dumps(r) for r in rec["routines"]]
        out.extend(f"{r}," for r in routines[:-1])
        out.extend(routines[-1:])
        out.append("]}" + ("," if i + 1 < len(items) else ""))
    out.extend(["}", "}", ""])
    return "\n".join(out)


def load_inventory(path: pathlib.Path) -> dict[str, Any]:
    """Load a committed inventory file."""
    payload: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return payload


def validate_inventory(
    payload: dict[str, Any], manifest: port_manifest.PortManifest
) -> list[str]:
    """Check an inventory against the manifest and its own spans.

    Needs no MESA source. Verifies the provenance header, that the covered
    file set equals the manifest's Fortran files with matching digests and
    line counts, that every span lies in the file and is correctly ordered,
    and that each file's ``outside`` count equals the lines outside the
    union of its routine spans.

    Args:
        payload: Loaded inventory.
        manifest: Loaded port manifest.

    Returns:
        Error messages (empty when consistent).
    """
    errors: list[str] = []
    head = payload.get("header", {})
    if head.get("mesa_version") != manifest.upstream_version:
        errors.append("inventory mesa_version differs from the manifest")
    if head.get("upstream_commit") != manifest.upstream_commit:
        errors.append("inventory upstream_commit differs from the manifest")
    if head.get("schema_version") != SCHEMA_VERSION:
        errors.append(f"inventory schema_version != {SCHEMA_VERSION}")
    files: dict[str, Any] = payload.get("files", {})
    want = {
        e.upstream_path: e
        for e in manifest.entries
        if is_covered(e.upstream_path)
    }
    for up in sorted(set(want) - set(files)):
        errors.append(f"{up}: Fortran file missing from routine inventory")
    for up in sorted(set(files) - set(want)):
        errors.append(f"{up}: inventory file not a covered manifest file")
    for up in sorted(set(files) & set(want)):
        rec, entry = files[up], want[up]
        if rec["sha256"] != entry.upstream_sha256:
            errors.append(f"{up}: inventory sha256 differs from the manifest")
        if rec["lines"] != entry.upstream_lines:
            errors.append(f"{up}: inventory lines differ from the manifest")
        routines = [_fortran_routines.Routine(*r) for r in rec["routines"]]
        if routines != sorted(
            routines, key=lambda r: (r.first, r.last, r.name)
        ):
            errors.append(f"{up}: routines are not sorted by span")
        for r in routines:
            if not 1 <= r.first <= r.last <= rec["lines"]:
                errors.append(f"{up}: {r.name} span {r.first}-{r.last} invalid")
        covered = _fortran_routines.covered_lines(routines, rec["lines"])
        if rec["lines"] - covered != rec["outside"]:
            errors.append(f"{up}: outside-routine line count inconsistent")
    n_routines = sum(len(f["routines"]) for f in files.values())
    if head.get("routines") != n_routines or head.get("files") != len(files):
        errors.append("inventory header counts differ from the file records")
    return errors
