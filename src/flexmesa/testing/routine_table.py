"""Derived routine-level port table from the routine inventory (`#611`).

Combines ``routine_inventory.json`` (what upstream contains) with the
``routine_map`` entries of ``port_manifest.toml`` (what the port claims) to
give routines and upstream lines at the ``mapped`` evidence level, per file,
per module, and for the core engine modules together. A routine counts as
mapped when its file's ``routine_map`` names it and the mapped target passes
the ``routine_map`` gate (the key is an inventory routine and every symbol is a
function item). Entries listed in the gate's allow-list therefore do not count.

The ``oracle`` level counts a mapped routine when a test file classified
``oracle`` in ``test_taxonomy.toml`` lists its ``<upstream path>::<routine>``
id in its ``routines`` field (the per-routine oracle cover that
``test_taxonomy`` already records). The ``exercised`` level needs the coverage
job and is not computed. No status in the manifest is read as evidence of a
routine.

Each file also gets a derived status ceiling (see ``status_ceiling``) and the
table reports where the hand-set status exceeds it or sits below it. The
ceiling is reported only; nothing gates on it and no status is changed. The
backlog of unmapped routines carries failing-case attribution from
``routine_backlog``.

Outputs are ``notes/audit/routine_table.md`` and
``notes/audit/routine_table.json``, regenerated by
``scripts/dashboard/build_routine_table.py`` and compared byte for byte by its
``--check`` mode.
"""

from __future__ import annotations

import json
import pathlib
from typing import Any

from flexmesa.testing import (
    port_manifest,
    routine_backlog,
    routine_gate,
    routine_inventory,
    test_taxonomy,
)

MD_RELPATH = "notes/audit/routine_table.md"
JSON_RELPATH = "notes/audit/routine_table.json"
GENERATOR = "scripts/dashboard/build_routine_table.py"
BACKLOG_MARKDOWN_ROWS = 40
ATTRIBUTED_MARKDOWN_ROWS = 40
CEILING_MARKDOWN_ROWS = 10


def _union_lines(spans: list[tuple[int, int]]) -> int:
    """Return the number of lines in the union of ``(first, last)`` spans."""
    total = 0
    reach = 0
    for first, last in sorted(spans):
        lo = max(first, reach + 1)
        if last >= lo:
            total += last - lo + 1
        reach = max(reach, last)
    return total


def _pct(num: int, den: int) -> float:
    """Return ``100 * num / den`` rounded to one decimal (0 if ``den`` is 0)."""
    return round(100.0 * num / den, 1) if den else 0.0


def status_ceiling(
    routines: int, mapped: int, oracle: int
) -> port_manifest.PortStatus | None:
    """Return the highest status the routine evidence supports, or ``None``.

    The rule, applied to the routines of one inventory file:

    * no routines, or none mapped: ``None`` (no ceiling claim);
    * some but not all routines mapped: ``partial``;
    * all routines mapped: ``ported_unverified``;
    * all routines mapped and each also has oracle evidence:
      ``kernel_reference_vectors``.

    ``case_level_evidence`` is never a ceiling because the ``exercised`` level
    is not derived. Contained procedures count as routines, so a file is
    eligible only when they are mapped too.

    Args:
        routines: Number of inventory routines in the file.
        mapped: How many of them are mapped.
        oracle: How many of them have oracle evidence.

    Returns:
        The ceiling status, or ``None`` when the evidence makes no claim.
    """
    if routines == 0 or mapped == 0:
        return None
    if mapped < routines:
        return port_manifest.PortStatus.PARTIAL
    if oracle == routines:
        return port_manifest.PortStatus.KERNEL_REFERENCE_VECTORS
    return port_manifest.PortStatus.PORTED_UNVERIFIED


def oracle_routine_ids(repo_root: pathlib.Path) -> set[str]:
    """Return ``<upstream path>::<routine>`` ids listed by ``oracle`` tests."""
    tax = test_taxonomy.load_test_taxonomy(
        repo_root / test_taxonomy.DEFAULT_TAXONOMY_REL
    )
    return {
        rid for e in tax.entries if e.kind == "oracle" for rid in e.routines
    }


def build_table(
    manifest: port_manifest.PortManifest,
    inventory: dict[str, Any],
    repo_root: pathlib.Path,
    *,
    oracle_ids: set[str] | None = None,
    gaps: list[tuple[str, str]] | None = None,
) -> dict[str, Any]:
    """Derive the per-file, per-module, and engine routine table.

    Args:
        manifest: Loaded port manifest.
        inventory: Loaded routine inventory.
        repo_root: Repository root (to resolve mapped Rust and Python files).
        oracle_ids: ``<upstream path>::<routine>`` ids with oracle evidence;
            read from ``test_taxonomy.toml`` when ``None``.
        gaps: ``(case id, reason)`` pairs for backlog attribution; read from
            ``known_gaps.toml`` when ``None``.

    Returns:
        JSON-serializable table with ``files``, ``modules``, ``engine`` and
        ``backlog`` sections.
    """
    bad = {
        (v.upstream_path, v.routine)
        for v in routine_gate.collect_violations(manifest, inventory, repo_root)
    }
    if oracle_ids is None:
        oracle_ids = oracle_routine_ids(repo_root)
    if gaps is None:
        gaps = routine_backlog.load_gap_cases(repo_root)
    files: list[dict[str, Any]] = []
    backlog: list[dict[str, Any]] = []
    for entry in manifest.entries:
        rec = inventory["files"].get(entry.upstream_path)
        if rec is None:
            continue
        good = {
            k.lower()
            for k, _ in entry.routine_map
            if (entry.upstream_path, k) not in bad
        }
        good_oracle = {
            k.lower()
            for k, _ in entry.routine_map
            if (entry.upstream_path, k) not in bad
            and f"{entry.upstream_path}::{k}" in oracle_ids
        }
        routines = rec["routines"]
        mapped = [r for r in routines if r[0].lower() in good]
        oracle = [r for r in routines if r[0].lower() in good_oracle]
        in_routines = _union_lines([(r[3], r[4]) for r in routines])
        mapped_lines = _union_lines([(r[3], r[4]) for r in mapped])
        oracle_lines = _union_lines([(r[3], r[4]) for r in oracle])
        ceiling = status_ceiling(len(routines), len(mapped), len(oracle))
        files.append(
            {
                "upstream_path": entry.upstream_path,
                "module": entry.module,
                "status": entry.status.value,
                "upstream_lines": rec["lines"],
                "routines": len(routines),
                "routines_mapped": len(mapped),
                "lines_in_routines": in_routines,
                "lines_in_mapped_routines": mapped_lines,
                "routines_oracle": len(oracle),
                "lines_in_oracle_routines": oracle_lines,
                "lines_outside_routines": rec["outside"],
                "whole_file_ported": entry.status.is_ported,
                "ceiling": ceiling.value if ceiling else None,
            }
        )
        if (
            entry.module in port_manifest.CORE_ENGINE_MODULES
            and entry.status.value in routine_backlog.BACKLOG_STATUSES
        ):
            mapped_ids = {id(r) for r in mapped}
            backlog.extend(
                {
                    "upstream_path": entry.upstream_path,
                    "routine": r[0],
                    "kind": r[1],
                    "parent": r[2],
                    "first": r[3],
                    "last": r[4],
                    "lines": r[4] - r[3] + 1,
                }
                for r in routines
                if id(r) not in mapped_ids
            )
    routine_backlog.attribute(backlog, gaps)
    backlog.sort(
        key=lambda b: (
            -len(b["cases"]),
            -b["lines"],
            b["upstream_path"],
            b["first"],
            b["routine"],
        )
    )
    modules = {
        mod: _aggregate([f for f in files if f["module"] == mod])
        for mod in port_manifest.MODULE_ORDER
        if any(f["module"] == mod for f in files)
    }
    engine = _aggregate(
        [f for f in files if f["module"] in port_manifest.CORE_ENGINE_MODULES]
    )
    engine["modules"] = sorted(port_manifest.CORE_ENGINE_MODULES)
    return {
        "header": {
            "generator": GENERATOR,
            "mesa_version": manifest.upstream_version,
            "upstream_commit": manifest.upstream_commit,
            "evidence_levels": ["mapped", "oracle"],
            "gap_cases": len(gaps),
            "inventory": routine_inventory.INVENTORY_RELPATH,
            "files_in_table": len(files),
            "files_not_in_inventory": sum(
                1
                for e in manifest.entries
                if e.upstream_path not in inventory["files"]
            ),
        },
        "engine": engine,
        "modules": modules,
        "ceiling": _ceiling_report(files),
        "files": files,
        "backlog": backlog,
    }


def _ceiling_report(files: list[dict[str, Any]]) -> dict[str, Any]:
    """List files whose status exceeds, or could be raised to, the ceiling."""
    rank = {s.value: s.rank for s in port_manifest.PortStatus}
    exceed: list[dict[str, Any]] = []
    candidates: list[dict[str, Any]] = []
    no_claim_ported = 0
    for f in files:
        if f["ceiling"] is None:
            no_claim_ported += f["whole_file_ported"]
            continue
        if rank[f["status"]] > rank[f["ceiling"]]:
            exceed.append(f)
        elif (
            f["status"] == "partial"
            and rank[f["ceiling"]] >= rank["ported_unverified"]
        ):
            candidates.append(f)
    order = lambda f: (-f["upstream_lines"], f["upstream_path"])  # noqa: E731
    return {
        "files_exceeding_ceiling": sorted(exceed, key=order),
        "raise_candidates": sorted(candidates, key=order),
        "ported_files_without_ceiling_claim": no_claim_ported,
    }


def _aggregate(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Sum file rows into one module or group row."""
    total = sum(f["upstream_lines"] for f in rows)
    mapped_lines = sum(f["lines_in_mapped_routines"] for f in rows)
    oracle_lines = sum(f["lines_in_oracle_routines"] for f in rows)
    in_routines = sum(f["lines_in_routines"] for f in rows)
    whole = sum(f["upstream_lines"] for f in rows if f["whole_file_ported"])
    return {
        "files": len(rows),
        "routines": sum(f["routines"] for f in rows),
        "routines_mapped": sum(f["routines_mapped"] for f in rows),
        "upstream_lines": total,
        "lines_in_routines": in_routines,
        "lines_in_mapped_routines": mapped_lines,
        "routines_oracle": sum(f["routines_oracle"] for f in rows),
        "lines_in_oracle_routines": oracle_lines,
        "lines_outside_routines": sum(
            f["lines_outside_routines"] for f in rows
        ),
        "lines_in_whole_file_ported": whole,
        "pct_lines_mapped": _pct(mapped_lines, total),
        "pct_routine_lines_mapped": _pct(mapped_lines, in_routines),
        "pct_lines_oracle": _pct(oracle_lines, total),
        "pct_whole_file_ported": _pct(whole, total),
    }


def render_json(table: dict[str, Any]) -> str:
    """Render the table as deterministic JSON, one file row per line."""
    parts = {k: table[k] for k in ("header", "engine", "modules", "ceiling")}
    out = ["{"]
    for key, val in parts.items():
        out.append(f"{json.dumps(key)}: {json.dumps(val)},")
    for key in ("files", "backlog"):
        out.append(f"{json.dumps(key)}: [")
        rows = [json.dumps(r) for r in table[key]]
        out.extend(f"{r}," for r in rows[:-1])
        out.extend(rows[-1:])
        out.append("]" + ("," if key == "files" else ""))
    out.extend(["}", ""])
    return "\n".join(out)


def _mod_row(label: str, m: dict[str, Any]) -> str:
    return (
        f"| {label} | {m['files']:,} | {m['routines']:,} | "
        f"{m['routines_mapped']:,} | {m['routines_oracle']:,} | "
        f"{m['upstream_lines']:,} | {m['lines_in_routines']:,} | "
        f"{m['lines_in_mapped_routines']:,} | "
        f"{m['lines_in_oracle_routines']:,} | "
        f"{m['lines_outside_routines']:,} | {m['pct_lines_mapped']:.1f}% | "
        f"{m['pct_lines_oracle']:.1f}% | "
        f"{m['pct_whole_file_ported']:.1f}% |"
    )


def _ceiling_rows(rows: list[dict[str, Any]]) -> list[str]:
    out = [
        "| File | Status | Ceiling | Lines | Routines | Mapped | Oracle |",
        "| :--- | :--- | :--- | ---: | ---: | ---: | ---: |",
    ]
    out.extend(
        f"| `{f['upstream_path']}` | {f['status']} | "
        f"{f['ceiling']} | {f['upstream_lines']:,} | {f['routines']:,} | "
        f"{f['routines_mapped']:,} | {f['routines_oracle']:,} |"
        for f in rows[:CEILING_MARKDOWN_ROWS]
    )
    return out


def _backlog_row(i: int, b: dict[str, Any]) -> str:
    cases = ", ".join(f"`{c}`" for c in b["cases"][:3])
    if len(b["cases"]) > 3:
        cases += f" and {len(b['cases']) - 3} more"
    return (
        f"| {i} | `{b['upstream_path']}` | `{b['routine']}` | "
        f"{len(b['cases'])} | {b['lines']:,} | {b['basis'] or '-'} | "
        f"{cases or '-'} |"
    )


_BACKLOG_HEAD = [
    "| # | Upstream file | Routine | Cases | Lines | Basis | Cases named |",
    "| ---: | :--- | :--- | ---: | ---: | :--- | :--- |",
]


def render_markdown(table: dict[str, Any]) -> str:
    """Render the table as Markdown for ``notes/audit/``."""
    head = table["header"]
    eng = table["engine"]
    ceil = table["ceiling"]
    lines = [
        "# Routine-level port table (generated)",
        "",
        "<!-- GENERATED VIA scripts/dashboard/build_routine_table.py (#611). "
        "Do not edit by hand. -->",
        "",
        f"Derived from `{head['inventory']}` (MESA {head['mesa_version']}, "
        f"commit `{head['upstream_commit'][:7]}`), the `routine_map` entries "
        "of `benchmarks/dashboard/port_manifest.toml`, the oracle routine "
        "lists of `benchmarks/dashboard/test_taxonomy.toml`, and the declared "
        "gaps of `benchmarks/history_harness/known_gaps.toml`. "
        "Machine-readable "
        "copy: `notes/audit/routine_table.json`.",
        "",
        "## Evidence levels",
        "",
        "* `mapped`: the `routine_map` names the routine and the target passes "
        "the `routine_map` gate.",
        "* `oracle`: the routine is mapped and a test file classified "
        "`oracle` in the taxonomy lists its `<upstream path>::<routine>` id "
        "in its `routines` field. This is the taxonomy's own record of "
        "per-routine oracle cover; it is a listing, not a call-site check.",
        "* `exercised` (reached by a strict-pass history case) is not derived.",
        "",
        f"{head['files_not_in_inventory']} manifest files are not in the "
        "inventory (C sources and STELLA `.trf` files) and are excluded from "
        "every figure; none of them is in the core engine modules. Contained "
        "procedures are separate routines whose lines also lie inside their "
        "parent, so routine counts include both while line figures count each "
        "line once.",
        "",
        "## Core engine (`star`, `star_data`, `binary`, `astero`)",
        "",
        "| Measure | Value |",
        "| :--- | ---: |",
        f"| Upstream lines | {eng['upstream_lines']:,} |",
        f"| Lines in mapped routines | {eng['lines_in_mapped_routines']:,} |",
        f"| Lines in routines with oracle evidence | "
        f"{eng['lines_in_oracle_routines']:,} |",
        f"| Line-weighted mapped fraction | {eng['pct_lines_mapped']:.1f}% |",
        f"| Line-weighted oracle fraction | {eng['pct_lines_oracle']:.1f}% |",
        f"| Whole-file ported fraction (existing headline) | "
        f"{eng['pct_whole_file_ported']:.1f}% |",
        f"| Mapped fraction of routine lines only | "
        f"{eng['pct_routine_lines_mapped']:.1f}% |",
        f"| Routines (mapped / total) | {eng['routines_mapped']:,} / "
        f"{eng['routines']:,} |",
        f"| Routines with oracle evidence | {eng['routines_oracle']:,} |",
        "",
        "The fractions answer different questions. The whole-file figure "
        "counts every line of a file whose hand-set status is ported; the "
        "line-weighted figures count only the lines of routines that carry "
        "the named evidence. Neither is a statement about agreement with "
        "MESA.",
        "",
        "## Per module",
        "",
        "| Module | Files | Routines | Mapped | Oracle | Upstream lines | In "
        "routines | In mapped | In oracle | Outside routines | Lines mapped | "
        "Lines oracle | Whole-file ported |",
        "| :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | "
        "---: | ---: | ---: | ---: |",
    ]
    lines.extend(_mod_row(f"`{m}`", row) for m, row in table["modules"].items())
    lines += [
        "",
        "## Derived status ceiling",
        "",
        "The ceiling is the highest status that the routine evidence of a "
        "file supports. The rule, over the file's inventory routines:",
        "",
        "* none mapped, or no routines: no ceiling claim;",
        "* some but not all mapped: `partial`;",
        "* all mapped: `ported_unverified`;",
        "* all mapped and each has oracle evidence: "
        "`kernel_reference_vectors`.",
        "",
        "`case_level_evidence` is never a ceiling because the `exercised` "
        "level is not derived. Contained procedures count as routines. A "
        "ceiling over the hand-set status is a candidate for review, not a "
        "raise: the table reads no status as evidence and changes none, and "
        "nothing gates on this section.",
        "",
        f"### Hand-set status above the ceiling "
        f"({len(ceil['files_exceeding_ceiling']):,} files)",
        "",
        "Files whose status needs more than the routine evidence gives. Files "
        "with no ceiling claim are not listed; "
        f"{ceil['ported_files_without_ceiling_claim']:,} files with a ported "
        "status have no ceiling claim. Largest ten:",
        "",
        *_ceiling_rows(ceil["files_exceeding_ceiling"]),
        "",
        f"### `partial` files with every routine mapped "
        f"({len(ceil['raise_candidates']):,} files)",
        "",
        "Candidates for a reviewed raise to `ported_unverified`. Largest ten:",
        "",
        *_ceiling_rows(ceil["raise_candidates"]),
        "",
        "## Per file (files with a non-absent status or a mapped routine)",
        "",
        "| File | Module | Status | Ceiling | Lines | Routines | Mapped | "
        "Oracle | In routines | In mapped | In oracle | Outside |",
        "| :--- | :--- | :--- | :--- | ---: | ---: | ---: | ---: | ---: | "
        "---: | ---: | ---: |",
    ]
    for f in table["files"]:
        if f["status"] == "absent" and not f["routines_mapped"]:
            continue
        lines.append(
            f"| `{f['upstream_path']}` | `{f['module']}` | {f['status']} | "
            f"{f['ceiling'] or '-'} | "
            f"{f['upstream_lines']:,} | {f['routines']:,} | "
            f"{f['routines_mapped']:,} | {f['routines_oracle']:,} | "
            f"{f['lines_in_routines']:,} | "
            f"{f['lines_in_mapped_routines']:,} | "
            f"{f['lines_in_oracle_routines']:,} | "
            f"{f['lines_outside_routines']:,} |"
        )
    backlog = table["backlog"]
    attributed = [b for b in backlog if b["cases"]]
    lines += [
        "",
        "## Backlog of unmapped core-engine routines",
        "",
        f"{len(backlog):,} routines in core-engine files with status `stub`, "
        "`partial`, or `absent` have no gate-checked `routine_map` entry "
        f"({sum(b['lines'] for b in backlog):,} routine lines, with contained "
        "procedures counted inside their parents as well). Some may already "
        "be implemented without a map entry; the table cannot tell.",
        "",
        "### How cases are attributed, and its limits",
        "",
        f"The {head['gap_cases']} declared gaps in `known_gaps.toml` are the "
        "non-passing cases. A routine is attributed to a case only when that "
        "case's gap `reason` names the routine (an identifier equal to its "
        "Fortran name, at least eight characters or containing an "
        "underscore), basis `routine`, or names its upstream file, basis "
        "`file`, which attributes every unmapped routine of that file. A "
        "name found in several backlog files counts only when the reason "
        "also names one of the files. No other signal is used: the "
        "unsupported-controls report and `extras_status.toml` name controls "
        "and cases but no routines, so a missing control or an unported "
        "extras hook cannot be tied to a routine mechanically. Most gap "
        "reasons name neither a routine nor a file, so most routines are "
        "unattributed. Unattributed does not mean unneeded, and the case "
        "counts are lower bounds. Rows are sorted by number of cases named, "
        "then lines.",
        "",
        f"{len(attributed):,} backlog routines are attributed to at least "
        "one case.",
        "",
        "### Attributed routines",
        "",
        *_BACKLOG_HEAD,
    ]
    lines.extend(
        _backlog_row(i, b)
        for i, b in enumerate(attributed[:ATTRIBUTED_MARKDOWN_ROWS], start=1)
    )
    if not attributed:
        lines.append("| - | none | - | 0 | 0 | - | - |")
    lines += [
        "",
        "### Largest unattributed routines",
        "",
        f"The {BACKLOG_MARKDOWN_ROWS} largest backlog routines with no case "
        "named. The full list is in the JSON file.",
        "",
        *_BACKLOG_HEAD,
    ]
    unattributed = [b for b in backlog if not b["cases"]]
    unattributed.sort(
        key=lambda b: (-b["lines"], b["upstream_path"], b["first"])
    )
    lines.extend(
        _backlog_row(i, b)
        for i, b in enumerate(unattributed[:BACKLOG_MARKDOWN_ROWS], start=1)
    )
    lines.append("")
    return "\n".join(lines)


def render_outputs(repo_root: pathlib.Path) -> dict[pathlib.Path, str]:
    """Return the expected content of the table files for ``repo_root``."""
    manifest = port_manifest.load_port_manifest(
        repo_root / "benchmarks" / "dashboard" / "port_manifest.toml"
    )
    inventory = routine_inventory.load_inventory(
        repo_root / routine_inventory.INVENTORY_RELPATH
    )
    table = build_table(manifest, inventory, repo_root)
    return {
        repo_root / MD_RELPATH: render_markdown(table),
        repo_root / JSON_RELPATH: render_json(table),
    }
