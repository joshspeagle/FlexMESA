LEVELS = ("full", "partial", "na", "unmapped", "oracle_exact", "oracle_print")


def _union_lines(spans: list[tuple[int, int]]) -> int:
    """Return the number of lines in the union of ``(first, last)`` spans."""
    total = 0
    reach = 0
    for first, last in sorted(spans):
        lo = max(first, reach + 1)
        if last >= lo:
            total += last - lo + 1
        reach = max(reach, last)
    return total


def own_lines(routines: list[list[Any]]) -> list[int]:
    """Return each routine's own line count (span minus contained spans).

    Args:
        routines: Inventory rows ``[name, kind, parent, first, last]`` sorted
            by span, as the inventory stores them.

    Returns:
        One count per row: its span length less the union of the spans of the
        rows contained in it. Rows with an identical span are nested in
        inventory order.
    """
    out: list[int] = []
    for i, r in enumerate(routines):
        inner = [
            (c[3], c[4])
            for c in routines[i + 1 :]
            if c[3] <= r[4] and c[4] <= r[4]
        ]
        out.append(r[4] - r[3] + 1 - _union_lines(inner))
    return out


def _pct(num: int, den: int) -> float:
    """Return ``100 * num / den`` rounded to one decimal (0 if ``den`` is 0)."""
    return round(100.0 * num / den, 1) if den else 0.0


def status_ceiling(
    routines: int, mapped: int, oracle: int, partial: int = 0
) -> port_manifest.PortStatus | None:
    """Return the highest status the routine evidence supports, or ``None``.

    The rule, applied to the applicable routines of one inventory file (those
    not declared not applicable) with ``mapped`` counting full mappings only:

    * no routines, or none mapped in full or in part: ``None``;
    * any routine partial or unmapped: ``partial``;
    * all routines mapped in full: ``ported_unverified``;
    * all routines mapped in full and each also has exact (0-ULP) oracle
      evidence: ``kernel_reference_vectors``. Print-precision oracles do not
      count toward this ceiling.

    ``case_level_evidence`` is never a ceiling because the ``exercised`` level
    is not derived. Contained procedures count as routines, so a file is
    eligible only when they are mapped too.

    Args:
        routines: Number of applicable inventory routines in the file.
        mapped: How many of them are mapped in full.
        oracle: How many of them have exact (0-ULP) oracle evidence.
        partial: How many of them are mapped in part.

    Returns:
        The ceiling status, or ``None`` when the evidence makes no claim.
    """
    if routines == 0 or mapped + partial == 0:
        return None
    if mapped < routines:
        return port_manifest.PortStatus.PARTIAL
    if oracle == routines:
        return port_manifest.PortStatus.KERNEL_REFERENCE_VECTORS
    return port_manifest.PortStatus.PORTED_UNVERIFIED


def _credited(keys: list[str], routines: list[list[Any]]) -> set[int]:
    """Return ``id()`` of the routine rows that unambiguous keys name.

    A bare key credits the one routine of that name; a ``parent::name`` key
    credits only the contained procedure it names. A key that matches no
    routine or several credits nothing (the gate reports it).
    """
    out: set[int] = set()
    for key in keys:
        hits = routine_gate.match_routines(key, routines)
        if len(hits) == 1:
            out.add(id(hits[0]))
    return out


def oracle_claims(
    repo_root: pathlib.Path, manifest: port_manifest.PortManifest
) -> list[_oracle_provenance.ClaimResult]:
    """Evaluate every ``[[tests.oracles]]`` claim of the test taxonomy."""
    tax = test_taxonomy.load_test_taxonomy(
        repo_root / test_taxonomy.DEFAULT_TAXONOMY_REL
    )
    targets: dict[str, set[str]] = {}
    for entry in manifest.entries:
        for key, target in entry.routine_map:
            targets[f"{entry.upstream_path}::{key}"] = (
                _routine_call_gate.parse_target_symbols(target)
            )
    records = [(e.path, e.oracles) for e in tax.entries if e.kind == "oracle"]
    return _oracle_provenance.evaluate(repo_root, records, targets)


def oracle_routine_ids(
    repo_root: pathlib.Path, manifest: port_manifest.PortManifest
) -> tuple[set[str], set[str]]:
    """Return ``(exact ids, print-only ids)`` of verified oracle routines."""
    return _oracle_provenance.verified_ids(oracle_claims(repo_root, manifest))


def build_table(
    manifest: port_manifest.PortManifest,
    inventory: dict[str, Any],
    repo_root: pathlib.Path,
    *,
    oracle_ids: tuple[set[str], set[str]] | None = None,
    gaps: list[tuple[str, str]] | None = None,
    na_entries: list[routine_na.NotApplicable] | None = None,
) -> dict[str, Any]:
    """Derive the per-file, per-module, and engine routine table.

    Args:
        manifest: Loaded port manifest.
        inventory: Loaded routine inventory.
        repo_root: Repository root (to resolve mapped Rust and Python files).
        oracle_ids: ``(exact, print-only)`` sets of verified
            ``<upstream path>::<routine>`` ids; evaluated from
            ``test_taxonomy.toml`` when ``None``.
        gaps: ``(case id, reason)`` pairs for backlog attribution; read from
            ``known_gaps.toml`` when ``None``.
        na_entries: Routines declared not applicable; read from
            ``port_status_na.toml`` (none when absent) when ``None``.

    Returns:
        JSON-serializable table with ``files``, ``modules``, ``engine`` and
        ``backlog`` sections.
    """
    bad = {
        (v.upstream_path, v.routine)
        for v in routine_gate.collect_violations(manifest, inventory, repo_root)
    }
    if oracle_ids is None:
        oracle_ids = oracle_routine_ids(repo_root, manifest)
    exact_ids, print_ids = oracle_ids
    if gaps is None:
        gaps = routine_backlog.load_gap_cases(repo_root)
    if na_entries is None:
        na_entries = routine_na.load_na(repo_root / routine_na.NA_RELPATH)
    files: list[dict[str, Any]] = []
    backlog: list[dict[str, Any]] = []
    for entry in manifest.entries:
        rec = inventory["files"].get(entry.upstream_path)
        if rec is None:
            continue
        usable = [
            k
            for k, _ in entry.routine_map
            if (entry.upstream_path, k) not in bad
        ]
        routines = rec["routines"]
        own = dict(zip(map(id, routines), own_lines(routines), strict=True))
        na_ids = routine_na.na_row_ids(
            na_entries, entry.upstream_path, routines
        )
        mapped_ids = _credited(usable, routines) - na_ids
        partial_ids = _credited(list(entry.routine_map_partial), routines)
        partial_ids &= mapped_ids
        full_ids = mapped_ids - partial_ids
        exact_here = _credited(
            [k for k in usable if f"{entry.upstream_path}::{k}" in exact_ids],
            routines,
        )
        exact_here &= full_ids
        print_here = _credited(
            [k for k in usable if f"{entry.upstream_path}::{k}" in print_ids],
            routines,
        )
        print_here &= full_ids
        print_here -= exact_here
        levels = {
            "full": full_ids,
            "partial": partial_ids,
            "na": na_ids,
            "oracle_exact": exact_here,
            "oracle_print": print_here,
        }
        unmapped_ids = {id(r) for r in routines} - mapped_ids - na_ids
        levels["unmapped"] = unmapped_ids
        count = {k: len(v) for k, v in levels.items()}
        lines = {k: sum(own[i] for i in v) for k, v in levels.items()}
        n_applicable = len(routines) - count["na"]
        ceiling = status_ceiling(
            n_applicable,
            count["full"],
            count["oracle_exact"],
            count["partial"],
        )
        row: dict[str, Any] = {
            "upstream_path": entry.upstream_path,
            "module": entry.module,
            "status": entry.status.value,
            "upstream_lines": rec["lines"],
            "routines": len(routines),
            "lines_in_routines": sum(own.values()),
            "lines_outside_routines": rec["outside"],
            "whole_file_ported": entry.status.is_ported,
            "ceiling": ceiling.value if ceiling else None,
        }
        for level in LEVELS:
            row[f"routines_{level}"] = count[level]
            row[f"lines_{level}"] = lines[level]
        files.append(row)
        if (
            entry.module in port_manifest.CORE_ENGINE_MODULES
            and entry.status.value in routine_backlog.BACKLOG_STATUSES
        ):
            backlog.extend(
                {
                    "upstream_path": entry.upstream_path,
                    "routine": r[0],
                    "kind": r[1],
                    "parent": r[2],
                    "first": r[3],
                    "last": r[4],
                    "lines": own[id(r)],
                }
                for r in routines
                if id(r) in unmapped_ids
            )
    routine_backlog.attribute(backlog, gaps)
    backlog.sort(
        key=lambda b: (
            -len(b["cases"]),
            -b["lines"],
            b["upstream_path"],
            b["first"],
            b["routine"],
        )
    )
    modules = {
        mod: _aggregate([f for f in files if f["module"] == mod])
        for mod in port_manifest.MODULE_ORDER
        if any(f["module"] == mod for f in files)
    }
    engine = _aggregate(
        [f for f in files if f["module"] in port_manifest.CORE_ENGINE_MODULES]
    )
    engine["modules"] = sorted(port_manifest.CORE_ENGINE_MODULES)
    return {
        "header": {
            "generator": GENERATOR,
            "mesa_version": manifest.upstream_version,
            "upstream_commit": manifest.upstream_commit,
            "evidence_levels": list(LEVELS),
            "na_declared": len(na_entries),
            "gap_cases": len(gaps),
            "inventory": routine_inventory.INVENTORY_RELPATH,
            "files_in_table": len(files),
            "files_not_in_inventory": sum(
                1
                for e in manifest.entries
                if e.upstream_path not in inventory["files"]
            ),
        },
        "engine": engine,
        "modules": modules,
        "ceiling": _ceiling_report(files),
        "files": files,
        "backlog": backlog,
    }


def _ceiling_report(files: list[dict[str, Any]]) -> dict[str, Any]:
    """List files whose status exceeds, or could be raised to, the ceiling."""
    rank = {s.value: s.rank for s in port_manifest.PortStatus}
    exceed: list[dict[str, Any]] = []
    candidates: list[dict[str, Any]] = []
    no_claim_ported = 0
    for f in files:
        if f["ceiling"] is None:
            no_claim_ported += f["whole_file_ported"]
            continue
        if rank[f["status"]] > rank[f["ceiling"]]:
            exceed.append(f)
        elif (
            f["status"] == "partial"
            and rank[f["ceiling"]] >= rank["ported_unverified"]
        ):
            candidates.append(f)
    order = lambda f: (-f["upstream_lines"], f["upstream_path"])  # noqa: E731
    return {
        "files_exceeding_ceiling": sorted(exceed, key=order),
        "raise_candidates": sorted(candidates, key=order),
        "ported_files_without_ceiling_claim": no_claim_ported,
    }


def _aggregate(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Sum file rows into one module or group row."""
    total = sum(f["upstream_lines"] for f in rows)
    out: dict[str, Any] = {
        "files": len(rows),
        "routines": sum(f["routines"] for f in rows),
        "upstream_lines": total,
        "lines_in_routines": sum(f["lines_in_routines"] for f in rows),
        "lines_outside_routines": sum(
            f["lines_outside_routines"] for f in rows
        ),
    }
    for level in LEVELS:
        out[f"routines_{level}"] = sum(f[f"routines_{level}"] for f in rows)
        out[f"lines_{level}"] = sum(f[f"lines_{level}"] for f in rows)
    whole = sum(f["upstream_lines"] for f in rows if f["whole_file_ported"])
    applicable = total - out["lines_na"]
    out["lines_in_whole_file_ported"] = whole
    out["pct_lines_full"] = _pct(out["lines_full"], total)
    out["pct_lines_partial"] = _pct(out["lines_partial"], total)
    out["pct_lines_na"] = _pct(out["lines_na"], total)
    out["pct_lines_full_excl_na"] = _pct(out["lines_full"], applicable)
    out["pct_lines_partial_excl_na"] = _pct(out["lines_partial"], applicable)
    out["pct_lines_oracle_exact"] = _pct(out["lines_oracle_exact"], total)
    out["pct_lines_oracle_print"] = _pct(out["lines_oracle_print"], total)
    out["pct_whole_file_ported"] = _pct(whole, total)
    return out


def render_json(table: dict[str, Any]) -> str:
    """Render the table as deterministic JSON, one file row per line."""
    parts = {k: table[k] for k in ("header", "engine", "modules", "ceiling")}
    out = ["{"]
    for key, val in parts.items():
        out.append(f"{json.dumps(key)}: {json.dumps(val)},")
    for key in ("files", "backlog"):
        out.append(f"{json.dumps(key)}: [")
        rows = [json.dumps(r) for r in table[key]]
        out.extend(f"{r}," for r in rows[:-1])
        out.extend(rows[-1:])
        out.append("]" + ("," if key == "files" else ""))
    out.extend(["}", ""])
    return "\n".join(out)


def _mod_row(label: str, m: dict[str, Any]) -> str:
    return (
        f"| {label} | {m['files']:,} | {m['routines']:,} | "
        f"{m['routines_full']:,} | {m['routines_partial']:,} | "
        f"{m['routines_na']:,} | {m['routines_unmapped']:,} | "
        f"{m['routines_oracle_exact']:,} / {m['routines_oracle_print']:,} | "
        f"{m['upstream_lines']:,} | "
        f"{m['lines_full']:,} | {m['lines_partial']:,} | "
        f"{m['lines_na']:,} | {m['lines_unmapped']:,} | "
        f"{m['lines_outside_routines']:,} | {m['pct_lines_full']:.1f}% | "
        f"{m['pct_lines_partial']:.1f}% | "
        f"{m['pct_lines_full_excl_na']:.1f}% | "
        f"{m['pct_lines_oracle_exact']:.1f}% / "
        f"{m['pct_lines_oracle_print']:.1f}% | "
        f"{m['pct_whole_file_ported']:.1f}% |"
    )


def _ceiling_rows(rows: list[dict[str, Any]]) -> list[str]:
    out = [
        "| File | Status | Ceiling | Lines | Routines | Full | Partial | "
        "N/A | Oracle (exact / print) |",
        "| :--- | :--- | :--- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    out.extend(
        f"| `{f['upstream_path']}` | {f['status']} | "
        f"{f['ceiling']} | {f['upstream_lines']:,} | {f['routines']:,} | "
        f"{f['routines_full']:,} | {f['routines_partial']:,} | "
        f"{f['routines_na']:,} | "
        f"{f['routines_oracle_exact']:,} / {f['routines_oracle_print']:,} |"
        for f in rows[:CEILING_MARKDOWN_ROWS]
    )
    return out


def _backlog_row(i: int, b: dict[str, Any]) -> str:
    cases = ", ".join(f"`{c}`" for c in b["cases"][:3])
    if len(b["cases"]) > 3:
        cases += f" and {len(b['cases']) - 3} more"
    return (
        f"| {i} | `{b['upstream_path']}` | `{b['routine']}` | "
        f"{len(b['cases'])} | {b['lines']:,} | {b['basis'] or '-'} | "
        f"{cases or '-'} |"
    )


