"""Derived routine-level port table from the routine inventory (`#611`).

Combines ``routine_inventory.json`` (what upstream contains) with the
``routine_map`` entries of ``port_manifest.toml`` (what the port claims) to
give routines and upstream lines per file, per module, and for the core engine
modules together. Every routine is at exactly one of four levels:

* ``full``: the file's ``routine_map`` names it, the mapped target passes the
  ``routine_map`` gate (the key is an inventory routine and every symbol is a
  function item), and it is not listed in ``routine_map_partial``;
* ``partial``: mapped as above and listed in the file's
  ``routine_map_partial`` (the Rust counterpart implements only part of it);
* ``na``: declared not applicable to a Rust port in ``port_status_na.toml``
  (see ``routine_na``). It is never counted as mapped and stays in every
  denominator; fractions are given both with and without those lines;
* ``unmapped``: none of the above.

Lines are credited to a routine for its own lines only: its span minus the
spans of the procedures contained in it. A contained procedure is credited
only when it is itself mapped (by bare name where that is unambiguous, or as
``parent::name``). The own lines of all routines of a file plus its lines
outside any routine therefore equal the file's line count.

The oracle levels count a fully mapped routine only through a verified
``[[tests.oracles]]`` entry of a test classified ``oracle`` in
``test_taxonomy.toml``, whose expected values trace to a committed MESA
``26.4.1`` artifact (``_oracle_provenance``, `DECISIONS #80`):
``oracle_exact`` when some verified entry compares at 0 ULP, otherwise
``oracle_print`` when a verified entry compares within a stated tolerance
against printed MESA values. The ``exercised`` level needs the coverage job
and is not computed. No status in the manifest is read as evidence of a
routine.

Each file also gets a derived status ceiling (see ``status_ceiling``) from
full mappings only, and the table reports where the hand-set status exceeds it
or sits below it. The ceiling is reported only; nothing gates on it and no
status is changed. The backlog of unmapped routines carries failing-case
attribution from ``routine_backlog``.

Outputs are ``notes/audit/routine_table.md`` and
``notes/audit/routine_table.json``, regenerated by
``scripts/dashboard/build_routine_table.py`` and compared byte for byte by its
``--check`` mode.
"""

